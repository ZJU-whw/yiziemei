CREATE FUNCTION ORA_NEXT_DAY(P_VALUE DATETIME(6), P_WEEKDAY VARCHAR(20))
RETURNS DATETIME(6)
DETERMINISTIC
NO SQL
BEGIN
    DECLARE V_TARGET_DAY TINYINT;

    SET V_TARGET_DAY = CASE UPPER(TRIM(P_WEEKDAY))
        WHEN 'SUNDAY' THEN 1 WHEN 'SUN' THEN 1 WHEN '1' THEN 1
        WHEN 'MONDAY' THEN 2 WHEN 'MON' THEN 2 WHEN '2' THEN 2
        WHEN 'TUESDAY' THEN 3 WHEN 'TUE' THEN 3 WHEN '3' THEN 3
        WHEN 'WEDNESDAY' THEN 4 WHEN 'WED' THEN 4 WHEN '4' THEN 4
        WHEN 'THURSDAY' THEN 5 WHEN 'THU' THEN 5 WHEN '5' THEN 5
        WHEN 'FRIDAY' THEN 6 WHEN 'FRI' THEN 6 WHEN '6' THEN 6
        WHEN 'SATURDAY' THEN 7 WHEN 'SAT' THEN 7 WHEN '7' THEN 7
        ELSE NULL
    END;

    IF P_VALUE IS NULL OR V_TARGET_DAY IS NULL THEN
        RETURN NULL;
    END IF;

    RETURN TIMESTAMPADD(
        DAY,
        MOD(V_TARGET_DAY - DAYOFWEEK(P_VALUE) + 6, 7) + 1,
        P_VALUE
    );
END$$

DROP PROCEDURE IF EXISTS ORA_RAISE_APPLICATION_ERROR$$

CREATE PROCEDURE ORA_RAISE_APPLICATION_ERROR(
    IN P_ERROR_NUMBER INT,
    IN P_MESSAGE LONGTEXT
)
BEGIN
    DECLARE V_MESSAGE VARCHAR(128);

    SET V_MESSAGE = LEFT(
        CONCAT('[ORA-', ABS(P_ERROR_NUMBER), '] ', COALESCE(P_MESSAGE, '')),
        128
    );
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = V_MESSAGE;
END$$

DROP FUNCTION IF EXISTS SEQ_NEXTVAL$$

CREATE FUNCTION SEQ_NEXTVAL(P_SEQ_NAME VARCHAR(100))
RETURNS BIGINT
NOT DETERMINISTIC
MODIFIES SQL DATA
BEGIN
    INSERT INTO sys_sequence (SEQ_NAME, SEQ_VALUE)
    VALUES (UPPER(P_SEQ_NAME), LAST_INSERT_ID(1))
    ON DUPLICATE KEY UPDATE
        SEQ_VALUE = LAST_INSERT_ID(SEQ_VALUE + 1);

    RETURN LAST_INSERT_ID();
END$$

