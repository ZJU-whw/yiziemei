DROP FUNCTION IF EXISTS ORA_CONCAT$$

CREATE FUNCTION ORA_CONCAT(P_LEFT LONGTEXT, P_RIGHT LONGTEXT)
RETURNS LONGTEXT
DETERMINISTIC
NO SQL
RETURN NULLIF(CONCAT(IFNULL(P_LEFT, ''), IFNULL(P_RIGHT, '')), '')$$

DROP FUNCTION IF EXISTS ORA_REGEXP_SUBSTR$$

CREATE FUNCTION ORA_REGEXP_SUBSTR(
    P_EXPR LONGTEXT,
    P_PATTERN LONGTEXT,
    P_POSITION INT,
    P_OCCURRENCE INT,
    P_MATCH_TYPE VARCHAR(10),
    P_SUBEXPR INT
)
RETURNS LONGTEXT
DETERMINISTIC
NO SQL
BEGIN
    DECLARE V_FULL_MATCH LONGTEXT;

    SET V_FULL_MATCH = REGEXP_SUBSTR(
        P_EXPR,
        P_PATTERN,
        P_POSITION,
        P_OCCURRENCE,
        P_MATCH_TYPE
    );
    IF V_FULL_MATCH IS NULL OR P_SUBEXPR < 0 OR P_SUBEXPR > 9 THEN
        RETURN NULL;
    END IF;
    IF P_SUBEXPR = 0 THEN
        RETURN V_FULL_MATCH;
    END IF;

    RETURN REGEXP_REPLACE(
        V_FULL_MATCH,
        P_PATTERN,
        CONCAT('$', P_SUBEXPR),
        1,
        1,
        P_MATCH_TYPE
    );
END$$

DROP FUNCTION IF EXISTS ORA_MEDIAN$$

CREATE FUNCTION ORA_MEDIAN(P_VALUES JSON)
RETURNS DECIMAL(65,30)
DETERMINISTIC
CONTAINS SQL
BEGIN
    DECLARE V_RESULT DECIMAL(65,30);

    IF P_VALUES IS NULL OR JSON_LENGTH(P_VALUES) = 0 THEN
        RETURN NULL;
    END IF;

    WITH BJTS_VALUES AS (
        SELECT V_VALUE
          FROM JSON_TABLE(
                   P_VALUES,
                   '$[*]' COLUMNS (
                       V_VALUE DECIMAL(65,30) PATH '$'
                           NULL ON EMPTY NULL ON ERROR
                   )
               ) AS J
         WHERE V_VALUE IS NOT NULL
    ),
    BJTS_RANKED AS (
        SELECT V_VALUE,
               ROW_NUMBER() OVER (ORDER BY V_VALUE) AS V_ROW_NO,
               COUNT(*) OVER () AS V_ROW_COUNT
          FROM BJTS_VALUES
    )
    SELECT AVG(V_VALUE)
      INTO V_RESULT
      FROM BJTS_RANKED
     WHERE V_ROW_NO IN (
         FLOOR((V_ROW_COUNT + 1) / 2),
         FLOOR((V_ROW_COUNT + 2) / 2)
     );

    RETURN V_RESULT;
END$$

DROP FUNCTION IF EXISTS ORA_SPLIT_JSON$$

CREATE FUNCTION ORA_SPLIT_JSON(P_VALUE LONGTEXT, P_DELIMITER VARCHAR(4000))
RETURNS JSON
DETERMINISTIC
NO SQL
BEGIN
    DECLARE V_RESULT JSON;
    DECLARE V_REST LONGTEXT;
    DECLARE V_POSITION INT;
    DECLARE V_TOKEN LONGTEXT;

    SET V_RESULT = JSON_ARRAY();
    SET V_REST = P_VALUE;
    SET P_DELIMITER = COALESCE(NULLIF(P_DELIMITER, ''), ',');

    WHILE V_REST IS NOT NULL AND V_REST <> '' DO
        SET V_POSITION = LOCATE(P_DELIMITER, V_REST);
        IF V_POSITION = 0 THEN
            SET V_TOKEN = V_REST;
            SET V_REST = NULL;
        ELSE
            SET V_TOKEN = LEFT(V_REST, V_POSITION - 1);
            SET V_REST = SUBSTRING(
                V_REST,
                V_POSITION + CHAR_LENGTH(P_DELIMITER)
            );
        END IF;

        IF V_TOKEN IS NOT NULL AND V_TOKEN <> '' THEN
            SET V_RESULT = JSON_ARRAY_APPEND(V_RESULT, '$', V_TOKEN);
        END IF;
    END WHILE;

    RETURN V_RESULT;
END$$

