        INTO LN_SBHS, LN_SB_CKE_HIS, LN_SB_CKE_CUR, 
             LN_SB_ZZS_HIS, LN_SB_ZZS_CUR, LN_ZT_ZZS_HIS, LN_ZT_ZZS_CUR, LN_SH_ZZS_HIS, LN_SH_ZZS_CUR, LN_BY_ZZS_HIS, LN_BY_ZZS_CUR
        FROM (SELECT B.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,B.MTSBZ,B.BYTSBZ,C.LCSLID_FS,
                     B.MYLAJ * CASE WHEN TRIM(C.LCSLID_FS) IS NULL THEN 1  
                                    WHEN A.SNBL_MDTSE=0 THEN 1
                                    WHEN A.SNBL_MDTSE>0 AND B.BYTSBZ='Y' THEN 0
                                    ELSE 1 - A.SNBL_MDTSE / A.ZY_MDTSE 
                               END AS MYLAJ,
                     B.TSE   * CASE WHEN TRIM(C.LCSLID_FS) IS NULL THEN 1  
                                    WHEN A.SNBL_MDTSE=0 THEN 1
                                    WHEN A.SNBL_MDTSE>0 AND B.BYTSBZ='Y' THEN 0
                                    ELSE 1 - A.SNBL_MDTSE / A.ZY_MDTSE 
                               END AS TSE
                FROM CKTS_LC_SHXX A
               INNER JOIN CKTS_SB_MTS_CKMX B ON B.LCSLID=A.LCSLID AND B.CHBZ='N' AND B.CKTMSYWLXDMJH LIKE '%WL%'
                LEFT JOIN (SELECT DISTINCT LCSLID_FS FROM CKTS_LC_YWHZXX S) C ON C.LCSLID_FS=A.LCSLID_FS
               WHERE A.TSSWJG_DM=V_SWCODE
                 AND A.QDSJ<LD_NEXTMONTH
                 AND A.LCJSRQ>=LD_THISYEAR) T;

      INSERT INTO TJBB_DT_B02105 (SSNY, BBLC, SWJGDM, SBHS, 
                SBLJ_TSCKE_HIS, SBLJ_TSCKE_YEAR, SBLJ_TMSE_HIS,  SBLJ_TMSE_YEAR, 
                SHLJ_TMSE_HIS,  SHLJ_TMSE_YEAR, SHBY_TMSE_HIS,  SHBY_TMSE_YEAR, SHZT_TMSE_HIS,  SHZT_TMSE_YEAR, 
                SPTK_TKE_HIS,   SPTK_TKE_YEAR, YSGK_TKE, GKBL_TKE_HIS,   GKBL_TKE_YEAR)
         SELECT LC_THISMONTH, '01', V_SWCODE, LN_SBHS, 
                LN_SB_CKE_HIS, LN_SB_CKE_CUR, LN_SB_ZZS_HIS, LN_SB_ZZS_CUR, 
                LN_SH_ZZS_HIS, LN_SH_ZZS_CUR, LN_BY_ZZS_HIS, LN_BY_ZZS_CUR, LN_ZT_ZZS_HIS, LN_ZT_ZZS_CUR, 
                LN_SH_ZZS_HIS, LN_SH_ZZS_CUR, LN_SH_ZZS_HIS + LN_SH_ZZS_CUR, LN_SH_ZZS_HIS, LN_SH_ZZS_CUR
;
      COMMIT;
    END;
         
