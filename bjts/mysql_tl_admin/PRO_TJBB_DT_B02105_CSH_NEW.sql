        FROM (SELECT B.DJXH,B.LCSLID,B.SBXH,B.KPRQ AS CKRQ_1,B.BYTSBZ,C.LCSLID_FS,
                     B.TSE   * CASE WHEN TRIM(C.LCSLID_FS) IS NULL THEN 1  
                                    WHEN A.SNBL_MDTSE=0 THEN 1
                                    WHEN A.SNBL_MDTSE>0 AND B.BYTSBZ='Y' THEN 0
                                    ELSE 1 - A.SNBL_MDTSE / A.ZY_MDTSE 
                               END AS TSE
                FROM CKTS_LC_SHXX A
               INNER JOIN CKTS_SB_GJ_SBMX B ON B.LCSLID=A.LCSLID AND B.CHBZ='N'
                LEFT JOIN (SELECT DISTINCT LCSLID_FS FROM CKTS_LC_YWHZXX S) C ON C.LCSLID_FS=A.LCSLID_FS
               INNER JOIN GLXT_BB_SHXT_DJXX D ON D.DJXH_JS=A.DJXH
               WHERE A.TSSWJG_DM=V_SWCODE
                 AND A.QDSJ<LD_NEXTMONTH
                 AND A.LCJSRQ>=LD_THISYEAR
                 AND ((B.CKTMSYWLXDMJH IN ('SDQ',' NZYFJG')) OR (B.CKTMSYWLXDMJH='GCSB' AND D.QYLX<>'2'))
               UNION ALL
              SELECT B.DJXH,B.LCSLID,B.SBXH,B.KPRQ AS CKRQ_1,B.BYTSBZ,C.LCSLID_FS,
                     B.XFSTSE * CASE WHEN TRIM(C.LCSLID_FS) IS NULL THEN 1  
                                    WHEN A.SNBL_MDTSE=0 THEN 1
                                     WHEN A.SNBL_MDTSE>0 AND B.BYTSBZ='Y' THEN 0
                                     ELSE 1 - A.SNBL_MDTSE / A.ZY_MDTSE 
                                END AS TSE
                FROM CKTS_LC_SHXX A
               INNER JOIN CKTS_SB_FZC_SBMX B ON B.LCSLID=A.LCSLID AND B.CHBZ='N'
                LEFT JOIN (SELECT DISTINCT LCSLID_FS FROM CKTS_LC_YWHZXX S) C ON C.LCSLID_FS=A.LCSLID_FS
               INNER JOIN GLXT_BB_SHXT_DJXX D ON D.DJXH_JS=A.DJXH
               WHERE A.TSSWJG_DM=V_SWCODE
                 AND A.QDSJ<LD_NEXTMONTH
                 AND A.LCJSRQ>=LD_THISYEAR
               UNION ALL
              SELECT B.DJXH,B.LCSLID,B.SBXH,B.KPRQ AS CKRQ_1,B.BYTSBZ,C.LCSLID_FS,
                     B.TSE * CASE WHEN TRIM(C.LCSLID_FS) IS NULL THEN 1  
                                    WHEN A.SNBL_MDTSE=0 THEN 1
                                     WHEN A.SNBL_MDTSE>0 AND B.BYTSBZ='Y' THEN 0
                                     ELSE 1 - A.SNBL_MDTSE / A.ZY_MDTSE 
                                END AS TSE
                FROM CKTS_LC_SHXX A
               INNER JOIN CKTS_SB_YS_SBMX B ON B.LCSLID=A.LCSLID AND B.CHBZ='N'
                LEFT JOIN (SELECT DISTINCT LCSLID_FS FROM CKTS_LC_YWHZXX S) C ON C.LCSLID_FS=A.LCSLID_FS
               INNER JOIN GLXT_BB_SHXT_DJXX D ON D.DJXH_JS=A.DJXH
               WHERE A.TSSWJG_DM=V_SWCODE
                 AND A.QDSJ<LD_NEXTMONTH
                 AND A.LCJSRQ>=LD_THISYEAR
                 ) T;

      INSERT INTO TJBB_DT_B02105 (SSNY, BBLC, SWJGDM, SBHS, 
                SBLJ_TSCKE_HIS, SBLJ_TSCKE_YEAR, SBLJ_TMSE_HIS,  SBLJ_TMSE_YEAR, 
