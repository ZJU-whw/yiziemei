    --1.18 其他
    BEGIN
      --申报户数、申报出口额
      SELECT COUNT(DISTINCT T.DJXH), 0, 0,
             ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR THEN T.TSE ELSE 0 END), 0)/10000,6), 
             ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR THEN T.TSE ELSE 0 END), 0)/10000,6),
             ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NULL THEN T.TSE ELSE 0 END), 0)/10000,6), --在途
             ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NULL THEN T.TSE ELSE 0 END), 0)/10000,6), --在途
             ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='N' THEN T.TSE ELSE 0 END), 0)/10000,6), --准予
             ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='N' THEN T.TSE ELSE 0 END), 0)/10000,6), --准予
             ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='Y' THEN T.TSE ELSE 0 END), 0)/10000,6), --不予
             ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='Y' THEN T.TSE ELSE 0 END), 0)/10000,6) --不予
        INTO LN_SBHS, LN_SB_CKE_HIS, LN_SB_CKE_CUR, 
