  DECLARE LN_SB_ZZS_CUR    DECIMAL(18,6);
  DECLARE LN_SH_ZZS_HIS    DECIMAL(18,6);
  DECLARE LN_SH_ZZS_CUR    DECIMAL(18,6);
  DECLARE LN_BY_ZZS_HIS    DECIMAL(18,6);
  DECLARE LN_BY_ZZS_CUR    DECIMAL(18,6);
  DECLARE LN_ZT_ZZS_HIS    DECIMAL(18,6);
  DECLARE LN_ZT_ZZS_CUR    DECIMAL(18,6);

