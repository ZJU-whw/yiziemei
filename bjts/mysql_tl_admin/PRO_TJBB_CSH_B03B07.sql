DELIMITER $$

DROP PROCEDURE IF EXISTS PRO_TJBB_CSH_B03B07$$

CREATE PROCEDURE PRO_TJBB_CSH_B03B07
/*
 * 省局月报表/出口退税月报表（不计结转），所有税务局重新制表
 * 需要手工调制报表所属期
 */
(
  IN LC_MONTH VARCHAR(4000)
)
routine_body: BEGIN
  DECLARE LC_SWJGDM        VARCHAR(11);

  --区县局
  FOR LSF_SWJG IN (SELECT SWJG_DM FROM DM_SWJG WHERE TSJG_BZ='1' AND YXWS=7 ORDER BY SWJG_DM) LOOP
    SET LC_SWJGDM = LSF_SWJG.SWJG_DM;

    PRO_TJBB_B03_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='20'
     WHERE T.BBDLDM='B03' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS<>'20';
    COMMIT;

    PRO_TJBB_B07_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='20'
     WHERE T.BBDLDM='B07' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS<>'20';
    COMMIT;
  END LOOP;

  --地市局
  FOR LSF_SWJG IN (SELECT SWJG_DM FROM DM_SWJG WHERE TSJG_BZ='1' AND YXWS=5 ORDER BY SWJG_DM) LOOP
    SET LC_SWJGDM = LSF_SWJG.SWJG_DM;

    PRO_TJBB_B03_HZ(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='20'
     WHERE T.BBDLDM='B03' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS<>'20';
    COMMIT;

    PRO_TJBB_B07_HZ(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='20'
     WHERE T.BBDLDM='B07' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS<>'20';
    COMMIT;
  END LOOP;

  --省局
  BEGIN
    SET LC_SWJGDM = '13300000000';
    
    PRO_TJBB_B03_HZ(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='20'
     WHERE T.BBDLDM='B03' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS<>'20';
    COMMIT;

    PRO_TJBB_B07_HZ(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='20'
     WHERE T.BBDLDM='B07' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS<>'20';
    COMMIT;
  END;
END$$

