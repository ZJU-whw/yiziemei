BEGIN
  DECLARE BJTS_CURSOR_DONE_002 BOOLEAN DEFAULT FALSE;
  DECLARE BJTS_LSF_XX_BBLC_002 LONGTEXT;
  DECLARE BJTS_LSF_XX_BBCS_002 LONGTEXT;
  DECLARE BJTS_CURSOR_002 CURSOR FOR
SELECT TRIM(LPAD(CAST(SUBSTR(T.FORMULA,2,INSTR(T.FORMULA,')')-2) AS CHAR), 2, '0')) AS BBLC,
                          ORA_CONCAT(ORA_CONCAT('(', REPLACE(REPLACE(REPLACE(SUBSTR(T.FORMULA,INSTR(T.FORMULA,'=')+1),'(',''''),'+',','),')','''')), ')') AS BBCS
                     FROM TJBB_REPORT_FORMULA T
                    WHERE T.BBDM='B02113'
                      AND T.TYPE=2
                    ORDER BY T.YXJ;
  OPEN BJTS_CURSOR_002;
  BJTS_CURSOR_LOOP_002: LOOP
    SET BJTS_CURSOR_DONE_002 = FALSE;
    BEGIN
      DECLARE CONTINUE HANDLER FOR NOT FOUND SET BJTS_CURSOR_DONE_002 = TRUE;
      FETCH BJTS_CURSOR_002 INTO BJTS_LSF_XX_BBLC_002, BJTS_LSF_XX_BBCS_002;
    END;
    IF BJTS_CURSOR_DONE_002 THEN
      LEAVE BJTS_CURSOR_LOOP_002;
    END IF;
      BEGIN
        SET LC_SQL = ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT('INSERT INTO TJBB_DT_B02113 (SSNY, BBLC, SWJGDM,
