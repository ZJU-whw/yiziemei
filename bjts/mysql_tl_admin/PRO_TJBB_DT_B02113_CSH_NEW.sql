       AND T.ZYTSBZ='Y';
    -- 当年备案有效的
    INSERT INTO TJBB_DT_B02113 (SSNY,BBLC,SWJGDM,BAHS,SBHS,SBTSCKE,SB_TMSE,SB_TSE,SB_MDSE,
                SH_TMSE,SH_TSE,SH_MDSE,BL_TMSE,BL_TSE,BL_MDSE)
