DELIMITER $$

DROP PROCEDURE IF EXISTS PRO_TJBB_B07_CSH$$

CREATE PROCEDURE PRO_TJBB_B07_CSH
/*
 * 	出口退税月报表（不计结转），区县局初始化
 * 需要指定区县级税务机关和报表所属期
 */
(
  IN LC_SWJGDM VARCHAR(4000),
  IN LC_MONTH VARCHAR(4000)
)
routine_body: BEGIN
  DECLARE LN_ERROR         DECIMAL(38,10);
  DECLARE LC_MSG           VARCHAR(2000);

  --按报表顺序依次制表
  BEGIN
    PRO_TJBB_DT_B07101_CSH_NEW(LC_SWJGDM,LC_MONTH,LN_ERROR,LC_MSG);
    INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('PRO_TJBB_DT_B07101_CSH_NEW！'||LC_SWJGDM);
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('执行PRO_TJBB_DT_B07101_CSH_NEW失败，税务机关：'||LC_SWJGDM, LC_MSG);
      COMMIT;
  END;

END$$

DELIMITER ;
