DELIMITER $$

DROP PROCEDURE IF EXISTS PRO_TJBB_DT_B02110_CSH_NEW$$

CREATE PROCEDURE PRO_TJBB_DT_B02110_CSH_NEW
/**************************************************************
 * 海关特殊监管区域企业增值税一般纳税人资格试点情况统计表
 **************************************************************/
(
  IN V_SWCODE VARCHAR(4000),
  IN V_SSNY VARCHAR(4000),
  OUT V_ERROR DECIMAL(38,10),
  OUT V_MSG VARCHAR(4000)
)
routine_body: BEGIN
  DECLARE LD_SYSDATE       DATETIME;
  DECLARE LC_THISMONTH     VARCHAR(6);
  DECLARE LC_PREVMONTH     VARCHAR(6);
  DECLARE V_TEMP           BIGINT DEFAULT 0;
  DECLARE LN_I             BIGINT;

  SET V_ERROR =0;
  SET V_MSG = ' ';

  IF V_SSNY IS NOT NULL THEN
    SET LD_SYSDATE =STR_TO_DATE(ORA_CONCAT(V_SSNY, '01'), '%Y%m%d');
  ELSE
    SET LD_SYSDATE =CURRENT_TIMESTAMP;
  END IF;

  SET LC_THISMONTH =DATE_FORMAT(LD_SYSDATE, '%Y%m');
  SET LC_PREVMONTH =DATE_FORMAT(DATE_ADD(LD_SYSDATE, INTERVAL -1 MONTH), '%Y%m');

  -- 0、清除原有制表数据，准备重新制表
  BEGIN
  DECLARE BJTS_SQLCODE_002 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_002 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_002 = MYSQL_ERRNO, BJTS_SQLERRM_002 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_002;
      SET V_MSG = BJTS_SQLERRM_002;
      LEAVE routine_body;

  END;
DELETE FROM TJBB_DT_B02110 WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;
    COMMIT;
  END;

  -- 1、统计
  BEGIN
  DECLARE BJTS_SQLCODE_001 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_001 TEXT DEFAULT '';
    -- 检查是否第一次使用该报表

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_001 = MYSQL_ERRNO, BJTS_SQLERRM_001 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_001;
      SET V_MSG = BJTS_SQLERRM_001;
      LEAVE routine_body;

  END;
SELECT LEAST(COUNT(1), 1)
      INTO V_TEMP
      FROM TJBB_DT_B02110
     WHERE SWJGDM=V_SWCODE AND SSNY=LC_PREVMONTH AND 1=1;
    IF (V_TEMP = 0) OR (SUBSTR(LC_THISMONTH,5)='01') THEN
      -- 首次使用该报表，或每年****01所属期，插入20行空行数据
      BEGIN
        BEGIN
  DECLARE BJTS_FOR_LN_I_001 DECIMAL(65,30) DEFAULT 1;
  DECLARE BJTS_FOR_END_001 DECIMAL(65,30) DEFAULT 20;
  WHILE BJTS_FOR_LN_I_001 <= BJTS_FOR_END_001 DO
          BEGIN
            INSERT INTO TJBB_DT_B02110 (SSNY,BBLC,SWJGDM,BYS,BYS_HZ,SYLJS,SYLJS_HZ,LJS,LJS_HZ)
            SELECT LC_THISMONTH, CASE WHEN BJTS_FOR_LN_I_001<10 THEN ORA_CONCAT('0', CAST(BJTS_FOR_LN_I_001 AS CHAR)) ELSE ORA_CONCAT('', CAST(BJTS_FOR_LN_I_001 AS CHAR)) END, V_SWCODE, 0, 0, 0, 0, 0, 0
;
          END;

    SET BJTS_FOR_LN_I_001 = BJTS_FOR_LN_I_001 + 1;
  END WHILE;
END;
      END;
    ELSE
      -- 其他情况，将上月报表拷贝本年累计数复制到本月的上月累计数及本月累计数
      BEGIN
        INSERT INTO TJBB_DT_B02110 (SSNY,BBLC,SWJGDM,BYS,BYS_HZ,SYLJS,SYLJS_HZ,LJS,LJS_HZ)
        SELECT LC_THISMONTH, BBLC, SWJGDM, 0, 0, LJS, LJS_HZ, LJS, LJS_HZ
          FROM TJBB_DT_B02110
         WHERE SWJGDM=V_SWCODE AND SSNY=LC_PREVMONTH;
      END;
    END IF;
    COMMIT;
  END;

  LEAVE routine_body;
END$$

DELIMITER ;
