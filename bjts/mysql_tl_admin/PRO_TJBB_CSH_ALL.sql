DELIMITER $$

DROP PROCEDURE IF EXISTS PRO_TJBB_CSH_ALL$$

CREATE PROCEDURE PRO_TJBB_CSH_ALL
/***********************************************
 * 每月报表截止期次日凌晨执行(目前暂时为每月初)
 * 202504，调整9810报表，增加QYGTS报表，耗时较长，调整顺序为总局月报表、总局专项报表先做
 * 注：温州二分局撤并以后，2025年报表未重置，因此需要2026年保留一年以获取省局报表的上年数据
 ***********************************************/
(
	IN V_SSNY VARCHAR(4000)
)
routine_body: BEGIN
  DECLARE LC_MONTH         VARCHAR(6);
  DECLARE LC_MSG           VARCHAR(2000);
  DECLARE LC_SWJGDM        VARCHAR(11);
  DECLARE LN_I             DECIMAL(38,10);


  IF V_SSNY IS NOT NULL THEN
    SET LC_MONTH =V_SSNY;
  ELSE
    SET LC_MONTH = DATE_FORMAT(DATE_ADD(CURRENT_TIMESTAMP, INTERVAL -1 MONTH), '%Y%m');
  END IF;

  BEGIN
    -- 刷新TJBB_TASK任务
    SELECT COUNT(1)
      INTO LN_I
      FROM TJBB_TASK
     WHERE NY=LC_MONTH;
    IF LN_I>0 THEN
      BEGIN
  DECLARE BJTS_SQLCODE_004 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_004 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_004 = MYSQL_ERRNO, BJTS_SQLERRM_004 = MESSAGE_TEXT;
          SET LC_MSG = BJTS_SQLERRM_004;
          INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('清除TJBB_TASK原有任务失败！', LC_MSG);
          COMMIT;

  END;
DELETE FROM TJBB_TASK WHERE NY=LC_MONTH;
        COMMIT;
      END;
    END IF;

    BEGIN
  DECLARE BJTS_SQLCODE_003 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_003 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_003 = MYSQL_ERRNO, BJTS_SQLERRM_003 = MESSAGE_TEXT;
        SET LC_MSG = BJTS_SQLERRM_003;
        INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('新增TJBB_TASK任务失败！', LC_MSG);
        COMMIT;

  END;
INSERT INTO TJBB_TASK (BBDLDM, SWJGDM, NY, STATUS, SJSWJG, CJTIME, CJR, ZBTIME, ZBR, TYPE, SWJGMC, SWJGJC)
           SELECT S.BBDLDM, T.SWJG_DM, LC_MONTH,
                  CASE WHEN SUBSTR(T.SWJG_DM,6,6)='000000' THEN '00' ELSE '10' END,
                  T.SWJG_DM_SJ, CURRENT_TIMESTAMP, 'system', CURRENT_TIMESTAMP, 'system', '1', T.SWJG_MC, T.SWJG_JC
             FROM DM_SWJG T, TJBB_REPORT_ITEM S
            WHERE T.TSJG_BZ='1'
              AND S.TYPE='1'
            ORDER BY T.SWJG_DM, S.BBDLDM;
      COMMIT;
    END;

    -- 刷新TJBB_TASK_SUB任务
    SELECT COUNT(1)
      INTO LN_I
      FROM TJBB_TASK_SUB
     WHERE NY=LC_MONTH;
    IF LN_I>0 THEN
      BEGIN
  DECLARE BJTS_SQLCODE_002 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_002 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_002 = MYSQL_ERRNO, BJTS_SQLERRM_002 = MESSAGE_TEXT;
          SET LC_MSG = BJTS_SQLERRM_002;
          INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('清除TJBB_TASK_SUB原有任务失败！', LC_MSG);
          COMMIT;

  END;
DELETE FROM TJBB_TASK_SUB WHERE NY=LC_MONTH;
        COMMIT;
      END;
    END IF;

    BEGIN
  DECLARE BJTS_SQLCODE_001 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_001 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_001 = MYSQL_ERRNO, BJTS_SQLERRM_001 = MESSAGE_TEXT;
        SET LC_MSG = BJTS_SQLERRM_001;
        INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('新增TJBB_TASK_SUB任务失败！', LC_MSG);
        COMMIT;

  END;
INSERT INTO TJBB_TASK_SUB (BBID, BBDM, SWJGDM, NY, HZTIME, HZR, BBDLDM)
           SELECT REPLACE(UUID(), '-', ''), S.BBDM, T.SWJG_DM, LC_MONTH, CURRENT_TIMESTAMP, 'system', S.BBDLDM
             FROM DM_SWJG T, TJBB_REPORT_ITEM R, TJBB_REPORT_LIST S
            WHERE T.TSJG_BZ='1'
              AND R.BBDLDM=S.BBDLDM AND R.TYPE='1'
              AND S.QYBJ='Y'
            ORDER BY T.SWJG_DM, S.BBDM;
      COMMIT;
    END;
  END;

  -- 初始化
  INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES (ORA_CONCAT('初始化开始！', LC_MONTH));
  COMMIT;

  -- 区县局
  BEGIN
  DECLARE BJTS_CURSOR_DONE_001 BOOLEAN DEFAULT FALSE;
  DECLARE BJTS_LSF_SWJG_SWJG_DM_001 LONGTEXT;
  DECLARE BJTS_CURSOR_001 CURSOR FOR
SELECT SWJG_DM FROM DM_SWJG WHERE TSJG_BZ='1' AND YXWS=7 ORDER BY SWJG_DM;
  OPEN BJTS_CURSOR_001;
  BJTS_CURSOR_LOOP_001: LOOP
    SET BJTS_CURSOR_DONE_001 = FALSE;
    BEGIN
      DECLARE CONTINUE HANDLER FOR NOT FOUND SET BJTS_CURSOR_DONE_001 = TRUE;
      FETCH BJTS_CURSOR_001 INTO BJTS_LSF_SWJG_SWJG_DM_001;
    END;
    IF BJTS_CURSOR_DONE_001 THEN
      LEAVE BJTS_CURSOR_LOOP_001;
    END IF;
    SET LC_SWJGDM = BJTS_LSF_SWJG_SWJG_DM_001;

    -- 总局月报表
    CALL PRO_TJBB_B01_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK AS T
       SET STATUS='10'
     WHERE T.BBDLDM='B01' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS='00';
    COMMIT;

    -- 总局专项报表
    CALL PRO_TJBB_B02_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK AS T
       SET STATUS='10'
     WHERE T.BBDLDM='B02' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS='00';
    COMMIT;

    -- 总局专项报表（二）
    CALL PRO_TJBB_B04_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK AS T
       SET STATUS='10'
     WHERE T.BBDLDM='B04' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS='00';
    COMMIT;

    -- 跨境电商统计表
    CALL PRO_TJBB_B05_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK AS T
       SET STATUS='10'
     WHERE T.BBDLDM='B05' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS='00';
    COMMIT;

    -- 市场采购情况统计表
    CALL PRO_TJBB_B06_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK AS T
       SET STATUS='10'
     WHERE T.BBDLDM='B06' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS='00';
    COMMIT;

  END LOOP BJTS_CURSOR_LOOP_001;
  CLOSE BJTS_CURSOR_001;
END;

  INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES (ORA_CONCAT('初始化结束！', LC_MONTH));
  COMMIT;
END$$

DELIMITER ;
