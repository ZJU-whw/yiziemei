CREATE PROCEDURE PRO_TJBB_DT_B01100_CSH_NEW
/*
 * 202106，根据金三抽取数据源，修改统计逻辑
 * 202202，针对同时申报出口货物劳务以及服务贸易的企业，调整lctjjc
 * 20260116，根据舟山反馈问题分析，在统计生产企业申报户数、申报出口额、申报免抵退税额口径，提取进料加工数据时加调整数不为0的条件
 */
(
  IN V_SWCODE VARCHAR(4000),
	IN V_SSNY VARCHAR(4000),
  OUT V_ERROR DECIMAL(38,10),
  OUT V_MSG VARCHAR(4000)
)
routine_body: BEGIN
  DECLARE LD_SYSDATE       DATETIME;
  DECLARE LC_THISMONTH     VARCHAR(6);
  DECLARE LD_THISYEAR      DATETIME;
  DECLARE LD_NEXTMONTH     DATETIME;

  DECLARE LN_BAHS          BIGINT;
  DECLARE LN_SBHS          BIGINT;
  DECLARE LN_SB_CKE_HIS    DECIMAL(18,6);
  DECLARE LN_SB_CKE_CUR    DECIMAL(18,6);

  DECLARE LN_SB_ZZS_HIS    DECIMAL(18,6);
  DECLARE LN_SB_ZZS_CUR    DECIMAL(18,6);
  DECLARE LN_SH_ZZS_HIS    DECIMAL(18,6);
  DECLARE LN_SH_ZZS_CUR    DECIMAL(18,6);
  DECLARE LN_ZH_ZZS_HIS    DECIMAL(18,6);
  DECLARE LN_ZH_ZZS_CUR    DECIMAL(18,6);
  DECLARE LN_BY_ZZS_HIS    DECIMAL(18,6);
  DECLARE LN_BY_ZZS_CUR    DECIMAL(18,6);
  DECLARE LN_ZT_ZZS_HIS    DECIMAL(18,6);
  DECLARE LN_ZT_ZZS_CUR    DECIMAL(18,6);
  DECLARE LN_SP_ZZS_XJ     DECIMAL(18,6);
  DECLARE LN_SP_ZZS_HIS    DECIMAL(18,6);
  DECLARE LN_SP_ZZS_CUR    DECIMAL(18,6);
  DECLARE LN_YS_ZZS        DECIMAL(18,6);
  DECLARE LN_BL_ZZS_HIS    DECIMAL(18,6);
  DECLARE LN_BL_ZZS_CUR    DECIMAL(18,6);
  DECLARE TSFN_ZZS_HIS     DECIMAL(18,6);
  DECLARE TSFN_ZZS_CUR     DECIMAL(18,6);

  DECLARE LN_SB_XFS_HIS    DECIMAL(18,6);
  DECLARE LN_SB_XFS_CUR    DECIMAL(18,6);
  DECLARE LN_SH_XFS_HIS    DECIMAL(18,6);
  DECLARE LN_SH_XFS_CUR    DECIMAL(18,6);
  DECLARE LN_ZH_XFS_HIS    DECIMAL(18,6);
  DECLARE LN_ZH_XFS_CUR    DECIMAL(18,6);
  DECLARE LN_BY_XFS_HIS    DECIMAL(18,6);
  DECLARE LN_BY_XFS_CUR    DECIMAL(18,6);
  DECLARE LN_ZT_XFS_HIS    DECIMAL(18,6);
  DECLARE LN_ZT_XFS_CUR    DECIMAL(18,6);
  DECLARE LN_SP_XFS_XJ     DECIMAL(18,6);
  DECLARE LN_SP_XFS_HIS    DECIMAL(18,6);
  DECLARE LN_SP_XFS_CUR    DECIMAL(18,6);
  DECLARE LN_YS_XFS        DECIMAL(18,6);
  DECLARE LN_BL_XFS_HIS    DECIMAL(18,6);
  DECLARE LN_BL_XFS_CUR    DECIMAL(18,6);
  DECLARE TSFN_XFS_HIS     DECIMAL(18,6);
  DECLARE TSFN_XFS_CUR     DECIMAL(18,6);

  DECLARE LC_SQL           VARCHAR(4000);
  DECLARE LC_SQL_UPDATEHZ  VARCHAR(4000);

  SET V_ERROR =0;
  SET V_MSG = ' ';

  IF V_SSNY IS NOT NULL THEN
    SET LD_SYSDATE =STR_TO_DATE(ORA_CONCAT(V_SSNY, '01'), '%Y%m%d');
  ELSE
    SET LD_SYSDATE =CAST(DATE_FORMAT(CURRENT_TIMESTAMP, '%Y-%m-01') AS DATETIME);
  END IF;
  SET LC_THISMONTH =DATE_FORMAT(LD_SYSDATE, '%Y%m');
  SET LD_THISYEAR =MAKEDATE(YEAR(LD_SYSDATE), 1);
  SET LD_NEXTMONTH =CAST(DATE_FORMAT(DATE_ADD(LD_SYSDATE, INTERVAL 1 MONTH), '%Y-%m-01') AS DATETIME);

  -- 0、初始化
  BEGIN
  DECLARE BJTS_SQLCODE_013 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_013 TEXT DEFAULT '';
    -- 清除原有制表数据、准备重新制表

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_013 = MYSQL_ERRNO, BJTS_SQLERRM_013 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_013;
      SET V_MSG = BJTS_SQLERRM_013;
      LEAVE routine_body;

  END;
DELETE FROM TJBB_DT_B01100 WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;
    COMMIT;
  END;

  -- 1、外贸企业
  BEGIN
  DECLARE BJTS_SQLCODE_012 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_012 TEXT DEFAULT '';
    -- 返纳

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_012 = MYSQL_ERRNO, BJTS_SQLERRM_012 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_012;
      SET V_MSG = BJTS_SQLERRM_012;

  END;
SELECT IFNULL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10101' AND T.SKSSQZ< LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6), 0),
           IFNULL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10101' AND T.SKSSQZ>=LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6), 0),
           IFNULL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10102' AND T.SKSSQZ< LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6), 0),
           IFNULL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10102' AND T.SKSSQZ>=LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6), 0)
      INTO TSFN_ZZS_HIS, TSFN_ZZS_CUR, TSFN_XFS_HIS, TSFN_XFS_CUR
      FROM FG_CKTSFN_HXZG T, GLXT_BB_SHXT_DJXX S
     WHERE S.BAJC_YEAR IN ('00','10')
       AND T.CPCODE=S.CPCODE
       AND T.SKSSSWJG_DM=V_SWCODE
       AND T.RKRQ>=LD_THISYEAR AND T.RKRQ<LD_NEXTMONTH
       AND T.YWHZBUUID IS NULL;

    -- 备案户数
    SELECT COUNT(1)
      INTO LN_BAHS
      FROM GLXT_BB_SHXT_DJXX T
     WHERE T.SWJGDM=V_SWCODE
       AND T.ZX_FLAG='N'
       AND T.BAJC_YEAR='10';

    -- 申报户数、申报出口额
    SELECT COUNT(DISTINCT T.DJXH),
           ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR THEN T.MYLAJ ELSE 0 END), 0)/10000,6),
           ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR THEN T.MYLAJ ELSE 0 END), 0)/10000,6)
      INTO LN_SBHS, LN_SB_CKE_HIS, LN_SB_CKE_CUR
      FROM (SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,
                   B.MYLAJ * CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1
                                  WHEN A.ZY_MDTSE=0 THEN 1
                                  WHEN A.SNBL_MDTSE=0 THEN 1
                                  WHEN A.SNBL_MDTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                  ELSE LEAST(GREATEST(1 - A.SNBL_MDTSE / A.ZY_MDTSE,0),1)
                             END AS MYLAJ
              FROM CKTS_LC_SHXX A
              LEFT JOIN CKTS_SB_MTS_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N'
             WHERE A.TSSWJG_DM=V_SWCODE
               AND A.LCTJJC IN ('10','40','50')
               AND A.QDSJ<LD_NEXTMONTH
               AND A.LCJSRQ>=LD_THISYEAR) T;

    -- 申报退税额、审核通过退税额、暂缓退税额、不予退税额、在途退税额
    SELECT ROUND(IFNULL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1< LD_THISYEAR THEN T.TSE ELSE 0 END), 0)/10000,6), -- 增值税申报
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1>=LD_THISYEAR THEN T.TSE ELSE 0 END), 0)/10000,6), -- 申报
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=40 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 在途
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=40 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 在途
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 准予
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 准予
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=20 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 不予
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=20 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 不予
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=10 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 暂缓
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=10 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 暂缓
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1< LD_THISYEAR THEN T.TSE ELSE 0 END), 0)/10000,6), -- 消费税申报
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1>=LD_THISYEAR THEN T.TSE ELSE 0 END), 0)/10000,6), -- 申报
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=40 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 在途
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=40 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 在途
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 准予
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 准予
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=20 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 不予
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=20 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 不予
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=10 THEN T.TSE ELSE 0 END), 0)/10000,6), -- 暂缓
           ROUND(IFNULL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=10 THEN T.TSE ELSE 0 END), 0)/10000,6) -- 暂缓
      INTO LN_SB_ZZS_HIS, LN_SB_ZZS_CUR, LN_ZT_ZZS_HIS, LN_ZT_ZZS_CUR, LN_SH_ZZS_HIS, LN_SH_ZZS_CUR, LN_BY_ZZS_HIS, LN_BY_ZZS_CUR, LN_ZH_ZZS_HIS, LN_ZH_ZZS_CUR,
           LN_SB_XFS_HIS, LN_SB_XFS_CUR, LN_ZT_XFS_HIS, LN_ZT_XFS_CUR, LN_SH_XFS_HIS, LN_SH_XFS_CUR, LN_BY_XFS_HIS, LN_BY_XFS_CUR, LN_ZH_XFS_HIS, LN_ZH_XFS_CUR
      FROM (SELECT A.DJXH,B.SBXH,B.CKRQ_1,B.SZ,
                   CASE WHEN TRIM(A.LCSLID_FS) IS NOT NULL AND B.ZBBLBZ='Y' THEN 10
                        WHEN TRIM(A.LCSLID_FS) IS NOT NULL AND B.BYTSBZ='Y' THEN 20
                        WHEN TRIM(A.LCSLID_FS) IS NOT NULL THEN 30
                        WHEN TRIM(A.LCSLID_FS) IS NULL AND A.LCSLID_SB<>A.LCSLID THEN 10
                        ELSE 40 END AS SHZT,
                   B.TSE * CASE WHEN B.SZ='V' THEN (CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1
                                                         WHEN A.ZY_ZZSTSE=0 THEN 1
                                                         WHEN A.SNBL_ZZSTSE=0 THEN 1
                                                         WHEN A.SNBL_ZZSTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                                         ELSE LEAST(GREATEST(1 - A.SNBL_ZZSTSE / A.ZY_ZZSTSE,0),1)
                                                    END)
                           ELSE (CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1
                                      WHEN A.ZY_XFSTSE=0 THEN 1
                                      WHEN A.SNBL_XFSTSE=0 THEN 1
                                      WHEN A.SNBL_XFSTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                      ELSE LEAST(GREATEST(1 - A.SNBL_XFSTSE / A.ZY_XFSTSE,0),1)
                                 END)
                           END AS TSE
              FROM CKTS_LC_SHXX A
             INNER JOIN CKTS_SB_MTS_JHMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N'
             WHERE A.TSSWJG_DM=V_SWCODE
               AND A.LCTJJC IN ('10','40','50')
               AND A.QDSJ<LD_NEXTMONTH
               AND A.LCJSRQ>=LD_THISYEAR) T;

    -- 审批退税额、移送国库退税额、国库办理退税额
    SELECT ROUND(IFNULL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_ZZSTSE ELSE T.SEHZ_ZZSTSE END), 0)/10000,6), -- 增值税审批
           ROUND(IFNULL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_ZZSTSE ELSE T.SEHZ_ZZSTSE END * T.SNCKZB), 0)/10000,6), -- 审批上年出口
           ROUND(IFNULL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_ZZSTSE ELSE 0 END), 0)/10000,6), -- 移送国库
           ROUND(IFNULL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_ZZSTSE ELSE 0 END * T.SNCKZB), 0)/10000,6), -- 办理上年出口
           ROUND(IFNULL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_XFSTSE ELSE T.SEHZ_XFSTSE END), 0)/10000,6), -- 消费税审批
           ROUND(IFNULL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_XFSTSE ELSE T.SEHZ_XFSTSE END * T.SNCKZB), 0)/10000,6), -- 审批上年出口
           ROUND(IFNULL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_XFSTSE ELSE 0 END), 0)/10000,6), -- 移送国库
           ROUND(IFNULL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_XFSTSE ELSE 0 END * T.SNCKZB), 0)/10000,6) -- 办理上年出口
      INTO LN_SP_ZZS_XJ, LN_SP_ZZS_HIS, LN_YS_ZZS, LN_BL_ZZS_HIS,
           LN_SP_XFS_XJ, LN_SP_XFS_HIS, LN_YS_XFS, LN_BL_XFS_HIS
      FROM CKTS_LC_SEHZXX T
     WHERE T.CKTMSJHSSSWJGDM=V_SWCODE
       AND T.LCTJJC='10'
       AND T.XHRQ_TK>=LD_THISYEAR
       AND T.SEHZRQ<LD_NEXTMONTH;
    SET LN_SP_ZZS_CUR = LN_SP_ZZS_XJ - LN_SP_ZZS_HIS;
    SET LN_SP_XFS_CUR = LN_SP_XFS_XJ - LN_SP_XFS_HIS;
    SET LN_BL_ZZS_CUR = LN_YS_ZZS - LN_BL_ZZS_HIS;
    SET LN_BL_XFS_CUR = LN_YS_XFS - LN_BL_XFS_HIS;

    INSERT INTO TJBB_DT_B01100 (SSNY, BBLC, SWJGDM, RDHS, SBHS, SB_CKE_XJ, SB_CKE_HIS, SB_CKE_CUR,
           SB_TMSE_XJ, SB_TMSE_HIS, SB_TMSE_CUR,
           SH_TMSE_XJ, SH_TMSE_HIS, SH_TMSE_CUR,
           ZH_TMSE_XJ, ZH_TMSE_HIS, ZH_TMSE_CUR,
           BY_TMSE_XJ, BY_TMSE_HIS, BY_TMSE_CUR,
           ZT_TMSE_XJ, ZT_TMSE_HIS, ZT_TMSE_CUR,
           SP_TK_XJ,   SP_TK_HIS,   SP_TK_CUR,
           YS_TK,      WS_TK,
           BL_TK_XJ,   BL_TK_HIS,   BL_TK_CUR,
           ZT_TK)
    SELECT LC_THISMONTH, '05', V_SWCODE, LN_BAHS, LN_SBHS, LN_SB_CKE_HIS + LN_SB_CKE_CUR, LN_SB_CKE_HIS, LN_SB_CKE_CUR,
           LN_SB_ZZS_HIS + LN_SB_ZZS_CUR, LN_SB_ZZS_HIS, LN_SB_ZZS_CUR,
           LN_SH_ZZS_HIS + LN_SH_ZZS_CUR, LN_SH_ZZS_HIS, LN_SH_ZZS_CUR,
           LN_ZH_ZZS_HIS + LN_ZH_ZZS_CUR, LN_ZH_ZZS_HIS, LN_ZH_ZZS_CUR,
           LN_BY_ZZS_HIS + LN_BY_ZZS_CUR, LN_BY_ZZS_HIS, LN_BY_ZZS_CUR,
           LN_ZT_ZZS_HIS + LN_ZT_ZZS_CUR, LN_ZT_ZZS_HIS, LN_ZT_ZZS_CUR,
           LN_SP_ZZS_XJ - TSFN_ZZS_HIS - TSFN_ZZS_CUR,   LN_SP_ZZS_HIS - TSFN_ZZS_HIS, LN_SP_ZZS_CUR - TSFN_ZZS_CUR,
           LN_YS_ZZS - TSFN_ZZS_HIS - TSFN_ZZS_CUR,      LN_SP_ZZS_XJ - LN_YS_ZZS,
           LN_YS_ZZS - TSFN_ZZS_HIS - TSFN_ZZS_CUR,      LN_BL_ZZS_HIS - TSFN_ZZS_HIS, LN_BL_ZZS_CUR - TSFN_ZZS_CUR,
           0
;

    INSERT INTO TJBB_DT_B01100 (SSNY, BBLC, SWJGDM, RDHS, SBHS, SB_CKE_XJ, SB_CKE_HIS, SB_CKE_CUR,
           SB_TMSE_XJ, SB_TMSE_HIS, SB_TMSE_CUR,
           SH_TMSE_XJ, SH_TMSE_HIS, SH_TMSE_CUR,
           ZH_TMSE_XJ, ZH_TMSE_HIS, ZH_TMSE_CUR,
           BY_TMSE_XJ, BY_TMSE_HIS, BY_TMSE_CUR,
           ZT_TMSE_XJ, ZT_TMSE_HIS, ZT_TMSE_CUR,
           SP_TK_XJ,   SP_TK_HIS,   SP_TK_CUR,
           YS_TK,      WS_TK,
           BL_TK_XJ,   BL_TK_HIS,   BL_TK_CUR,
           ZT_TK)
    SELECT LC_THISMONTH, '06', V_SWCODE, 0, 0, 0, 0, 0,
           LN_SB_XFS_HIS + LN_SB_XFS_CUR, LN_SB_XFS_HIS, LN_SB_XFS_CUR,
           LN_SH_XFS_HIS + LN_SH_XFS_CUR, LN_SH_XFS_HIS, LN_SH_XFS_CUR,
           LN_ZH_XFS_HIS + LN_ZH_XFS_CUR, LN_ZH_XFS_HIS, LN_ZH_XFS_CUR,
           LN_BY_XFS_HIS + LN_BY_XFS_CUR, LN_BY_XFS_HIS, LN_BY_XFS_CUR,
           LN_ZT_XFS_HIS + LN_ZT_XFS_CUR, LN_ZT_XFS_HIS, LN_ZT_XFS_CUR,
           LN_SP_XFS_XJ - TSFN_XFS_HIS - TSFN_XFS_CUR,  LN_SP_XFS_HIS - TSFN_XFS_HIS, LN_SP_XFS_CUR - TSFN_XFS_CUR,
           LN_YS_XFS - TSFN_XFS_HIS - TSFN_XFS_CUR,      LN_SP_XFS_XJ - LN_YS_XFS,
           LN_YS_XFS - TSFN_XFS_HIS - TSFN_XFS_CUR,      LN_BL_XFS_HIS - TSFN_XFS_HIS, LN_BL_XFS_CUR - TSFN_XFS_CUR,
           0
;
    COMMIT;
  END;

  -- 2、外综服企业
  BEGIN
  DECLARE BJTS_SQLCODE_011 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_011 TEXT DEFAULT '';
    -- 返纳

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_011 = MYSQL_ERRNO, BJTS_SQLERRM_011 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_011;
      SET V_MSG = BJTS_SQLERRM_011;

  END;
SELECT IFNULL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10101' AND T.SKSSQZ< LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6), 0),
           IFNULL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10101' AND T.SKSSQZ>=LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6), 0),
           IFNULL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10102' AND T.SKSSQZ< LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6), 0),
           IFNULL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10102' AND T.SKSSQZ>=LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6), 0)
      INTO TSFN_ZZS_HIS, TSFN_ZZS_CUR, TSFN_XFS_HIS, TSFN_XFS_CUR
      FROM FG_CKTSFN_HXZG T, GLXT_BB_SHXT_DJXX S
     WHERE S.BAJC_YEAR IN ('70','71','72')
       AND T.CPCODE=S.CPCODE
       AND T.SKSSSWJG_DM=V_SWCODE
       AND T.RKRQ>=LD_THISYEAR
       AND T.RKRQ<LD_NEXTMONTH
       AND T.YWHZBUUID IS NULL;

    -- 备案户数
    SELECT COUNT(1)
      INTO LN_BAHS
      FROM GLXT_BB_SHXT_DJXX A
     WHERE A.SWJGDM=V_SWCODE
       AND A.ZX_FLAG='N'
       AND A.BAJC_YEAR IN ('70','71','72');

    -- 申报户数、申报出口额
    SELECT COUNT(DISTINCT T.DJXH),
           ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR THEN T.MYLAJ ELSE 0 END), 0)/10000,6),
           ROUND(IFNULL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR THEN T.MYLAJ ELSE 0 END), 0)/10000,6)
      INTO LN_SBHS, LN_SB_CKE_HIS, LN_SB_CKE_CUR
      FROM (SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,
                   B.MYLAJ * CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1
                                  WHEN A.ZY_MDTSE=0 THEN 1
                                  WHEN A.SNBL_MDTSE=0 THEN 1
                                  WHEN A.SNBL_MDTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                  ELSE LEAST(GREATEST(1 - A.SNBL_MDTSE / A.ZY_MDTSE,0),1)
                             END AS MYLAJ
              FROM CKTS_LC_SHXX A
              LEFT JOIN CKTS_SB_MTS_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N'
             WHERE A.TSSWJG_DM=V_SWCODE
               AND A.LCTJJC IN ('70','71')
               AND A.QDSJ<LD_NEXTMONTH
               AND A.LCJSRQ>=LD_THISYEAR
