DELIMITER $$

DROP PROCEDURE IF EXISTS PRO_TJBB_DT_B03113_CSH_NEW$$

CREATE PROCEDURE PRO_TJBB_DT_B03113_CSH_NEW
/*************************************************
 * 浙江省对美主要出口企业情况表
 * 20210205，金额栏保留整数，比率保留小数点后1位
 ************************************************/
(
  IN V_SWCODE VARCHAR(4000),
  IN V_SSNY VARCHAR(4000),
  OUT V_ERROR DECIMAL(38,10),
  OUT V_MSG VARCHAR(4000)
)
routine_body: BEGIN
  DECLARE LC_THISMONTH     VARCHAR(6);-- 当月
  DECLARE LC_THISYEAR      VARCHAR(6);-- 当年首月
  DECLARE LC_LASTMONTH     VARCHAR(6);-- 上年同期
  DECLARE LC_LASTYEAR      VARCHAR(6);-- 上年首月
  DECLARE LC_SQL_UPDATEHZ  VARCHAR(4000);
  DECLARE LD_SYSDATE       DATETIME;

  SET V_ERROR =0;
  SET V_MSG = ' ';

  IF V_SSNY IS NOT NULL THEN
    SET LD_SYSDATE =STR_TO_DATE(ORA_CONCAT(V_SSNY, '01'), '%Y%m%d');
  ELSE
    SET LD_SYSDATE =CURRENT_TIMESTAMP;
  END IF;

  SET LC_THISMONTH =DATE_FORMAT(LD_SYSDATE, '%Y%m');
  SET LC_THISYEAR =ORA_CONCAT(DATE_FORMAT(LD_SYSDATE, '%Y'), '01');
  SET LC_LASTMONTH =DATE_FORMAT(DATE_ADD(LD_SYSDATE, INTERVAL -12 MONTH), '%Y%m');
  SET LC_LASTYEAR =ORA_CONCAT(DATE_FORMAT(DATE_ADD(LD_SYSDATE, INTERVAL -12 MONTH), '%Y'), '01');

  -- 0、清除原有制表数据，准备重新制表
  BEGIN
  DECLARE BJTS_SQLCODE_005 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_005 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_005 = MYSQL_ERRNO, BJTS_SQLERRM_005 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_005;
      SET V_MSG = BJTS_SQLERRM_005;
      LEAVE routine_body;

  END;
DELETE FROM TJBB_DT_B03113 WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;
    COMMIT;
  END;

  -- 1、本年前50名当年数据与上年同期数据
  BEGIN
  DECLARE BJTS_SQLCODE_004 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_004 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_004 = MYSQL_ERRNO, BJTS_SQLERRM_004 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_004;
      SET V_MSG = BJTS_SQLERRM_004;
      LEAVE routine_body;

  END;
INSERT INTO TJBB_DT_B03113 (SSNY,BBLC,SWJGDM,CPCODE,QYHGDM,QYMC,JSMODE,JSMODEMC,
                                USA_CKE_YEAR,CKE_YEAR,USA_TMSE_YEAR,TMSE_YEAR,PM,
                                USA_CKE_YEAR_LAST,CKE_YEAR_LAST,USA_TMSE_YEAR_LAST,TMSE_YEAR_LAST)
      WITH THISYEAR AS (SELECT A.CPCODE, A.QYHGDM, A.NSRMC, A.JSMODE,
                               SUM(B.USD_AMT_USA)/10000 AS USD_AMT_USA, SUM(B.USD_AMT_ALL)/10000 AS USD_AMT_ALL,
                               SUM(B.TS_AMT_USA)/10000 AS TSE_AMT_USA, SUM(B.TS_AMT_ALL)/10000 AS TSE_AMT_ALL,
                               ROW_NUMBER() OVER (PARTITION BY A.JSMODE ORDER BY SUM(B.USD_AMT_USA) DESC) AS PM
                          FROM GLXT_BB_SHXT_DJXX A, TJBB_FHXX_CPCODE B
                         WHERE A.SWJGDM=V_SWCODE
                           AND B.SWCODE=V_SWCODE
                           AND SSNY BETWEEN LC_THISYEAR AND LC_THISMONTH
                           AND B.XMFL=A.CPCODE
                           AND A.JSMODE IN ('1','2')
                         GROUP BY A.CPCODE, A.QYHGDM, A.NSRMC, A.JSMODE),
           LASTYEAR AS (SELECT XMFL, SUM(USD_AMT_USA)/10000 AS USD_AMT_USA, SUM(USD_AMT_ALL)/10000 AS USD_AMT_ALL,
                               SUM(TS_AMT_USA)/10000 AS TSE_AMT_USA, SUM(TS_AMT_ALL)/10000 AS TSE_AMT_ALL
                          FROM TJBB_FHXX_CPCODE
                         WHERE SWCODE=V_SWCODE
                           AND SSNY BETWEEN LC_LASTYEAR AND LC_LASTMONTH
                         GROUP BY XMFL)
    SELECT LC_THISMONTH, ORA_CONCAT(ORA_CONCAT(A.JSMODE, CASE WHEN A.PM<10 THEN '0' ELSE '' END), A.PM), V_SWCODE,
           A.CPCODE, A.QYHGDM, A.NSRMC, A.JSMODE, CASE WHEN A.JSMODE='1' THEN '生产' ELSE '外贸' END,
           ROUND(A.USD_AMT_USA,0), ROUND(A.USD_AMT_ALL,0), ROUND(A.TSE_AMT_USA,0), ROUND(A.TSE_AMT_ALL,0), A.PM,
           ROUND(B.USD_AMT_USA,0), ROUND(B.USD_AMT_ALL,0), ROUND(B.TSE_AMT_USA,0), ROUND(B.TSE_AMT_ALL,0)
      FROM THISYEAR A
      LEFT JOIN LASTYEAR B ON B.XMFL = A.CPCODE
     WHERE PM<=50
       AND A.USD_AMT_USA>0
    ;
    COMMIT;
  END;

  -- 2、同比计算
  BEGIN
  DECLARE BJTS_SQLCODE_003 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_003 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_003 = MYSQL_ERRNO, BJTS_SQLERRM_003 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_003;
      SET V_MSG = BJTS_SQLERRM_003;

  END;
UPDATE TJBB_DT_B03113
       SET USA_CKE_TB  = CASE WHEN IFNULL(USA_CKE_YEAR_LAST, 0)=0 THEN NULL ELSE ROUND(100 * USA_CKE_YEAR / USA_CKE_YEAR_LAST -100,1) END,
    CKE_TB  = CASE WHEN IFNULL(CKE_YEAR_LAST, 0)=0 THEN NULL ELSE ROUND(100 * CKE_YEAR / CKE_YEAR_LAST -100,1) END,
    USA_TMSE_TB = CASE WHEN IFNULL(USA_TMSE_YEAR_LAST, 0)=0 THEN NULL ELSE ROUND(100 * USA_TMSE_YEAR / USA_TMSE_YEAR_LAST -100,1) END,
    TMSE_TB = CASE WHEN IFNULL(TMSE_YEAR_LAST, 0)=0 THEN NULL ELSE ROUND(100 * TMSE_YEAR / TMSE_YEAR_LAST -100,1) END
     WHERE SWJGDM=V_SWCODE
       AND SSNY=LC_THISMONTH;
    COMMIT;
  END;
  IF V_ERROR <> 0 THEN
    LEAVE routine_body;
  END IF;

  -- 3、占比计算
  BEGIN
  DECLARE BJTS_SQLCODE_002 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_002 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_002 = MYSQL_ERRNO, BJTS_SQLERRM_002 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_002;
      SET V_MSG = BJTS_SQLERRM_002;

  END;
UPDATE TJBB_DT_B03113 AS T
       SET CKE_YEAR_ZB = CASE WHEN IFNULL(CKE_YEAR, 0)=0 THEN NULL ELSE ROUND(100 * USA_CKE_YEAR / CKE_YEAR,1) END,
    CKE_YEAR_ZB_LAST = CASE WHEN IFNULL(CKE_YEAR_LAST, 0)=0 THEN NULL ELSE ROUND(100 * USA_CKE_YEAR_LAST / CKE_YEAR_LAST,1) END,
    TMSE_YEAR_ZB = CASE WHEN IFNULL(TMSE_YEAR, 0)=0 THEN NULL ELSE ROUND(100 * USA_TMSE_YEAR / TMSE_YEAR,1) END,
    TMSE_YEAR_ZB_LAST = CASE WHEN IFNULL(TMSE_YEAR_LAST, 0)=0 THEN NULL ELSE ROUND(100 * USA_TMSE_YEAR_LAST / TMSE_YEAR_LAST,1) END
     WHERE SWJGDM=V_SWCODE
       AND SSNY=LC_THISMONTH;
    COMMIT;
  END;
  IF V_ERROR <> 0 THEN
    LEAVE routine_body;
  END IF;

  -- 4、汇总栏初始化
  BEGIN
  DECLARE BJTS_SQLCODE_001 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_001 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_001 = MYSQL_ERRNO, BJTS_SQLERRM_001 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_001;
      SET V_MSG = BJTS_SQLERRM_001;

  END;
SET LC_SQL_UPDATEHZ = 'UPDATE TJBB_DT_B03113 SET ';

    BEGIN
  DECLARE BJTS_CURSOR_DONE_001 BOOLEAN DEFAULT FALSE;
  DECLARE BJTS_LSF_XX_FNAME_001 LONGTEXT;
  DECLARE BJTS_CURSOR_001 CURSOR FOR
SELECT FNAME FROM TJBB_HEADER_COLS WHERE BBDM='B03113' AND FTYPE='NUMBER' ORDER BY SHOWORDER;
  OPEN BJTS_CURSOR_001;
  BJTS_CURSOR_LOOP_001: LOOP
    SET BJTS_CURSOR_DONE_001 = FALSE;
    BEGIN
      DECLARE CONTINUE HANDLER FOR NOT FOUND SET BJTS_CURSOR_DONE_001 = TRUE;
      FETCH BJTS_CURSOR_001 INTO BJTS_LSF_XX_FNAME_001;
    END;
    IF BJTS_CURSOR_DONE_001 THEN
      LEAVE BJTS_CURSOR_LOOP_001;
    END IF;
      SET LC_SQL_UPDATEHZ = ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(LC_SQL_UPDATEHZ, BJTS_LSF_XX_FNAME_001), '_HZ='), BJTS_LSF_XX_FNAME_001), ', ');

  END LOOP BJTS_CURSOR_LOOP_001;
  CLOSE BJTS_CURSOR_001;
END;

    SET LC_SQL_UPDATEHZ = ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(SUBSTR(LC_SQL_UPDATEHZ, 1, LENGTH(LC_SQL_UPDATEHZ)-2), ' WHERE SWJGDM='''), V_SWCODE), ''' AND SSNY='''), LC_THISMONTH), '''');

    SET @BJTS_DYNAMIC_SQL_001 = LC_SQL_UPDATEHZ;
PREPARE BJTS_DYNAMIC_STMT_001 FROM @BJTS_DYNAMIC_SQL_001;
EXECUTE BJTS_DYNAMIC_STMT_001;
DEALLOCATE PREPARE BJTS_DYNAMIC_STMT_001;
    COMMIT;
  END;

  LEAVE routine_body;
END$$

DELIMITER ;
