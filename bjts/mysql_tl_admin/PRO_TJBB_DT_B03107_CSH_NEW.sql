DELIMITER $$

DROP PROCEDURE IF EXISTS PRO_TJBB_DT_B03107_CSH_NEW$$

CREATE PROCEDURE PRO_TJBB_DT_B03107_CSH_NEW
/*************************************************
 * 浙江省出口退（免）税分类管理情况统计表
 * 20210205，金额栏保留整数，比率保留小数点后1位
 ************************************************/
(
  IN V_SWCODE VARCHAR(4000),
  IN V_SSNY VARCHAR(4000),
  OUT V_ERROR DECIMAL(38,10),
  OUT V_MSG VARCHAR(4000)
)
routine_body: BEGIN
  DECLARE LC_THISMONTH     VARCHAR(6);-- 当月
  DECLARE LC_THISYEAR      VARCHAR(6);-- 当年1月
  DECLARE LC_LASTMONTH     VARCHAR(6);-- 上年同期
  DECLARE LC_LASTYEAR      VARCHAR(6);-- 上年1月

  DECLARE LN_TSE_HJ        DECIMAL(16,4);-- 退税额合计
  DECLARE TSE_1_LAST       DECIMAL(16,4);
  DECLARE TSE_2_LAST       DECIMAL(16,4);
  DECLARE TSE_3_LAST       DECIMAL(16,4);
  DECLARE TSE_4_LAST       DECIMAL(16,4);
  DECLARE LC_SQL_UPDATEHZ  VARCHAR(4000);
  DECLARE LD_SYSDATE       DATETIME;

  SET V_ERROR =0;
  SET V_MSG = ' ';

  IF V_SSNY IS NOT NULL THEN
    SET LD_SYSDATE =STR_TO_DATE(ORA_CONCAT(V_SSNY, '01'), '%Y%m%d');
  ELSE
    SET LD_SYSDATE =CURRENT_TIMESTAMP;
  END IF;

  SET LC_THISMONTH =DATE_FORMAT(LD_SYSDATE, '%Y%m');
  SET LC_THISYEAR =ORA_CONCAT(DATE_FORMAT(LD_SYSDATE, '%Y'), '01');
  SET LC_LASTMONTH =DATE_FORMAT(DATE_ADD(LD_SYSDATE, INTERVAL -12 MONTH), '%Y%m');
  SET LC_LASTYEAR =ORA_CONCAT(DATE_FORMAT(DATE_ADD(LD_SYSDATE, INTERVAL -12 MONTH), '%Y'), '01');

  -- 0、清除原有制表数据，准备重新制表
  BEGIN
  DECLARE BJTS_SQLCODE_007 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_007 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_007 = MYSQL_ERRNO, BJTS_SQLERRM_007 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_007;
      SET V_MSG = BJTS_SQLERRM_007;
      LEAVE routine_body;

  END;
DELETE FROM TJBB_DT_B03107 WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;
    COMMIT;
  END;

  -- 1、计算并插入本年明细
  BEGIN
  DECLARE BJTS_SQLCODE_006 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_006 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_006 = MYSQL_ERRNO, BJTS_SQLERRM_006 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_006;
      SET V_MSG = BJTS_SQLERRM_006;
      LEAVE routine_body;

  END;
INSERT INTO TJBB_DT_B03107 (SSNY,BBLC,SWJGDM,SBHS_1,SBHS_2,SBHS_3,SBHS_4,TSE_1_LJ,TSE_2_LJ,TSE_3_LJ,TSE_4_LJ)
    WITH THISYEAR AS (SELECT A.XMFL, A.TS_AMT_ALL, IFNULL(B.FLGLCD, 'C') AS FLGLCD_B, IFNULL(C.KZXX, 'C') AS FLGLCD_C,
                             ROW_NUMBER() OVER (PARTITION BY A.SWCODE,A.XMFL,A.SSNY,A.SBYWBDM ORDER BY C.ST_DATE DESC) AS RN
                        FROM TJBB_FHXX_CPCODE A
                        LEFT JOIN GLXT_BB_SHXT_DJXX B ON A.XMFL=B.CPCODE
                        LEFT JOIN GS_DJ_CKTMSDAB_KZ C ON A.XMFL=C.CPCODE AND C.KZLX='FLGLCD' AND C.FLAG='1' AND ORA_CONCAT(A.SSNY, '01') BETWEEN DATE_FORMAT(C.ST_DATE, '%Y%m%d') AND DATE_FORMAT(C.END_DATE, '%Y%m%d')
                       WHERE A.SWCODE=V_SWCODE
                         AND A.SSNY BETWEEN LC_THISYEAR AND LC_THISMONTH)
    SELECT LC_THISMONTH, '01', V_SWCODE,
           COUNT(DISTINCT CASE WHEN FLGLCD_B='A' THEN XMFL ELSE NULL END),
           COUNT(DISTINCT CASE WHEN FLGLCD_B='B' THEN XMFL ELSE NULL END),
           COUNT(DISTINCT CASE WHEN FLGLCD_B='C' THEN XMFL ELSE NULL END),
           COUNT(DISTINCT CASE WHEN FLGLCD_B='D' THEN XMFL ELSE NULL END),
           ROUND(SUM(CASE WHEN FLGLCD_C='A' THEN TS_AMT_ALL ELSE 0 END)/10000,0),
           ROUND(SUM(CASE WHEN FLGLCD_C='B' THEN TS_AMT_ALL ELSE 0 END)/10000,0),
           ROUND(SUM(CASE WHEN FLGLCD_C='C' THEN TS_AMT_ALL ELSE 0 END)/10000,0),
           ROUND(SUM(CASE WHEN FLGLCD_C='D' THEN TS_AMT_ALL ELSE 0 END)/10000,0)
      FROM THISYEAR
     WHERE RN=1;
    COMMIT;
  END;

  -- 2、更新地区名称
  BEGIN
  DECLARE BJTS_SQLCODE_005 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_005 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_005 = MYSQL_ERRNO, BJTS_SQLERRM_005 = MESSAGE_TEXT;
      DO 0;

  END;
UPDATE TJBB_DT_B03107 AS T
       SET AREA=(SELECT S.SWJG_JC FROM DM_SWJG S WHERE S.SWJG_DM=T.SWJGDM)
     WHERE T.SWJGDM=V_SWCODE
       AND T.SSNY=LC_THISMONTH;
    COMMIT;
  END;

  -- 3、更新上年同期
  BEGIN
  DECLARE BJTS_SQLCODE_004 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_004 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_004 = MYSQL_ERRNO, BJTS_SQLERRM_004 = MESSAGE_TEXT;
      DO 0;

  END;
WITH LASTYEAR AS (SELECT A.XMFL, A.TS_AMT_ALL, IFNULL(B.FLGLCD, 'C') AS FLGLCD_B, IFNULL(C.KZXX, 'C') AS FLGLCD_C,
                             ROW_NUMBER() OVER (PARTITION BY A.SWCODE,A.XMFL,A.SSNY,A.SBYWBDM ORDER BY C.ST_DATE DESC) AS RN
                        FROM TJBB_FHXX_CPCODE A
                        LEFT JOIN GLXT_BB_SHXT_DJXX B ON A.XMFL=B.CPCODE
                        LEFT JOIN GS_DJ_CKTMSDAB_KZ C ON A.XMFL=C.CPCODE AND C.KZLX='FLGLCD' AND C.FLAG='1' AND ORA_CONCAT(A.SSNY, '01') BETWEEN DATE_FORMAT(C.ST_DATE, '%Y%m%d') AND DATE_FORMAT(C.END_DATE, '%Y%m%d')
                       WHERE A.SWCODE=V_SWCODE
                         AND A.SSNY BETWEEN LC_LASTYEAR AND LC_LASTMONTH)
    SELECT ROUND(SUM(CASE WHEN FLGLCD_C='A' THEN TS_AMT_ALL ELSE 0 END)/10000,0),
           ROUND(SUM(CASE WHEN FLGLCD_C='B' THEN TS_AMT_ALL ELSE 0 END)/10000,0),
           ROUND(SUM(CASE WHEN FLGLCD_C='C' THEN TS_AMT_ALL ELSE 0 END)/10000,0),
           ROUND(SUM(CASE WHEN FLGLCD_C='D' THEN TS_AMT_ALL ELSE 0 END)/10000,0)
      INTO TSE_1_LAST,TSE_2_LAST,TSE_3_LAST,TSE_4_LAST
      FROM LASTYEAR
     WHERE RN=1;
    UPDATE TJBB_DT_B03107 AS T
       SET TSE_1_LJ_LAST = (SELECT TSE_1_LAST),
    TSE_2_LJ_LAST = (SELECT TSE_2_LAST),
    TSE_3_LJ_LAST = (SELECT TSE_3_LAST),
    TSE_4_LJ_LAST = (SELECT TSE_4_LAST)
     WHERE T.SWJGDM=V_SWCODE
       AND T.SSNY=LC_THISMONTH;
    COMMIT;
  END;

  -- 4、同比计算
  BEGIN
  DECLARE BJTS_SQLCODE_003 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_003 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_003 = MYSQL_ERRNO, BJTS_SQLERRM_003 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_003;
      SET V_MSG = BJTS_SQLERRM_003;
      LEAVE routine_body;

  END;
UPDATE TJBB_DT_B03107
       SET TSE_1_TB = CASE WHEN IFNULL(TSE_1_LJ_LAST, 0)=0 THEN NULL ELSE ROUND(100 * TSE_1_LJ / TSE_1_LJ_LAST -100,1) END,
    TSE_2_TB = CASE WHEN IFNULL(TSE_2_LJ_LAST, 0)=0 THEN NULL ELSE ROUND(100 * TSE_2_LJ / TSE_2_LJ_LAST -100,1) END,
    TSE_3_TB = CASE WHEN IFNULL(TSE_3_LJ_LAST, 0)=0 THEN NULL ELSE ROUND(100 * TSE_3_LJ / TSE_3_LJ_LAST -100,1) END,
    TSE_4_TB = CASE WHEN IFNULL(TSE_4_LJ_LAST, 0)=0 THEN NULL ELSE ROUND(100 * TSE_4_LJ / TSE_4_LJ_LAST -100,1) END
     WHERE SWJGDM=V_SWCODE
       AND SSNY=LC_THISMONTH;
    COMMIT;
  END;

  -- 5、占比计算
  BEGIN
  DECLARE BJTS_SQLCODE_002 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_002 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_002 = MYSQL_ERRNO, BJTS_SQLERRM_002 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_002;
      SET V_MSG = BJTS_SQLERRM_002;
      LEAVE routine_body;

  END;
SELECT TSE_1_LJ + TSE_2_LJ + TSE_3_LJ + TSE_4_LJ
      INTO LN_TSE_HJ
      FROM TJBB_DT_B03107
     WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;

    UPDATE TJBB_DT_B03107 AS T
       SET TSE_1_ZB = CASE WHEN IFNULL(LN_TSE_HJ, 0)=0 THEN NULL ELSE ROUND(100 * TSE_1_LJ / LN_TSE_HJ,1) END,
    TSE_2_ZB = CASE WHEN IFNULL(LN_TSE_HJ, 0)=0 THEN NULL ELSE ROUND(100 * TSE_2_LJ / LN_TSE_HJ,1) END,
    TSE_3_ZB = CASE WHEN IFNULL(LN_TSE_HJ, 0)=0 THEN NULL ELSE ROUND(100 * TSE_3_LJ / LN_TSE_HJ,1) END,
    TSE_4_ZB = CASE WHEN IFNULL(LN_TSE_HJ, 0)=0 THEN NULL ELSE ROUND(100 * TSE_4_LJ / LN_TSE_HJ,1) END
     WHERE SWJGDM=V_SWCODE
       AND SSNY=LC_THISMONTH;
    COMMIT;
  END;

  -- 6、汇总栏初始化
  BEGIN
  DECLARE BJTS_SQLCODE_001 INT DEFAULT 0;
  DECLARE BJTS_SQLERRM_001 TEXT DEFAULT '';

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    GET DIAGNOSTICS CONDITION 1 BJTS_SQLCODE_001 = MYSQL_ERRNO, BJTS_SQLERRM_001 = MESSAGE_TEXT;
      SET V_ERROR = BJTS_SQLCODE_001;
      SET V_MSG = BJTS_SQLERRM_001;

  END;
SET LC_SQL_UPDATEHZ = 'UPDATE TJBB_DT_B03107 SET ';

    BEGIN
  DECLARE BJTS_CURSOR_DONE_001 BOOLEAN DEFAULT FALSE;
  DECLARE BJTS_LSF_XX_FNAME_001 LONGTEXT;
  DECLARE BJTS_CURSOR_001 CURSOR FOR
SELECT FNAME FROM TJBB_HEADER_COLS WHERE BBDM='B03107' AND FTYPE='NUMBER' ORDER BY SHOWORDER;
  OPEN BJTS_CURSOR_001;
  BJTS_CURSOR_LOOP_001: LOOP
    SET BJTS_CURSOR_DONE_001 = FALSE;
    BEGIN
      DECLARE CONTINUE HANDLER FOR NOT FOUND SET BJTS_CURSOR_DONE_001 = TRUE;
      FETCH BJTS_CURSOR_001 INTO BJTS_LSF_XX_FNAME_001;
    END;
    IF BJTS_CURSOR_DONE_001 THEN
      LEAVE BJTS_CURSOR_LOOP_001;
    END IF;
      SET LC_SQL_UPDATEHZ = ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(LC_SQL_UPDATEHZ, BJTS_LSF_XX_FNAME_001), '_HZ='), BJTS_LSF_XX_FNAME_001), ', ');

  END LOOP BJTS_CURSOR_LOOP_001;
  CLOSE BJTS_CURSOR_001;
END;

    SET LC_SQL_UPDATEHZ = ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(SUBSTR(LC_SQL_UPDATEHZ, 1, LENGTH(LC_SQL_UPDATEHZ)-2), ' WHERE SWJGDM='''), V_SWCODE), ''' AND SSNY='''), LC_THISMONTH), '''');

    SET @BJTS_DYNAMIC_SQL_001 = LC_SQL_UPDATEHZ;
PREPARE BJTS_DYNAMIC_STMT_001 FROM @BJTS_DYNAMIC_SQL_001;
EXECUTE BJTS_DYNAMIC_STMT_001;
DEALLOCATE PREPARE BJTS_DYNAMIC_STMT_001;
    COMMIT;
  END;

  LEAVE routine_body;
END$$

