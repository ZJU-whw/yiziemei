                'CKTS_SB_GJ_SBMX_LSB',NULL,NULL,T.SBXH,NULL,'GJZY_JHMX_KPRQ_FQTS','E','开票日期[' || DATE_FORMAT(T.KPRQ, '%Y-%m-%d') || ']企业处于放弃退（免）税权期间！','N',CURRENT_TIMESTAMP
