DELIMITER $$

DROP FUNCTION IF EXISTS FUNC_XXBD_CHECK_GCSBKPRQ$$

CREATE FUNCTION FUNC_XXBD_CHECK_GCSBKPRQ(V_KPRQ DATETIME)
RETURNS DECIMAL(38,10)
NOT DETERMINISTIC
READS SQL DATA
BEGIN

  IF V_KPRQ>=DATE'2016-01-01' AND V_KPRQ<=DATE'2017-03-14' THEN
    RETURN 1;
  END IF;
  IF V_KPRQ>=DATE'2019-01-01' AND V_KPRQ<=DATE'2020-03-01' THEN
    RETURN 1;
  END IF;
  IF V_KPRQ>=DATE'2021-01-01' AND V_KPRQ<=DATE'2021-06-22' THEN
    RETURN 1;
  END IF;
  RETURN 0;
END$$

DELIMITER ;
