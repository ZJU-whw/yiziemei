;
                  COMMIT;
                END IF;
                IF TIMESTAMPDIFF(MONTH, LSF_XX.QYRQ_SH, TRUNCATE(CURRENT_TIMESTAMP, 0))>2 THEN
                  INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                       SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_NEXTVAL('SEQ_XXBD_SHQ_YDID'),LC_YDOBJECT,
                              'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_BGD_QYGTS_CKRQ','E',
                              '出口货物报关单号[' || LSF_XX.CKBGDH || ']超过启运日两月，“业务类型”不应包含“QYGTS”！','N',CURRENT_TIMESTAMP
;
                  COMMIT;
                END IF;
                IF LSF_XX.QYGWDDBZ='Y' THEN
                  INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                       SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_NEXTVAL('SEQ_XXBD_SHQ_YDID'),LC_YDOBJECT,
                              'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_BGD_QYGTS_WDD','E',
                              '出口货物报关单号[' || LSF_XX.CKBGDH || ']未实际到达离境港，“业务类型”不应包含“QYGTS”！','N',CURRENT_TIMESTAMP
;
                  COMMIT;
                END IF;
              END;
            END IF;
          END;
        ELSE
          BEGIN
            IF (LSF_XX.CKRQ_SB<>LSF_XX.CKRQ_SH) AND (INSTR(LSF_XX.CKTMSYWLXDMJH,'BSQ')=0) THEN
              INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                   SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_NEXTVAL('SEQ_XXBD_SHQ_YDID'),LC_YDOBJECT,
                          'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_BGD_CKRQ','E',
                          '出口货物报关单号[' || LSF_XX.CKBGDH || ']出口日期[' || DATE_FORMAT(LSF_XX.CKRQ_SB, '%Y-%m-%d') || ']与电子信息中[' || DATE_FORMAT(LSF_XX.CKRQ_SH, '%Y-%m-%d') || ']不一致！','N',CURRENT_TIMESTAMP
;
              COMMIT;
            END IF;
            IF (LSF_XX.QYGBZ='Y' AND LSF_XX.QYGZCJGBZ='N') THEN
              INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                   SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_NEXTVAL('SEQ_XXBD_SHQ_YDID'),LC_YDOBJECT,
                          'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_BGD_QYGTS_NULL','E',
                          '出口货物报关单号[' || LSF_XX.CKBGDH || ']为启运港业务，目前尚未收到结关信息，“业务类型”应包含“QYGTS”！','N',CURRENT_TIMESTAMP
;
              COMMIT;
            END IF;
          END;
        END IF;

        IF (INSTR(LSF_XX.CKTMSYWLXDMJH,'BSQ')>0) THEN
          IF (LSF_XX.YSFS_DM<>'0') THEN
            INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                 SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_NEXTVAL('SEQ_XXBD_SHQ_YDID'),LC_YDOBJECT,
                        'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_BGD_BSQ_NOT','E',
                        '出口货物报关单号[' || LSF_XX.CKBGDH || ']非经保税区出口业务，“业务类型”不应包含“BSQ”！','N',CURRENT_TIMESTAMP
;
            COMMIT;
           ELSE
            BEGIN
              INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                   SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_NEXTVAL('SEQ_XXBD_SHQ_YDID'),LC_YDOBJECT,
