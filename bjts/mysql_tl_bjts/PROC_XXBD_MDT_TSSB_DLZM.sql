;
              COMMIT;
            END IF;
          END;
        END IF;

        IF (BJTS_LSF_XX_CKRQ_SB_002<>BJTS_LSF_XX_CKRQ_SH_002) AND (INSTR(BJTS_LSF_XX_CKTMSYWLXDMJH_002,'BSQ')=0) THEN
