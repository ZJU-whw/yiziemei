CREATE PROCEDURE PROC_XXBD_MDT_TSSB_DLZM
/*
  编制人:严国平
  编制日期:202009
  功能:信息比对（生产企业免抵退税）
  调整日期：20201106，1、对HZCJ不判断剩余数量和美元离岸价，2、对金额增加null判断，3、监管方式1200列入进料加工
  调整日期：20211111，与报关单疑点一致，1、调整MDT_CKHW_BGD_WDZXX监控条件，对红字冲减业务不判断；
