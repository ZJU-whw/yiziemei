                 FROM DUAL;
          COMMIT;
        END IF;
        IF (LSF_XX.FPYT_DM='1' AND LSF_XX.FPSJBZ='Y' AND LSF_XX.NXZCKBZ='N') THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_ZZSFP_YDK','E','代办退税发票[' || LSF_XX.DBTSWSPZHM || ']在电子信息中已勾选用于抵扣！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        END IF;

        IF LSF_XX.GHFNSRSBH IS NOT NULL THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_ZZSFP_XKFP','E','代办退税发票[' || LSF_XX.DBTSWSPZHM || ']在电子信息中为虚开增值税专用发票！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        END IF;
      END;
    END LOOP;
  END;

  BEGIN
    FOR LSF_XX IN (SELECT DISTINCT
                          A.SBXH,
                          A.WTDBTSSCQYNSRSBH,
                          A.CKRQ_1,
                          C.NSRSBH,
                          C.BACHBZ,
                          C.BACHRQ,
                          C.NSRRDSJQ,
                          C.NSRRDSJZ,
                          C.YBNSRZXGMNSRSJQ,
                          C.YBNSRZXGMNSRSJZ,
                          C.TZCKTMSQBZ,
                          C.TZCKTMSQQSRQ,
                          C.TZCKTMSQJZRQ,
                          C.TSGMSBZ,
                          C.TSGMSQSRQ,
                          C.TSGMSJZRQ,
                          C.FQCKTMSQBZ,
                          C.FQCKTMSQQSRQ,
                          C.FQCKTMSQJZRQ,
                          NVL(C.TSKHYHMC,'1') AS TSKHYHMC,
                          NVL(C.TSKHYHZH,'1') AS TSKHYHZH,
                          B.YHMC,
                          B.YHZH
                     FROM CKTS_SB_DB_TSSB_LSB A
                    INNER JOIN GS_DJ_CKTMSDAB B ON B.NSRDZDAH=V_IN_NSRDZDAH
                     LEFT JOIN CKTS_WBSJ_ZJ_SCWTDBBA C ON C.DJXH=V_IN_DJXH AND (C.NSRSBH=A.WTDBTSSCQYNSRSBH OR C.SHXYDM=A.WTDBTSSCQYNSRSBH)
                    WHERE A.SBID=V_IN_SBID) LOOP
      BEGIN
        IF (LSF_XX.NSRSBH IS NULL) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_WTFSH_DBBA','E','“未收到该委托代办退税生产企业”[' || LSF_XX.WTDBTSSCQYNSRSBH || ']的委托代办退税备案信息！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        ELSIF (LSF_XX.BACHBZ='Y' AND LSF_XX.CKRQ_1>LSF_XX.BACHRQ) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_WTFSH_TMSBA','E','“委托代办退税的生产企业”[' || LSF_XX.WTDBTSSCQYNSRSBH || ']已经办理备案撤回！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        ELSIF (LSF_XX.TSKHYHZH<>LSF_XX.YHZH) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_WTFSH_YHZH','E','“综服企业备案银行账号”[' || LSF_XX.YHZH || ']与委托代办退税备案信息中的账号”[' || LSF_XX.TSKHYHZH || ']不一致！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
/*        ELSIF (LSF_XX.TSKHYHMC<>LSF_XX.YHMC) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_WTFSH_YHZH','E','“综服企业备案银行名称”[' || LSF_XX.YHMC || ']与委托代办退税备案信息中的名称”[' || LSF_XX.TSKHYHMC || ']不一致！','N',SYSDATE
                 FROM DUAL;
          COMMIT;*/
        END IF;

        IF (LSF_XX.TZCKTMSQBZ IN ('Y','1') AND LSF_XX.CKRQ_1>LSF_XX.TZCKTMSQQSRQ AND LSF_XX.CKRQ_1<LSF_XX.TZCKTMSQJZRQ) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_CKRQ_TQQY_SC','E','出口日期[' || TO_CHAR(LSF_XX.CKRQ_1,'YYYY-MM-DD') || ']委托代办退税的生产企业处于出口退税停权期间！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        END IF;

        IF (LSF_XX.TSGMSBZ IN ('Y','1') AND LSF_XX.CKRQ_1>LSF_XX.TSGMSQSRQ AND LSF_XX.CKRQ_1<LSF_XX.TSGMSJZRQ) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_DB_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'WZF_DBTS_CKRQ_MSQY_SC','E','出口日期[' || TO_CHAR(LSF_XX.CKRQ_1,'YYYY-MM-DD') || ']委托代办退税的生产企业处于免税期间！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        END IF;

        IF (LSF_XX.FQCKTMSQBZ IN ('Y','1') AND LSF_XX.CKRQ_1>LSF_XX.FQCKTMSQQSRQ AND LSF_XX.CKRQ_1<LSF_XX.FQCKTMSQJZRQ) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
