CREATE OR REPLACE PROCEDURE PROC_XXBD_MDT_TSSB_DLZM
/*
  编制人:严国平
  编制日期:202009
  功能:信息比对（生产企业免抵退税）
  调整日期：20201106，1、对HZCJ不判断剩余数量和美元离岸价，2、对金额增加null判断，3、监管方式1200列入进料加工
  调整日期：20211111，与报关单疑点一致，1、调整MDT_CKHW_BGD_WDZXX监控条件，对红字冲减业务不判断；
                                        2、增加MDT_CKHW_DLZM_USDLAJ_CY、MDT_CKHW_DLZM_HZCJ_BYZ
                                        3、增加MDT_CKHW_DLCK_CKSL、MDT_CKHW_DLZM_USDLAJ
  调整日期：20211213，对疑点MDT_CKHW_DLZM_BYTS的校验逻辑进行修正，仅针对非红字冲减或红字冲减退运的业务进行判断
  调整日期：20211214，对疑点MDT_JLJG_SCH_NOJLJG的校验逻辑进行修正，同时判断企业是否填了加工贸易手册号或计划分配率
  调整日期：20230313，增加MDT_CKHW_DLZM_BSQ_BAQD、MDT_CKHW_DLZM_BSQ_BANR、MDT_CKHW_DLZM_RMBLAJ、MDT_CKHW_DLZM_HZCJ_TY疑点判断
 */
(
  V_IN_NSRDZDAH   IN  NUMBER, /*纳税人电子档案号*/
  V_IN_DJXH       IN  NUMBER, /*登记序号*/
  V_IN_SBYWBDM    IN  VARCHAR2, /*申报业务表代码*/
  V_IN_SSSQ       IN  VARCHAR2, /*申报年月*/
  V_IN_SBPC       IN  NUMBER, /*申报批次*/
  V_IN_SBID       IN  NUMBER, /*申报ID*/
  V_OUT_STATUS    OUT VARCHAR2, /*00:成功; 其他:执行失败*/
  V_OUT_MESSAGE   OUT VARCHAR2
)
AS
  LN_MXROW        NUMBER(10);
  LC_YDOBJECT     VARCHAR2(20);
  LN_CMCD_LEN     NUMBER(10);
  LN_ZHJHFPL      NUMBER(16,6);
BEGIN
  V_OUT_STATUS :='00';
  V_OUT_MESSAGE:=' ';


  --代理证明出口货物劳务明细表记录为空，不需要比对
  BEGIN
    SELECT COUNT(1)
      INTO LN_MXROW
      FROM CKTS_SB_MDT_TSSB_LSB T
     WHERE T.SBID=V_IN_SBID
       AND T.DLCKHWZMHM IS NOT NULL;
    IF LN_MXROW=0 THEN
      RETURN;
    END IF;
  END;
  LC_YDOBJECT :='代理证明';

  --获取进料加工企业最新调整计划分配律
  BEGIN
    SELECT ZHJHFPL
      INTO LN_ZHJHFPL
      FROM (SELECT CASE WHEN T.JHFPLV_NEW=0 THEN T.JHFPLV ELSE T.JHFPLV_NEW END AS ZHJHFPL
              FROM GS_JLJG_JHFPL T
             WHERE T.NSRDZDAH=V_IN_NSRDZDAH
             ORDER BY T.UPTIME DESC)
     WHERE ROWNUM=1;
  EXCEPTION
    WHEN OTHERS THEN
      LN_ZHJHFPL :=0;
  END;

  BEGIN
    INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
         SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,T.SBXH,NULL,'MDT_CKHW_DLZM_WDZXX','E','代理出口货物证明号[' || T.DLCKHWZMHM || ']无电子信息！','N',SYSDATE
           FROM CKTS_SB_MDT_TSSB_LSB T
          WHERE T.SBID=V_IN_SBID
            AND T.DLCKHWZMHM IS NOT NULL
            AND FUNC_XXBD_CHECK_YWLX(',' || T.CKTMSYWLXDMJH || ',') = 0
            AND INSTR(NVL(T.CKTMSYWLXDMJH,' '),'HZCJ')=0
            AND NOT EXISTS (SELECT 1 FROM CKTS_WBSJ_ZJ_DLCKHWZM S WHERE S.DJXH=V_IN_DJXH AND S.DLCKHWZMHM=T.DLCKHWZMHM);
    COMMIT;
  END;

  BEGIN
    FOR LSF_XX IN (SELECT A.SBXH,
                          A.DLCKHWZMHM,
                          B.BYTSBZ,
                          TRUNC(A.CKRQ_1,'DD') AS CKRQ_SB,
                          TRUNC(B.CKRQ_1,'DD') AS CKRQ_SH,
                          NVL(A.CKTMSYWLXDMJH,' ') AS CKTMSYWLXDMJH,
                          A.CKSP_DM AS CKSP_DM_SB,
                          B.CKSP_DM AS CKSP_DM_SH,
                          C.JGFS_DM,
                          C.JGFSTSLX_DM,
                          B.ZZMDGDQSZ_DM,
                          B.YSFS_DM,
                          A.CKSL AS CKSL_SB,
                          A.MYLAJ AS MYLAJ_SB,
                          A.RMBLAJ AS RMBLAJ_SB,
                          B.MYLAJ,
                          F.CKFPMYLAJ,
                          NVL(B.TSSBSL,0) AS TSSBSL,
                          NVL(B.TSSBMYLAJ,0) AS TSSBMYLAJ,
                          NVL(B.TSSBRMBLAJ,0) AS TSSBRMBLAJ,
                          A.JLJGSZCH,
                          A.TZHJHFPL,
                          G.SJFPL
                     FROM CKTS_SB_MDT_TSSB_LSB A
                    INNER JOIN CKTS_WBSJ_ZJ_DLCKHWZM B ON B.DJXH=V_IN_DJXH AND B.DLCKHWZMHM=A.DLCKHWZMHM
                     LEFT JOIN CKTS_DM_HGJGFS C ON C.JGFS_DM=B.JGFS_DM
                     LEFT JOIN CKTS_SB_MDT_CYSM_LSB F ON F.SBID=V_IN_SBID AND F.DLCKHWZMHM=A.DLCKHWZMHM
                     LEFT JOIN (SELECT NSRDZDAH, JGMYSCH, HXQSRQ, HXJZRQ, SJFPL, ROW_NUMBER() OVER (PARTITION BY NSRDZDAH, JGMYSCH, HXQSRQ, HXJZRQ ORDER BY LRRQ DESC) AS RN
                                  FROM GS_JLJG_HXJG) G ON G.NSRDZDAH=V_IN_NSRDZDAH AND G.JGMYSCH=A.JLJGSZCH AND RN=1 AND (SUBSTR(A.JLJGSZCH,1,1)='C' OR (A.CKRQ_1 BETWEEN G.HXQSRQ AND G.HXJZRQ))
                    WHERE A.SBID=V_IN_SBID
                      AND A.DLCKHWZMHM IS NOT NULL
                      AND FUNC_XXBD_CHECK_YWLX(',' || A.CKTMSYWLXDMJH || ',') = 0) LOOP
      BEGIN
        LC_YDOBJECT :='代理证明';
        
        IF (INSTR(LSF_XX.CKTMSYWLXDMJH,'HZCJ')>0) THEN
          IF (INSTR(LSF_XX.CKTMSYWLXDMJH,'HZCJ-TY')=0) THEN
            --20211111, 增加红字冲减与原申报数的比较
            BEGIN
              IF (LSF_XX.CKSL_SB + LSF_XX.TSSBSL <>0) THEN
                INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                     SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                            'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_HZCJ_BYZ','E',
                            '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']业务类型选择红字冲减，出口数量与已申报出口数量[' || LSF_XX.TSSBSL || ']不一致！','N',SYSDATE
                       FROM DUAL;
                COMMIT;
              END IF;
              IF (LSF_XX.MYLAJ_SB + LSF_XX.TSSBMYLAJ <>0) THEN
                INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                     SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                            'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_HZCJ_BYZ','E',
                            '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']业务类型选择红字冲减，美元离岸价与已申报美元离岸价[' || LSF_XX.TSSBMYLAJ || ']不一致！','N',SYSDATE
                       FROM DUAL;
                COMMIT;
              END IF;
              IF (LSF_XX.RMBLAJ_SB + LSF_XX.TSSBRMBLAJ <>0) THEN
                INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                     SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                            'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_HZCJ_BYZ','E',
                            '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']业务类型选择红字冲减，人民币离岸价与已申报人民币离岸价[' || LSF_XX.TSSBRMBLAJ || ']不一致！','N',SYSDATE
                       FROM DUAL;
                COMMIT;
              END IF;
            END;
          ELSE
            --20230314, 增加红字冲减-退运与原退运证明一致性的提示
            INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                 SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                        'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_HZCJ_TY','I',
                        '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']业务类型选择红字冲减-退运，请核实退运冲减的人民币离岸价与应冲减的退运证明对应的实际出口销售额是否一致！','Y',SYSDATE
                   FROM DUAL;
            COMMIT;
          END IF;
        ELSE
          BEGIN
            --20211111，与MDT_CKHW_BGD_USDLAJ_CY一致
            IF (ABS(LSF_XX.MYLAJ_SB-LSF_XX.MYLAJ)>1) AND (ABS(LSF_XX.MYLAJ_SB-LSF_XX.MYLAJ)>0.05 * LSF_XX.MYLAJ) AND (LSF_XX.CKFPMYLAJ IS NULL) THEN
                INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                     SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                            'CKTS_SB_MDT_TSSB_LSB','CKTS_SB_MDT_CYSM_LSB',NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_USDLAJ_CY','E',
                            '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']美元离岸价[' || LSF_XX.MYLAJ_SB || ']超过电子信息中[' || LSF_XX.MYLAJ || ']合理范围，需提供《出口货物离岸价差异原因说明表》！','N',SYSDATE
                       FROM DUAL;
              COMMIT;
            END IF;
            -- 20211213，对红字冲减、红字冲减退运业务，不判断已经标注“不予退税”
            IF (LSF_XX.BYTSBZ='Y') THEN
              INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                   SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                          'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_BYTS','E',
                          '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']已被标注为“不予退税”！','N',SYSDATE
                     FROM DUAL;
              COMMIT;
            END IF;
          END;
        END IF;

        IF (LSF_XX.CKRQ_SB<>LSF_XX.CKRQ_SH) AND (INSTR(LSF_XX.CKTMSYWLXDMJH,'BSQ')=0) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_CKRQ','E',
                      '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']出口日期[' || TO_CHAR(LSF_XX.CKRQ_SB,'YYYY-MM-DD') || ']与电子信息中[' || TO_CHAR(LSF_XX.CKRQ_SH,'YYYY-MM-DD') || ']不一致！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        END IF;

        LN_CMCD_LEN := CASE WHEN LENGTH(LSF_XX.CKSP_DM_SB) > LENGTH(LSF_XX.CKSP_DM_SH) THEN LENGTH(LSF_XX.CKSP_DM_SH) ELSE LENGTH(LSF_XX.CKSP_DM_SB) END;
        IF SUBSTR(LSF_XX.CKSP_DM_SB,1,LN_CMCD_LEN)<>SUBSTR(LSF_XX.CKSP_DM_SH,1,LN_CMCD_LEN) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_SPDM','E',
                      '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']商品代码[' || LSF_XX.CKSP_DM_SB || ']与电子信息中[' || LSF_XX.CKSP_DM_SH || ']不一致！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        END IF;

        IF (TRIM(LSF_XX.JGFS_DM) IS NULL) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_MYXZ_BCZ','E',
                      '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']在电子信息中监管方式不存在！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        ELSIF (TRIM(LSF_XX.JGFSTSLX_DM)='0') THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_MYXZ_BTS','E',
                      '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']在电子信息中监管方式[' || LSF_XX.JGFS_DM || ']不退税！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        END IF;

        IF (INSTR(LSF_XX.CKTMSYWLXDMJH,'DWCB')>0 AND LSF_XX.JGFS_DM<>'3422' AND LSF_XX.JGFS_DM<>'22') THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_DWCB_NOT','E',
                      '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']非对外承包业务，“业务类型”不应包含“DWCB”！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        END IF;
        IF (INSTR(LSF_XX.CKTMSYWLXDMJH,'DWCB')=0 AND (LSF_XX.JGFS_DM='3422' OR LSF_XX.JGFS_DM='22')) THEN
          INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
               SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                      'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_DWCB_NULL','E',
                      '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']为对外承包业务，“业务类型”应包含“DWCB”！','N',SYSDATE
                 FROM DUAL;
          COMMIT;
        END IF;

        IF (INSTR(LSF_XX.CKTMSYWLXDMJH,'BSQ')>0) THEN
          IF (LSF_XX.YSFS_DM<>'0') THEN
            INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                 SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                        'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_BSQ_NOT','E',
                        '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']非经保税区出口业务，“业务类型”不应包含“BSQ”！','N',SYSDATE
                   FROM DUAL;
            COMMIT;
          ELSE
            BEGIN
              INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                   SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                          'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_BSQ_BAQD','I',
                          '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']业务类型包含保税区BSQ，请核实是否附送《出境货物备案清单》！','Y',SYSDATE
                     FROM DUAL;
              COMMIT;
              INSERT INTO CKTS_XXBD_SHQ_YDXX(DJXH,SBYWB_DM,SSSQ,SBPC,SBID,ERR_LY,XH,ERR_OBJ,GLYWB1,GLYWB2,GLYWB3,GLYWZ1,GLYWZ2,YDCODE,ERR_LEV,ERR_MSG,PASS_FLAG,CRTIME)
                   SELECT V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,'1',SEQ_XXBD_SHQ_YDID.NEXTVAL,LC_YDOBJECT,
                          'CKTS_SB_MDT_TSSB_LSB',NULL,NULL,LSF_XX.SBXH,NULL,'MDT_CKHW_DLZM_BSQ_BANR','I',
                          '代理出口货物证明号[' || LSF_XX.DLCKHWZMHM || ']业务类型包含保税区BSQ，请核实出境货物备案清单的内容是否与报关单相关内容相符,出口日期填报是否准确！','Y',SYSDATE
                     FROM DUAL;
              COMMIT;
            END;
          END IF;
        END IF;
