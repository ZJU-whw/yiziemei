CREATE OR REPLACE PROCEDURE PROC_XXBD_XFS
/*
  编制人:严国平
  编制日期:202010
  功能:信息比对（出口非自产货物退消费税）
  修改日期：20220615，根据2022年9号公告，合并收汇与不能收汇
 */
(
  V_IN_NSRDZDAH   IN  NUMBER, /*纳税人电子档案号*/
  V_IN_DJXH       IN  NUMBER, /*登记序号*/
  V_IN_SBYWBDM    IN  VARCHAR2, /*申报业务表代码*/
  V_IN_SSSQ       IN  VARCHAR2, /*申报年月*/
  V_IN_SBPC       IN  NUMBER, /*申报批次*/
  V_IN_SBID       IN  NUMBER, /*申报ID*/
  V_OUT_STATUS    OUT VARCHAR2, /*00:成功; 其他:执行失败*/
  V_OUT_MESSAGE   OUT VARCHAR2
)
AS
  LDT_TODAY       DATE;

  LC_QYHGDM       VARCHAR2(20);
  LC_QYLXDM       VARCHAR2(20);
  LC_TSJSFSDM     VARCHAR2(20);
  LC_WMZHFWQYBZ   VARCHAR2(20);
  LC_SFYSFW       VARCHAR2(20);
  LC_YSFW         VARCHAR2(50);
  LC_YSFS         VARCHAR2(50);
  LC_YFSJ         VARCHAR2(50);
  LC_ZXFLAG       VARCHAR2(20);

  LN_CPCODEKZ     NUMBER(10);
  LC_KZXX         VARCHAR2(20);
  LN_TGSHZL       NUMBER(10);
  LC_FLGLCD       VARCHAR2(20);
  LN_ROWNUM_CKMX  NUMBER(10);
  LN_ROWNUM_CKSH  NUMBER(10);
  LN_ROWNUM_CQSB  NUMBER(10);
BEGIN
  V_OUT_STATUS :='00';
  V_OUT_MESSAGE:=' ';
  LDT_TODAY:=TRUNC(SYSDATE,'DD');

  IF V_IN_SSSQ>TO_CHAR(SYSDATE,'YYYYMM') THEN
    BEGIN
      V_OUT_STATUS :='05';
      V_OUT_MESSAGE:='申报所属时期超出合理范围！';
      RETURN;
    END;
  END IF;

  --取各申报明细表数据记录
  BEGIN
    SELECT COUNT(1)
      INTO LN_ROWNUM_CKMX
      FROM CKTS_SB_FZC_SBMX_LSB
     WHERE SBID=V_IN_SBID;
    SELECT COUNT(1)
      INTO LN_ROWNUM_CKSH
      FROM CKTS_SB_FZC_CKSH_LSB
     WHERE SBID=V_IN_SBID;
    SELECT COUNT(1)
      INTO LN_ROWNUM_CQSB
      FROM CKTS_SB_FZC_SBMX_LSB
     WHERE SBID=V_IN_SBID
       AND FUNC_XXBD_CHECK_NEEDSH(',' || CKTMSYWLXDMJH || ',') = 1
       AND (((TO_DATE(TO_CHAR(SYSDATE,'YYYY')||'0420','YYYYMMDD')<TRUNC(SYSDATE,'DD')) AND (KPRQ<TRUNC(SYSDATE,'YY'))) OR (KPRQ<ADD_MONTHS(TRUNC(SYSDATE,'YY'),-12)));
  EXCEPTION
    WHEN OTHERS THEN
      V_OUT_STATUS :='06';
      V_OUT_MESSAGE:='查询申报记录数据失败！';
      RETURN;
  END;
  IF LN_ROWNUM_CKMX=0 THEN
    BEGIN
      V_OUT_STATUS :='07';
      V_OUT_MESSAGE:='申报数据为空！';
      RETURN;
    END;
  END IF;

  --查询企业基本信息
  BEGIN
    SELECT T.QYHGDM, T.QYLX_DM, T.TSJSFS_DM, T.WMZHFWQYBZ, T.SFYSFW, T.YSFW, T.YSFS, T.YFSJ, T.ZX_FLAG
      INTO LC_QYHGDM, LC_QYLXDM, LC_TSJSFSDM, LC_WMZHFWQYBZ, LC_SFYSFW, LC_YSFW, LC_YSFS, LC_YFSJ, LC_ZXFLAG
      FROM GS_DJ_CKTMSDAB T
     WHERE T.NSRDZDAH=V_IN_NSRDZDAH;
  EXCEPTION
    WHEN OTHERS THEN
      V_OUT_STATUS :='08';
      V_OUT_MESSAGE:='企业当前未进行出口退（免）税备案，不允许申报除出口退（免）税备案以外的其他业务！';
      RETURN;
  END;
  IF LC_ZXFLAG='Y' THEN
    BEGIN
      V_OUT_STATUS :='09';
      V_OUT_MESSAGE:='企业当前已出口退（免）税备案撤回，不允许申报除出口退（免）税备案以外的其他业务！';
      RETURN;
    END;
  END IF;

  --取企业的FLGLCD信息, TGSHZL信息，判断是否需要申报收汇
  LN_CPCODEKZ:=FUNC_XXBD_QUERY_CPCODEKZ(V_IN_NSRDZDAH,'FLGLCD',LDT_TODAY,LC_FLGLCD);
  IF LN_CPCODEKZ=0 THEN
    BEGIN
      V_OUT_STATUS :='10';
      V_OUT_MESSAGE:='查询出口企业分类管理类型出错！';
      RETURN;
    END;
  END IF;

  IF ((LC_QYLXDM<>'1' AND LC_QYLXDM<>'2') OR LC_TSJSFSDM<>'1') THEN
    BEGIN
      V_OUT_STATUS :='11';
      V_OUT_MESSAGE:='备案信息中企业类型、退免税计算方法与当前申报业务冲突！';
      RETURN;
    END;
  END IF;

  LN_CPCODEKZ:=FUNC_XXBD_QUERY_CPCODEKZ(V_IN_NSRDZDAH,'YBNSRRD',LDT_TODAY,LC_KZXX);
  IF LN_CPCODEKZ=0 THEN
    BEGIN
      V_OUT_STATUS :='12';
      V_OUT_MESSAGE:='企业当前非增值税一般纳税人，不允许申报出口退（免）税业务！';
      RETURN;
    END;
  END IF;
  LN_CPCODEKZ:=FUNC_XXBD_QUERY_CPCODEKZ(V_IN_NSRDZDAH,'TQQY',LDT_TODAY,LC_KZXX);
  IF LN_CPCODEKZ=1 THEN
    BEGIN
      V_OUT_STATUS :='13';
      V_OUT_MESSAGE:='企业当前处于出口退税停权期间，不允许申报出口退（免）税业务！';
      RETURN;
    END;
  END IF;
  LN_CPCODEKZ:=FUNC_XXBD_QUERY_CPCODEKZ(V_IN_NSRDZDAH,'FQTSSXMS',LDT_TODAY,LC_KZXX);
  IF LN_CPCODEKZ=1 AND LN_ROWNUM_CKMX>0 THEN
    BEGIN
      V_OUT_STATUS :='14';
      V_OUT_MESSAGE:='企业当前处于放弃退（免）税权选择免税期间，不允许申报出口货物劳务免退税业务！';
      RETURN;
    END;
  END IF;
  LN_CPCODEKZ:=FUNC_XXBD_QUERY_CPCODEKZ(V_IN_NSRDZDAH,'FQTSSXZS',LDT_TODAY,LC_KZXX);
  IF LN_CPCODEKZ=1 AND LN_ROWNUM_CKMX>0 THEN
    BEGIN
      V_OUT_STATUS :='15';
      V_OUT_MESSAGE:='企业当前处于放弃退（免）税权选择征税期间，不允许申报出口货物劳务免退税业务！';
      RETURN;
    END;
  END IF;
  LN_CPCODEKZ:=FUNC_XXBD_QUERY_CPCODEKZ(V_IN_NSRDZDAH,'FQTMS',LDT_TODAY,LC_KZXX);
  IF LN_CPCODEKZ=1 AND LN_ROWNUM_CKMX>0 THEN
    BEGIN
      V_OUT_STATUS :='16';
      V_OUT_MESSAGE:='企业当前处于放弃退（免）税权期间，不允许申报出口货物劳务免退税业务！';
      RETURN;
    END;
  END IF;

  LN_TGSHZL:=FUNC_XXBD_QUERY_CPCODEKZ(V_IN_NSRDZDAH,'TGSHZL',LDT_TODAY,LC_KZXX);
  IF (LC_FLGLCD='D') AND LN_ROWNUM_CKMX>0 AND LN_ROWNUM_CKSH=0 THEN
    BEGIN
      V_OUT_STATUS :='27';
      V_OUT_MESSAGE:='出口退（免）税管理类别为四类的企业，申报出口退免税时必须申报收汇情况表！';
      RETURN;
    END;
  ELSIF (LN_TGSHZL>0) AND LN_ROWNUM_CKMX>0 AND LN_ROWNUM_CKSH=0 THEN
    BEGIN
      V_OUT_STATUS :='28';
      V_OUT_MESSAGE:='被认定为需提供收汇资料的企业，申报出口退免税时必须申报收汇情况表！';
      RETURN;
    END;
  ELSIF (LN_ROWNUM_CQSB>0) AND LN_ROWNUM_CKMX>0 AND LN_ROWNUM_CKSH=0 THEN
    BEGIN
      V_OUT_STATUS :='29';
      V_OUT_MESSAGE:='超期申报数据，申报出口退免税时必须申报收汇情况表！';
      RETURN;
    END;
  END IF;

  BEGIN
    PROC_XXBD_XFS_TSSB(V_IN_NSRDZDAH,V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,V_OUT_STATUS,V_OUT_MESSAGE);
  EXCEPTION
    WHEN OTHERS THEN
      V_OUT_STATUS :='51';
      V_OUT_MESSAGE:='出口非自产货物退消费税明细自检出错：'||SQLCODE||' - '||SQLERRM;
      RETURN;
  END;

  BEGIN
    PROC_XXBD_XFS_TSSB_BGD(V_IN_NSRDZDAH,V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,V_OUT_STATUS,V_OUT_MESSAGE);
  EXCEPTION
    WHEN OTHERS THEN
      V_OUT_STATUS :='52';
      V_OUT_MESSAGE:='出口报关单自检出错：'||SQLCODE||' - '||SQLERRM;
      RETURN;
  END;

  BEGIN
    PROC_XXBD_XFS_TSSB_DLZM(V_IN_NSRDZDAH,V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,V_OUT_STATUS,V_OUT_MESSAGE);
  EXCEPTION
    WHEN OTHERS THEN
      V_OUT_STATUS :='53';
      V_OUT_MESSAGE:='代理出口证明自检出错：'||SQLCODE||' - '||SQLERRM;
      RETURN;
  END;

  BEGIN
    PROC_XXBD_XFS_TSSB_JKXFS(V_IN_NSRDZDAH,V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,V_OUT_STATUS,V_OUT_MESSAGE);
  EXCEPTION
    WHEN OTHERS THEN
      V_OUT_STATUS :='54';
      V_OUT_MESSAGE:='海关进口消费税缴款书自检出错：'||SQLCODE||' - '||SQLERRM;
      RETURN;
  END;

  BEGIN
    PROC_XXBD_XFS_TSSB_ZJJKS(V_IN_NSRDZDAH,V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,V_OUT_STATUS,V_OUT_MESSAGE);
  EXCEPTION
    WHEN OTHERS THEN
      V_OUT_STATUS :='55';
      V_OUT_MESSAGE:='总局税收缴款书自检出错：'||SQLCODE||' - '||SQLERRM;
      RETURN;
  END;

  BEGIN
    PROC_XXBD_XFS_CKSH(V_IN_NSRDZDAH,V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,V_OUT_STATUS,V_OUT_MESSAGE);
  EXCEPTION
    WHEN OTHERS THEN
      V_OUT_STATUS :='62';
      V_OUT_MESSAGE:='出口收汇申报资料自检出错：'||SQLCODE||' - '||SQLERRM;
      RETURN;
  END;

  BEGIN
    PROC_XXBD_XFS_HGSPTZ(V_IN_NSRDZDAH,V_IN_DJXH,V_IN_SBYWBDM,V_IN_SSSQ,V_IN_SBPC,V_IN_SBID,V_OUT_STATUS,V_OUT_MESSAGE);
  EXCEPTION
    WHEN OTHERS THEN
      V_OUT_STATUS :='63';
      V_OUT_MESSAGE:='海关商品代码调整表自检出错：'||SQLCODE||' - '||SQLERRM;
      RETURN;
  END;

END;
