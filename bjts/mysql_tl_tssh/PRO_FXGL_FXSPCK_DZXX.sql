CREATE PROCEDURE PRO_FXGL_FXSPCK_DZXX()
/*
 * 风险商品出口电子信息提取
 * 20250331，根据省局李裕军局长意见，对市场采购业务不做风险商品出口短信提醒
 */
routine_body: BEGIN
  DECLARE LD_BEGINDATE      DATETIME;

  SELECT ORA_DATE_ADD(MAX(T.SJTB_SJ), -(3)) INTO LD_BEGINDATE FROM CKTS_WBSJ_HG_BGD T;

  BEGIN
  DECLARE BJTS_CURSOR_DONE_002 BOOLEAN DEFAULT FALSE;
  DECLARE BJTS_CUR_FXGZ_GZ_MC_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_FXMS_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_FW_SWJG_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_SPDM_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_SPMC_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_GGXH_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_CKKA_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_CKGB_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_HYD_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_DJQ_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_DJZ_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_ZJQ_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_ZJZ_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_YXQZ_002 LONGTEXT;
  DECLARE BJTS_CUR_FXGZ_GZ_DXTXBZ_002 LONGTEXT;
  DECLARE BJTS_CURSOR_002 CURSOR FOR
SELECT GZ_MC,GZ_FXMS,GZ_FW_SWJG,GZ_SPDM,GZ_SPMC,GZ_GGXH,GZ_CKKA,GZ_CKGB,GZ_HYD,GZ_DJQ,GZ_DJZ,GZ_ZJQ,GZ_ZJZ,GZ_YXQZ,GZ_DXTXBZ
                     FROM FXGL_SZ_SPFXCK
                    WHERE GZ_FW_DATA IN ('1','3') -- 规则适用业务范围：1出口电子信息+3同时适用
                      AND QYBJ='Y' -- 规则启用标记：Y
                      AND IFNULL(GZ_YXQZ, CAST('2100-12-31' AS DATE))>CURRENT_TIMESTAMP -- 规则有效期止：NULL或大于当前日期;
  OPEN BJTS_CURSOR_002;
  BJTS_CURSOR_LOOP_002: LOOP
    SET BJTS_CURSOR_DONE_002 = FALSE;
    BEGIN
      DECLARE CONTINUE HANDLER FOR NOT FOUND SET BJTS_CURSOR_DONE_002 = TRUE;
      FETCH BJTS_CURSOR_002 INTO BJTS_CUR_FXGZ_GZ_MC_002, BJTS_CUR_FXGZ_GZ_FXMS_002, BJTS_CUR_FXGZ_GZ_FW_SWJG_002, BJTS_CUR_FXGZ_GZ_SPDM_002, BJTS_CUR_FXGZ_GZ_SPMC_002, BJTS_CUR_FXGZ_GZ_GGXH_002, BJTS_CUR_FXGZ_GZ_CKKA_002, BJTS_CUR_FXGZ_GZ_CKGB_002, BJTS_CUR_FXGZ_GZ_HYD_002, BJTS_CUR_FXGZ_GZ_DJQ_002, BJTS_CUR_FXGZ_GZ_DJZ_002, BJTS_CUR_FXGZ_GZ_ZJQ_002, BJTS_CUR_FXGZ_GZ_ZJZ_002, BJTS_CUR_FXGZ_GZ_YXQZ_002, BJTS_CUR_FXGZ_GZ_DXTXBZ_002;
    END;
    IF BJTS_CURSOR_DONE_002 THEN
      LEAVE BJTS_CURSOR_LOOP_002;
    END IF;
    BEGIN
      -- 规则中所有设置为空，无效规则挑过
      IF BJTS_CUR_FXGZ_GZ_SPDM_002 IS NULL AND BJTS_CUR_FXGZ_GZ_SPMC_002 IS NULL AND BJTS_CUR_FXGZ_GZ_GGXH_002 IS NULL
         AND BJTS_CUR_FXGZ_GZ_CKKA_002 IS NULL AND BJTS_CUR_FXGZ_GZ_CKGB_002 IS NULL AND BJTS_CUR_FXGZ_GZ_HYD_002 IS NULL
         AND BJTS_CUR_FXGZ_GZ_DJQ_002 IS NULL AND BJTS_CUR_FXGZ_GZ_DJZ_002 IS NULL AND BJTS_CUR_FXGZ_GZ_ZJQ_002 IS NULL AND BJTS_CUR_FXGZ_GZ_ZJZ_002 IS NULL THEN
        ITERATE BJTS_CURSOR_LOOP_002;
      END IF;

      -- 根据风险规则扫描出口电子信息
      BEGIN
  DECLARE BJTS_CURSOR_DONE_001 BOOLEAN DEFAULT FALSE;
  DECLARE BJTS_CUR_FXSJ_DJXH_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_CKBGDH_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_MYLAJ_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_CKNY_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_CKSP_DM_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_CKRQ_1_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_CKBGD18_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_HGSPMC_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_NSRDZDAH_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_SWJG_DM_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_NSRSBH_001 LONGTEXT;
  DECLARE BJTS_CUR_FXSJ_NSRMC_001 LONGTEXT;
  DECLARE BJTS_CURSOR_001 CURSOR FOR
SELECT T.DJXH,T.CKBGDH,T.MYLAJ,T.CKNY,T.CKSP_DM,T.CKRQ_1,SUBSTR(T.CKBGDH,1,18) AS CKBGD18,T.HGSPMC,
                              S.NSRDZDAH,S.SWJG_DM,IFNULL(S.SHXYNO, S.NSRDJNO) AS NSRSBH,S.NSRMC
                         FROM CKTS_WBSJ_HG_BGD T
                        INNER JOIN GS_DJ_CKTMSDAB S ON S.CPCODE=T.DJXH
                        WHERE T.JGFS_DM<>'1039'
                          AND T.SJTB_SJ>=LD_BEGINDATE
                          AND (T.TSSWJG_DM_1 LIKE ORA_CONCAT(BJTS_CUR_FXGZ_GZ_FW_SWJG_002, '%'))
                          AND (BJTS_CUR_FXGZ_GZ_SPDM_002 IS NULL OR
                              (SUBSTR(BJTS_CUR_FXGZ_GZ_SPDM_002,1,1)='!' AND NOT REGEXP_LIKE(T.CKSP_DM,SUBSTR(BJTS_CUR_FXGZ_GZ_SPDM_002,2))) OR
                              (SUBSTR(BJTS_CUR_FXGZ_GZ_SPDM_002,1,1)<>'!' AND REGEXP_LIKE(T.CKSP_DM,BJTS_CUR_FXGZ_GZ_SPDM_002)))
                          AND (BJTS_CUR_FXGZ_GZ_SPMC_002 IS NULL OR REGEXP_LIKE(T.HGSPMC,BJTS_CUR_FXGZ_GZ_SPMC_002))
                          AND (BJTS_CUR_FXGZ_GZ_GGXH_002 IS NULL OR REGEXP_LIKE(T.GGXH,BJTS_CUR_FXGZ_GZ_GGXH_002))
                          AND (BJTS_CUR_FXGZ_GZ_CKKA_002 IS NULL OR REGEXP_LIKE(T.HGGQKA_DM,BJTS_CUR_FXGZ_GZ_CKKA_002))
                          AND (BJTS_CUR_FXGZ_GZ_CKGB_002 IS NULL OR REGEXP_LIKE(T.MYGDQSZ_DM,BJTS_CUR_FXGZ_GZ_CKGB_002))
                          AND (BJTS_CUR_FXGZ_GZ_HYD_002 IS NULL OR
                              (SUBSTR(BJTS_CUR_FXGZ_GZ_HYD_002,1,1)='!' AND NOT REGEXP_LIKE(T.HZDWDQ_DM,SUBSTR(BJTS_CUR_FXGZ_GZ_HYD_002,2))) OR
                              (SUBSTR(BJTS_CUR_FXGZ_GZ_HYD_002,1,1)<>'!' AND REGEXP_LIKE(T.HZDWDQ_DM,BJTS_CUR_FXGZ_GZ_HYD_002)))
                          AND (BJTS_CUR_FXGZ_GZ_DJQ_002 IS NULL OR (CASE T.CKSL WHEN 0 THEN 0 ELSE T.MYLAJ/T.CKSL END)>BJTS_CUR_FXGZ_GZ_DJQ_002)
                          AND (BJTS_CUR_FXGZ_GZ_DJZ_002 IS NULL OR (CASE T.CKSL WHEN 0 THEN 0 ELSE T.MYLAJ/T.CKSL END)<BJTS_CUR_FXGZ_GZ_DJZ_002)
                          AND (BJTS_CUR_FXGZ_GZ_ZJQ_002 IS NULL OR T.MYLAJ>BJTS_CUR_FXGZ_GZ_ZJQ_002)
                          AND (BJTS_CUR_FXGZ_GZ_ZJZ_002 IS NULL OR T.MYLAJ<BJTS_CUR_FXGZ_GZ_ZJZ_002);
  OPEN BJTS_CURSOR_001;
  BJTS_CURSOR_LOOP_001: LOOP
    SET BJTS_CURSOR_DONE_001 = FALSE;
    BEGIN
      DECLARE CONTINUE HANDLER FOR NOT FOUND SET BJTS_CURSOR_DONE_001 = TRUE;
      FETCH BJTS_CURSOR_001 INTO BJTS_CUR_FXSJ_DJXH_001, BJTS_CUR_FXSJ_CKBGDH_001, BJTS_CUR_FXSJ_MYLAJ_001, BJTS_CUR_FXSJ_CKNY_001, BJTS_CUR_FXSJ_CKSP_DM_001, BJTS_CUR_FXSJ_CKRQ_1_001, BJTS_CUR_FXSJ_CKBGD18_001, BJTS_CUR_FXSJ_HGSPMC_001, BJTS_CUR_FXSJ_NSRDZDAH_001, BJTS_CUR_FXSJ_SWJG_DM_001, BJTS_CUR_FXSJ_NSRSBH_001, BJTS_CUR_FXSJ_NSRMC_001;
    END;
    IF BJTS_CURSOR_DONE_001 THEN
      LEAVE BJTS_CURSOR_LOOP_001;
    END IF;
        BEGIN
          -- TL_ADMIN.YJ_DATA_YJXX，态势感知风险管理，所有风险数据往这张表写数据
          INSERT INTO YJ_DATA_YJXX(
                      TBPC,ID,SBID,NSRDZDAH,CJ_DATE,YJCODE,ZBCODE,YJ_OBJECT,YJ_COUNT,YJ_AMT,YJ_RECORD,YJ_MSG,SBYM,SWFLAG,QYFLAG,BMDFLAG)
               SELECT 0,SEQ_NEXTVAL('SEQ_YJ_DATA_YJXX'),0,BJTS_CUR_FXSJ_NSRDZDAH_001,CURRENT_TIMESTAMP,'140','14001',BJTS_CUR_FXSJ_CKSP_DM_001,1,BJTS_CUR_FXSJ_MYLAJ_001,BJTS_CUR_FXSJ_CKBGDH_001,
                      ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT(ORA_CONCAT('风险商品出口(规则：', IFNULL(BJTS_CUR_FXGZ_GZ_MC_002, BJTS_CUR_FXGZ_GZ_FXMS_002)), ')，报关单号('), BJTS_CUR_FXSJ_CKBGDH_001), ')，商品代码('), BJTS_CUR_FXSJ_CKSP_DM_001), ')，商品名称('), BJTS_CUR_FXSJ_CKSP_DM_001), ')，出口美元金额'), BJTS_CUR_FXSJ_MYLAJ_001), ')'),
                      BJTS_CUR_FXSJ_CKNY_001,1,0,0

                WHERE NOT EXISTS (SELECT 1
                                    FROM YJ_DATA_YJXX A
                                   WHERE A.SBID=0 AND A.NSRDZDAH=BJTS_CUR_FXSJ_NSRDZDAH_001
                                     AND A.YJCODE='140' AND A.ZBCODE='14001'
                                     AND A.YJ_RECORD=BJTS_CUR_FXSJ_CKBGDH_001)
                  AND NOT EXISTS (SELECT 1
                                      FROM YJ_CS_BMD B
                                      LEFT JOIN YJ_CS_BMD_SUB C ON C.BMDID=B.ID
                                     WHERE B.NSRDZDAH=BJTS_CUR_FXSJ_NSRDZDAH_001
                                       AND B.YJCODE='140'
                                       AND (B.OBJFLAG='0' OR C.YJ_OBJECT=BJTS_CUR_FXGZ_GZ_MC_002));
          -- TL_TSSH.JKGL_GY_FXSM_HGCK，原三三智检风险出口数据，待迁移
          INSERT INTO JKGL_GY_FXSM_HGCK(DJXH,CKBGDH,SMRQ,FXGZ)
               SELECT BJTS_CUR_FXSJ_DJXH_001,BJTS_CUR_FXSJ_CKBGDH_001,CURRENT_TIMESTAMP,BJTS_CUR_FXGZ_GZ_MC_002

                WHERE NOT EXISTS (SELECT 1
                                    FROM JKGL_GY_FXSM_HGCK A
                                   WHERE A.DJXH=BJTS_CUR_FXSJ_DJXH_001
                                     AND A.CKBGDH=BJTS_CUR_FXSJ_CKBGDH_001)
                  AND NOT EXISTS (SELECT 1
                                      FROM YJ_CS_BMD B
                                      LEFT JOIN YJ_CS_BMD_SUB C ON C.BMDID=B.ID
                                     WHERE B.NSRDZDAH=BJTS_CUR_FXSJ_NSRDZDAH_001
                                       AND B.YJCODE='140'
                                       AND (B.OBJFLAG='0' OR C.YJ_OBJECT=BJTS_CUR_FXGZ_GZ_MC_002));
          -- TL_TSSH.MSG_PUSH_DATA，风险出口数据的短信提醒
          -- 从原PRO_JKGL_FXCKSP存储过程迁移到这来，原biztype为“风险出口”，现改为“风险出口电子信息”
          IF BJTS_CUR_FXGZ_GZ_DXTXBZ_002='Y' THEN
            -- 20240819，插入风险出口的短信提醒信息，
            -- 风险出口短信提醒按18位报关单号汇总
            INSERT INTO MSG_PUSH_DATA(ID,SWJG_DM,NSRSBH,NSRMC,BIZTYPE,BIZKEY,QDSJ,JZSJ,YWBZ,SJTBSJ,IDLY)
                 SELECT SEQ_NEXTVAL('SEQ_MSG_PUSH_DATA'),BJTS_CUR_FXSJ_SWJG_DM_001,BJTS_CUR_FXSJ_NSRSBH_001,BJTS_CUR_FXSJ_NSRMC_001,'风险出口电子信息',
                        BJTS_CUR_FXSJ_CKBGD18_001,BJTS_CUR_FXSJ_CKRQ_1_001,NULL,BJTS_CUR_FXGZ_GZ_MC_002,CURRENT_TIMESTAMP,'1'

                  WHERE NOT EXISTS (SELECT 1
                                      FROM MSG_PUSH_DATA A
                                     WHERE A.BIZTYPE='风险出口电子信息'
                                       AND A.BIZKEY=BJTS_CUR_FXSJ_CKBGD18_001)
                    AND NOT EXISTS (SELECT 1
                                      FROM YJ_CS_BMD B
                                      LEFT JOIN YJ_CS_BMD_SUB C ON C.BMDID=B.ID
                                     WHERE B.NSRDZDAH=BJTS_CUR_FXSJ_NSRDZDAH_001
                                       AND B.YJCODE='140'
                                       AND (B.OBJFLAG='0' OR C.YJ_OBJECT=BJTS_CUR_FXGZ_GZ_MC_002));
          END IF;
          COMMIT;
        END;

  END LOOP BJTS_CURSOR_LOOP_001;
  CLOSE BJTS_CURSOR_001;
END;
    END;

  END LOOP BJTS_CURSOR_LOOP_002;
  CLOSE BJTS_CURSOR_002;
END;

  INSERT INTO FXGL_SZ_SPFXJH (ID,TSSWJG_DM,TSSWJG_MC,TBR,TBRQ,GZ_FW_SWJG,GZ_FW_DATA,GZ_MC,GZ_FXMS,GZ_GHQYSH,GZ_GHQYMC,GZ_DXTXBZ,QYBJ,FHXXBUUID)
SELECT SEQ_NEXTVAL('SEQ_FXGL_SZ_SPFXJH'),'13300000000','浙江省税务局','SYSTEM',CURRENT_TIMESTAMP,'133','2',B.GZ_MC,B.GZ_FXMS,B.GHQYNSRSBH_1,B.GHFQYMC_1,'N','Y',B.FHXXBUUID
FROM (
SELECT T.FHXXBUUID,T.FUHQFRQ,T.GHQYNSRSBH_1,T.GHFQYMC_1,'一年以上未回函' AS GZ_MC,
                     ORA_CONCAT(ORA_CONCAT(T.FAHDSWJGMC, DATE_FORMAT(T.FAHQFRQ, '%Y-%m-%d')), '发函，至今尚无明确回函意见') AS GZ_FXMS
                FROM YJ_CS_YCHD_JS T
               WHERE T.FUHLX_DM IS NULL AND ORA_DATE_DIFF(CURRENT_TIMESTAMP, T.FAHQFRQ)>365
) AS B
WHERE NOT EXISTS (
  SELECT 1 FROM FXGL_SZ_SPFXJH AS A WHERE B.FHXXBUUID=A.FHXXBUUID AND B.GZ_MC=A.GZ_MC
);
  COMMIT;
  INSERT INTO FXGL_SZ_SPFXJH (ID,TSSWJG_DM,TSSWJG_MC,TBR,TBRQ,GZ_FW_SWJG,GZ_FW_DATA,GZ_MC,GZ_FXMS,GZ_GHQYSH,GZ_GHQYMC,GZ_DXTXBZ,QYBJ,FHXXBUUID,GZ_YXQZ)
SELECT SEQ_NEXTVAL('SEQ_FXGL_SZ_SPFXJH'),'13300000000','浙江省税务局','SYSTEM',CURRENT_TIMESTAMP,'133','2',B.GZ_MC,B.GZ_FXMS,B.GHQYNSRSBH_1,B.GHFQYMC_1,'N','Y',B.FHXXBUUID,DATE_ADD(B.FUHQFRQ, INTERVAL 12 MONTH)
FROM (
SELECT T.FHXXBUUID,T.FUHQFRQ,T.GHQYNSRSBH_1,T.GHFQYMC_1,'回函存在异常业务' AS GZ_MC,
                     ORA_CONCAT(ORA_CONCAT(T.FAHDSWJGMC, DATE_FORMAT(T.FAHQFRQ, '%Y-%m-%d')), '发函，对方税务机关回函存在异常业务') AS GZ_FXMS
                FROM YJ_CS_YCHD_JS T
               WHERE T.FUHLX_DM='2'
) AS B
WHERE NOT EXISTS (
  SELECT 1 FROM FXGL_SZ_SPFXJH AS A WHERE B.FHXXBUUID=A.FHXXBUUID AND B.GZ_MC=A.GZ_MC
);
  COMMIT;
  /*MERGE INTO FXGL_SZ_SPFXJH A
       USING (SELECT T.FHXXBUUID,T.FUHQFRQ,T.GHQYNSRSBH_1,T.GHFQYMC_1,'回函正常其他情况不予退税' AS GZ_MC,
                     T.FAHDSWJGMC||TO_CHAR(T.FAHQFRQ,'yyyy-mm-dd')||'发函，对方税务机关回函正常，经核查其他情况不予退税' AS GZ_FXMS
                FROM TL_ADMIN.YJ_CS_YCHD_JS T
               WHERE T.FUHLX_DM<>'2' AND T.FUHCLYJ_DM='3') B
          ON (B.FHXXBUUID=A.FHXXBUUID AND B.GZ_MC=A.GZ_MC)
        WHEN NOT MATCHED THEN
          INSERT (ID,TSSWJG_DM,TSSWJG_MC,TBR,TBRQ,GZ_FW_SWJG,GZ_FW_DATA,GZ_MC,GZ_FXMS,GZ_GHQYSH,GZ_GHQYMC,GZ_DXTXBZ,QYBJ,FHXXBUUID,GZ_YXQZ)
          VALUES (SEQ_FXGL_SZ_SPFXJH.NEXTVAL,'13300000000','浙江省税务局','SYSTEM',SYSDATE,'133','2',B.GZ_MC,B.GZ_FXMS,B.GHQYNSRSBH_1,B.GHFQYMC_1,'N','Y',B.FHXXBUUID,ADD_MONTHS(B.FUHQFRQ,12));
  COMMIT;*/
  UPDATE FXGL_SZ_SPFXJH AS A
     SET GZ_YXQZ=(SELECT FUHQFRQ FROM YJ_CS_YCHD_JS B WHERE B.FHXXBUUID=A.FHXXBUUID)
   WHERE A.FHXXBUUID IS NOT NULL AND A.GZ_MC='一年以上未回函';
  COMMIT;

  LEAVE routine_body;
END$$

