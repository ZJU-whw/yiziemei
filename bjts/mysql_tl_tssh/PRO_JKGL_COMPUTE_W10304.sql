DELIMITER $$

DROP PROCEDURE IF EXISTS PRO_JKGL_COMPUTE_W10304$$

CREATE PROCEDURE PRO_JKGL_COMPUTE_W10304
/*
 * 出口企业是否经常变更法定代表人
 * ZB_VAL：变更次数
 */
(
  IN P_BGQID DECIMAL(38,10),
  IN P_DJXH DECIMAL(38,10),
  IN P_BGQ_Z DATETIME
)
routine_body: BEGIN
  DECLARE V_ZB_VAL     DECIMAL(18,2);
  DECLARE V_ROWS       BIGINT;
  DECLARE V_BADPOINT   CHAR(1);
  DECLARE V_PARAMS     VARCHAR(4000);

  BEGIN
    SET V_ZB_VAL = 0;
    FOR CUR_SPDM IN (SELECT DATE_FORMAT(LRRQ, '%Y%m%d') AS LRRQ, BGQNR, BGHNR
                       FROM CKTS_DJ_BGDJMX T
                      WHERE T.DJXH=P_DJXH AND T.BGQNR<>T.BGHNR AND T.LRRQ<P_BGQ_Z+1
                      ORDER BY T.LRRQ DESC)
    LOOP
      SET V_ZB_VAL = V_ZB_VAL +1;
      IF V_ZB_VAL=1 THEN
        SET V_PARAMS = '[d]变更日期=' || CUR_SPDM.LRRQ || '，变更前内容=' || CUR_SPDM.BGQNR || '，变更后内容=' || CUR_SPDM.BGHNR;
      ELSEIF V_ZB_VAL<=20 THEN
        SET V_PARAMS = V_PARAMS || '|变更日期=' || CUR_SPDM.LRRQ || '，变更前内容=' || CUR_SPDM.BGQNR || '，变更后内容=' || CUR_SPDM.BGHNR;
      END IF;
    END LOOP;
    IF V_ZB_VAL>20 THEN
      SET V_PARAMS = V_PARAMS || '|...';
    END IF;
  EXCEPTION
    WHEN OTHERS THEN
      SET V_ZB_VAL = NULL;
  END;

  IF V_ZB_VAL IS NULL THEN
    SET V_BADPOINT = 'Y';
  ELSE
    SET V_BADPOINT = 'N';
  END IF;

  SELECT COUNT(1)
    INTO V_ROWS
    FROM JKGL_DATA_TJ_ZB T
   WHERE T.BGQID=P_BGQID AND T.ZB_ID='W10304' AND ROWNUM=1;
  IF V_ROWS=0 THEN
    INSERT INTO JKGL_DATA_TJ_ZB(BGQID,ZB_ID,ZB_VAL,BADPOINT,PARAMS)
           VALUES(P_BGQID,'W10304',V_ZB_VAL,V_BADPOINT,V_PARAMS);
  ELSE
    UPDATE JKGL_DATA_TJ_ZB T
       SET T.ZB_VAL=V_ZB_VAL, T.BADPOINT=V_BADPOINT, T.PARAMS=V_PARAMS, T.UPTIME=CURRENT_TIMESTAMP
     WHERE T.BGQID=P_BGQID AND T.ZB_ID='W10304';
  END IF;
  COMMIT;

  LEAVE routine_body;
END$$

