DELIMITER $$

DROP PROCEDURE IF EXISTS PRO_FXGL_SZYJ_WLXX$$

CREATE PROCEDURE PRO_FXGL_SZYJ_WLXX()
/*
 * 从出口发票备注或申报明细备注提取物流信息（车牌号、起运日期、起运地、快递单号）
 * LN_WLBZ : 初始NULL，
 *           备注（发票+出口）空白99，
 *           从发票备注提取到车牌号，初始10；日期大于出口日期+1；大于系统日期+2；日期空+3；地址空+5
 *           从发票备注提取到快递信息20
 *           从出口明细备注提取到车牌号，初始30；日期大于出口日期+1；大于系统日期+2；日期空+3；地址空+5
 *           从出口明细备注提取到快递信息40
 *           备注非空白，未提取到物流98
 */
routine_body: BEGIN
  DECLARE LC_WLXX    VARCHAR(1000);
  DECLARE LN_WLBZ    BIGINT;
  DECLARE LC_WLDM    CHAR(1);
  DECLARE LC_CPH     VARCHAR(500);
  DECLARE LD_QYR     DATETIME;
  DECLARE LC_QYD     VARCHAR(500);
  DECLARE LN_ADDR    BIGINT;
  DECLARE LC_PATTERN VARCHAR(500);

  BEGIN
  DECLARE BJTS_CURSOR_DONE_001 BOOLEAN DEFAULT FALSE;
  DECLARE BJTS_CUR_BGD_DJXH_001 LONGTEXT;
  DECLARE BJTS_CUR_BGD_BGDHGBH_001 LONGTEXT;
  DECLARE BJTS_CUR_BGD_CKFPBZ_001 LONGTEXT;
  DECLARE BJTS_CUR_BGD_CKMXBZ_001 LONGTEXT;
  DECLARE BJTS_CUR_BGD_WLXXLY_DM_001 LONGTEXT;
  DECLARE BJTS_CUR_BGD_CPH_001 LONGTEXT;
  DECLARE BJTS_CUR_BGD_QYRQ_001 LONGTEXT;
  DECLARE BJTS_CUR_BGD_QYD_001 LONGTEXT;
  DECLARE BJTS_CUR_BGD_CKRQ_1_001 LONGTEXT;
  DECLARE BJTS_CURSOR_001 CURSOR FOR
SELECT DJXH,BGDHGBH,CKFPBZ,CKMXBZ,WLXXLY_DM,CPH,QYRQ,QYD,CKRQ_1
                    FROM CKLLFX_DATA_BGDWL
                   WHERE WLXXLY_BZ IS NULL
                   ORDER BY SJGXSJ;
  OPEN BJTS_CURSOR_001;
  BJTS_CURSOR_LOOP_001: LOOP
    SET BJTS_CURSOR_DONE_001 = FALSE;
    BEGIN
      DECLARE CONTINUE HANDLER FOR NOT FOUND SET BJTS_CURSOR_DONE_001 = TRUE;
      FETCH BJTS_CURSOR_001 INTO BJTS_CUR_BGD_DJXH_001, BJTS_CUR_BGD_BGDHGBH_001, BJTS_CUR_BGD_CKFPBZ_001, BJTS_CUR_BGD_CKMXBZ_001, BJTS_CUR_BGD_WLXXLY_DM_001, BJTS_CUR_BGD_CPH_001, BJTS_CUR_BGD_QYRQ_001, BJTS_CUR_BGD_QYD_001, BJTS_CUR_BGD_CKRQ_1_001;
    END;
    IF BJTS_CURSOR_DONE_001 THEN
      LEAVE BJTS_CURSOR_LOOP_001;
    END IF;
    SET LN_WLBZ = NULL;
    SET LC_WLDM = NULL;
    SET LC_CPH = NULL;
    SET LD_QYR = NULL;
    SET LC_QYD = NULL;

    -- 1、发票备注+出口明细备注 为空
    IF (TRIM(BJTS_CUR_BGD_CKFPBZ_001) IS NULL) AND (TRIM(BJTS_CUR_BGD_CKMXBZ_001) IS NULL) THEN
      SET LN_WLBZ = 99;
      SET LC_WLDM = '0';
      UPDATE CKLLFX_DATA_BGDWL AS T
         SET WLXXLY_BZ=LN_WLBZ,
    WLXXLY_DM=LC_WLDM,
    CPH=LC_CPH,
    QYRQ=LD_QYR,
    QYD=LC_QYD
       WHERE T.DJXH=BJTS_CUR_BGD_DJXH_001 AND T.BGDHGBH=BJTS_CUR_BGD_BGDHGBH_001;
      COMMIT;
      ITERATE BJTS_CURSOR_LOOP_001;
    END IF;

    -- 2、发票备注提取到车牌号
    CALL f_wlgl_extract_plate(BJTS_CUR_BGD_CKFPBZ_001,LN_ADDR, LC_CPH);
    IF LC_CPH IS NOT NULL THEN
      -- 2.1、从车牌号以后备注内容提取起运日、起运地信息，剔除前面的干扰因素
      SET LC_WLXX = SUBSTR(BJTS_CUR_BGD_CKFPBZ_001,LN_ADDR);
      SET LD_QYR = f_wlgl_extract_date(LC_WLXX,BJTS_CUR_BGD_CKRQ_1_001);
      SET LC_QYD = f_wlgl_extract_from(LC_WLXX);

      -- 2.2、起运日或起运地为空，提取物流关键字位置，从关键字位置以后再提取一次
      SET LC_PATTERN = '车牌|车号|车辆|起运|起始|起送|起至运|启运|始运|始发|出发|出运|出货|发车|发货|装车|装货|装柜|装箱|装运|送货|拉货|货源地|托运';
      SET LN_ADDR = REGEXP_INSTR(BJTS_CUR_BGD_CKFPBZ_001,LC_PATTERN,1);
      IF LN_ADDR > 0 THEN
        SET LC_WLXX = SUBSTR(BJTS_CUR_BGD_CKFPBZ_001,LN_ADDR);
        IF LD_QYR IS NULL THEN
          SET LD_QYR = f_wlgl_extract_date(LC_WLXX,BJTS_CUR_BGD_CKRQ_1_001);
        END IF;
        IF LC_QYD IS NULL THEN
          SET LC_QYD = f_wlgl_extract_from(LC_WLXX);
        END IF;
      END IF;

      -- 2.3、如果起运日或起运地还是为空，从完整备注中再提取一次
      IF LD_QYR IS NULL THEN
        SET LD_QYR = f_wlgl_extract_date(BJTS_CUR_BGD_CKFPBZ_001,BJTS_CUR_BGD_CKRQ_1_001);
      END IF;
      IF LC_QYD IS NULL THEN
        SET LC_QYD = f_wlgl_extract_from(BJTS_CUR_BGD_CKFPBZ_001);
      END IF;

      -- 2.4、根据起运日或起运地是否为空，记录不同结果
      SET LC_WLDM = '1';
      SET LN_WLBZ = 10;
      IF LD_QYR IS NULL THEN
        SET LN_WLBZ = LN_WLBZ + 3;
      ELSEIF LD_QYR>=CURRENT_TIMESTAMP THEN
        SET LN_WLBZ = LN_WLBZ + 2;
      ELSEIF LD_QYR>=BJTS_CUR_BGD_CKRQ_1_001 THEN
        SET LN_WLBZ = LN_WLBZ + 1;
      END IF;
      IF LC_QYD IS NULL THEN
        SET LN_WLBZ = LN_WLBZ + 5;
      END IF;
      UPDATE CKLLFX_DATA_BGDWL AS T
         SET WLXXLY_BZ=LN_WLBZ,
    WLXXLY_DM=LC_WLDM,
    CPH=LC_CPH,
    QYRQ=LD_QYR,
    QYD=LC_QYD
       WHERE T.DJXH=BJTS_CUR_BGD_DJXH_001 AND T.BGDHGBH=BJTS_CUR_BGD_BGDHGBH_001;
      COMMIT;
      ITERATE BJTS_CURSOR_LOOP_001;
    END IF;

    -- 2、发票备注未提取到车牌号，但提取到快递信息
    SET LC_CPH = f_wlgl_extract_parcel(BJTS_CUR_BGD_CKFPBZ_001);
    IF LC_CPH IS NOT NULL THEN
      SET LN_WLBZ = 20;
      SET LC_WLDM = '1';
      UPDATE CKLLFX_DATA_BGDWL AS T
         SET WLXXLY_BZ=LN_WLBZ,
    WLXXLY_DM=LC_WLDM,
    CPH=LC_CPH,
    QYRQ=LD_QYR,
    QYD=LC_QYD
       WHERE T.DJXH=BJTS_CUR_BGD_DJXH_001 AND T.BGDHGBH=BJTS_CUR_BGD_BGDHGBH_001;
      COMMIT;
      ITERATE BJTS_CURSOR_LOOP_001;
    END IF;

    -- 3、出口明细备注提取到车牌号
    CALL f_wlgl_extract_plate(BJTS_CUR_BGD_CKMXBZ_001,LN_ADDR, LC_CPH);
    IF LC_CPH IS NOT NULL THEN
      SET LN_WLBZ = 30;
      SET LC_WLDM = '2';
      SET LD_QYR = f_wlgl_extract_date(BJTS_CUR_BGD_CKMXBZ_001,BJTS_CUR_BGD_CKRQ_1_001);
      IF LD_QYR IS NULL THEN
        SET LN_WLBZ = LN_WLBZ + 3;
      ELSEIF LD_QYR>=CURRENT_TIMESTAMP THEN
        SET LN_WLBZ = LN_WLBZ + 2;
      ELSEIF LD_QYR>=BJTS_CUR_BGD_CKRQ_1_001 THEN
        SET LN_WLBZ = LN_WLBZ + 1;
      END IF;
      SET LC_QYD = f_wlgl_extract_from(BJTS_CUR_BGD_CKMXBZ_001);
      IF LC_QYD IS NULL THEN
        SET LN_WLBZ = LN_WLBZ + 5;
      END IF;
      UPDATE CKLLFX_DATA_BGDWL AS T
         SET WLXXLY_BZ=LN_WLBZ,
    WLXXLY_DM=LC_WLDM,
    CPH=LC_CPH,
    QYRQ=LD_QYR,
    QYD=LC_QYD
       WHERE T.DJXH=BJTS_CUR_BGD_DJXH_001 AND T.BGDHGBH=BJTS_CUR_BGD_BGDHGBH_001;
      COMMIT;
      ITERATE BJTS_CURSOR_LOOP_001;
    END IF;

    -- 4、出口明细备注未提取到车牌号，但提取到快递信息
    SET LC_CPH = f_wlgl_extract_parcel(BJTS_CUR_BGD_CKMXBZ_001);
    IF LC_CPH IS NOT NULL THEN
      SET LN_WLBZ = 40;
      SET LC_WLDM = '2';
      UPDATE CKLLFX_DATA_BGDWL AS T
         SET WLXXLY_BZ=LN_WLBZ,
    WLXXLY_DM=LC_WLDM,
    CPH=LC_CPH,
    QYRQ=LD_QYR,
    QYD=LC_QYD
       WHERE T.DJXH=BJTS_CUR_BGD_DJXH_001 AND T.BGDHGBH=BJTS_CUR_BGD_BGDHGBH_001;
      COMMIT;
      ITERATE BJTS_CURSOR_LOOP_001;
    END IF;

    -- 5、发票备注+出口明细备注 不包含物流关键字
    SET LN_WLBZ = 98;
    UPDATE CKLLFX_DATA_BGDWL AS T
       SET WLXXLY_BZ=LN_WLBZ,
    WLXXLY_DM=LC_WLDM,
    CPH=LC_CPH,
    QYRQ=LD_QYR,
    QYD=LC_QYD
     WHERE T.DJXH=BJTS_CUR_BGD_DJXH_001 AND T.BGDHGBH=BJTS_CUR_BGD_BGDHGBH_001;
    COMMIT;

  END LOOP BJTS_CURSOR_LOOP_001;
  CLOSE BJTS_CURSOR_001;
END;

  LEAVE routine_body;
END$$

