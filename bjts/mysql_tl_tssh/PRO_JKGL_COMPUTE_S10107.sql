DELIMITER $$

DROP PROCEDURE IF EXISTS PRO_JKGL_COMPUTE_S10107$$

CREATE PROCEDURE PRO_JKGL_COMPUTE_S10107
/*
 * 出口企业分类管理等级
 * ZB_VAL：A-1,B-2,C-3,D-4，无类别返回5
 */
(
  IN P_BGQID DECIMAL(38,10),
  IN P_DJXH DECIMAL(38,10),
  IN P_BGQ_Z DATETIME
)
routine_body: BEGIN
  DECLARE V_ZB_VAL     DECIMAL(18,2);
  DECLARE V_ROWS       BIGINT;
  DECLARE V_BADPOINT   CHAR(1);
  DECLARE V_PARAMS     VARCHAR(1000);

  BEGIN
    SELECT (CASE B.KZXX WHEN 'A' THEN 1 WHEN 'B' THEN 2 WHEN 'C' THEN 3 WHEN 'D' THEN 4 ELSE 5 END),
           '[d]出口企业分类管理等级=' || B.KZXX
      INTO V_ZB_VAL, V_PARAMS
      FROM GS_DJ_CKTMSDAB A
     INNER JOIN GS_DJ_CKTMSDAB_KZ B ON A.NSRDZDAH=B.NSRDZDAH AND B.KZLX='FLGLCD' AND (P_BGQ_Z BETWEEN B.ST_DATE AND B.END_DATE)
     WHERE A.CPCODE=CAST(P_DJXH AS CHAR)
       AND ROWNUM=1;
  EXCEPTION
    WHEN OTHERS THEN
      SET V_ZB_VAL = NULL;
  END;

  IF V_ZB_VAL IS NULL THEN
    SET V_BADPOINT = 'Y';
  ELSE
    SET V_BADPOINT = 'N';
  END IF;

  SELECT COUNT(1)
    INTO V_ROWS
    FROM JKGL_DATA_TJ_ZB T
   WHERE T.BGQID=P_BGQID AND T.ZB_ID='S10107' AND ROWNUM=1;
  IF V_ROWS=0 THEN
    INSERT INTO JKGL_DATA_TJ_ZB(BGQID,ZB_ID,ZB_VAL,BADPOINT,PARAMS)
           VALUES(P_BGQID,'S10107',V_ZB_VAL,V_BADPOINT,V_PARAMS);
  ELSE
    UPDATE JKGL_DATA_TJ_ZB T
       SET T.ZB_VAL=V_ZB_VAL, T.BADPOINT=V_BADPOINT, T.PARAMS=V_PARAMS, T.UPTIME=CURRENT_TIMESTAMP
     WHERE T.BGQID=P_BGQID AND T.ZB_ID='S10107';
  END IF;
  COMMIT;

  LEAVE routine_body;
END$$

DELIMITER ;
