DELIMITER $$

DROP PROCEDURE IF EXISTS PRO_JKGL_COMPUTE_S10105$$

CREATE PROCEDURE PRO_JKGL_COMPUTE_S10105
/*
 * 财务负责人是否兼职
 * ZB_VAL：财务负责人兼职的企业合计户数
 */
(
  IN P_BGQID DECIMAL(38,10),
  IN P_DJXH DECIMAL(38,10)
)
routine_body: BEGIN
  DECLARE V_ZB_VAL     DECIMAL(18,2);
  DECLARE V_ROWS       BIGINT;
  DECLARE V_ZJHM       VARCHAR(50);
  DECLARE V_BADPOINT   CHAR(1);
  DECLARE V_PARAMS     VARCHAR(4000);

  BEGIN
    SELECT T.CWFZRSFZJHM,
           '[d]财务负责人证件号码=' || T.CWFZRSFZJHM
      INTO V_ZJHM, V_PARAMS
      FROM GS_DJ_CKTMSDAB T
     WHERE T.CPCODE=CAST(P_DJXH AS CHAR)
       AND ROWNUM=1;

    SET V_ZB_VAL = 0;
    FOR CUR_SPDM IN (SELECT DISTINCT T.NSRSBH, T.NSRMC
                       FROM GS_DJ_CKTMSDAB T
                      WHERE T.CWFZRSFZJHM = V_ZJHM
                         OR T.FRZJHM = V_ZJHM)
    LOOP
      SET V_ZB_VAL = V_ZB_VAL +1;
      IF V_ZB_VAL<=20 THEN
        SET V_PARAMS = V_PARAMS || '|财务负责人所在单位税号=' || CUR_SPDM.NSRSBH || '，名称=' || CUR_SPDM.NSRMC;
      END IF;
    END LOOP;
    IF V_ZB_VAL>20 THEN
      SET V_PARAMS = V_PARAMS || '|...';
    END IF;
  EXCEPTION
    WHEN OTHERS THEN
      SET V_ZB_VAL = NULL;
  END;

  IF V_ZB_VAL IS NULL THEN
    SET V_BADPOINT = 'Y';
  ELSE
    SET V_BADPOINT = 'N';
  END IF;

  SELECT COUNT(1)
    INTO V_ROWS
    FROM JKGL_DATA_TJ_ZB T
   WHERE T.BGQID=P_BGQID AND T.ZB_ID='S10105' AND ROWNUM=1;
  IF V_ROWS=0 THEN
    INSERT INTO JKGL_DATA_TJ_ZB(BGQID,ZB_ID,ZB_VAL,BADPOINT,PARAMS)
           VALUES(P_BGQID,'S10105',V_ZB_VAL,V_BADPOINT,V_PARAMS);
  ELSE
    UPDATE JKGL_DATA_TJ_ZB T
       SET T.ZB_VAL=V_ZB_VAL, T.BADPOINT=V_BADPOINT, T.PARAMS=V_PARAMS, T.UPTIME=CURRENT_TIMESTAMP
     WHERE T.BGQID=P_BGQID AND T.ZB_ID='S10105';
  END IF;
  COMMIT;

  LEAVE routine_body;
END$$

DELIMITER ;
