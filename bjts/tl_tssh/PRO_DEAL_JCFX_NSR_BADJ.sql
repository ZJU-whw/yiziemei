CREATE OR REPLACE PROCEDURE PRO_DEAL_JCFX_NSR_BADJ
AS
  LD_DEALDATA      DATE;          --用于基础数据处理的提前量
BEGIN
  BEGIN
    MERGE INTO JCFX_NSR_BADJ A
         USING (SELECT T.DJXH_JS,T.NSRDJNO,T.SHXYNO,T.NSRMC,T.QYHGDM,T.QYLX,T.FLGLCD,T.DJZCLX_JS,T.HYDM,T.NSRZT_JS,T.NSRLX_JS,T.SQ_DATE,NVL(T.ZX_FLAG,'N') AS ZX_FLAG,T.ZX_DATE,T.SWJGDM,T.ZGSWSKFJ_DM,T.JDXZ_DM
                  FROM GLXT_BB_SHXT_DJXX T) B
            ON (A.DJXH=B.DJXH_JS)
          WHEN MATCHED THEN
            UPDATE SET A.NSRSBH=B.NSRDJNO, A.SHXYDM=B.SHXYNO, A.NSRMC=B.NSRMC, A.QYHGDM=B.QYHGDM, 
                       A.CKQYLX=B.QYLX, A.FLGLCD=B.FLGLCD, A.DJZCLX=B.DJZCLX_JS, A.HY=B.HYDM, A.NSRZT=B.NSRZT_JS, A.NSRLB=B.NSRLX_JS, 
                       A.SQ_DATE=B.SQ_DATE, A.BACHBZ=B.ZX_FLAG, A.BACHSJ=B.ZX_DATE, A.SWJGDM=B.SWJGDM, A.KSSWJG_DM=B.ZGSWSKFJ_DM, A.JDXZ_DM=B.JDXZ_DM
          WHEN NOT MATCHED THEN
            INSERT (DJXH,NSRSBH,SHXYDM,NSRMC,QYHGDM,CKQYLX,FLGLCD,DJZCLX,HY,NSRZT,NSRLB,SQ_DATE,BACHBZ,BACHSJ,SWJGDM,KSSWJG_DM,JDXZ_DM)
            VALUES (B.DJXH_JS,B.NSRDJNO,B.SHXYNO,B.NSRMC,B.QYHGDM,B.QYLX,B.FLGLCD,B.DJZCLX_JS,B.HYDM,B.NSRZT_JS,B.NSRLX_JS,B.SQ_DATE,B.ZX_FLAG,B.ZX_DATE,B.SWJGDM,B.ZGSWSKFJ_DM,B.JDXZ_DM);
    COMMIT;
    
    --QYFZ,NSRDZDAH
  END;
  
  SELECT MAX(JLXZSJ)-7 INTO LD_DEALDATA FROM JCFX_NSR_BADJ_TOHZ;
  
  BEGIN
    --后续增量数据1：新备案出口企业
    INSERT INTO JCFX_NSR_BADJ_TOHZ(DJXH,NSRSBH,SHXYDM,JLXZSJ,BACHSJ,SWJGDM)
         SELECT T.DJXH_JS,T.NSRDJNO,T.SHXYNO,TRUNC(LEAST(SYSDATE,T.SQ_DATE)),T.ZX_DATE,T.SWJGDM
           FROM GLXT_BB_SHXT_DJXX T
          WHERE T.SQ_DATE>=LD_DEALDATA
            AND NOT EXISTS (SELECT 1 FROM JCFX_NSR_BADJ_TOHZ S WHERE S.DJXH=T.DJXH_JS);
    COMMIT;

    --后续增量数据2：老备案企业，2019年1月1日以来首次申报出口退免税
    INSERT INTO JCFX_NSR_BADJ_TOHZ(DJXH,NSRSBH,SHXYDM,JLXZSJ,BACHSJ,SWJGDM)
         SELECT T.DJXH_JS,T.NSRDJNO,T.SHXYNO,TRUNC(SYSDATE),T.ZX_DATE,T.SWJGDM
           FROM GLXT_BB_SHXT_DJXX T
          WHERE EXISTS (SELECT 1 FROM CKTS_LC_SBXX S WHERE S.DJXH=T.DJXH_JS AND S.SBRQ>=LD_DEALDATA)
            AND NOT EXISTS (SELECT 1 FROM JCFX_NSR_BADJ_TOHZ S WHERE S.DJXH=T.DJXH_JS);
    COMMIT;

  --后续注销企业
    UPDATE JCFX_NSR_BADJ_TOHZ T
       SET T.BACHSJ=(SELECT S.ZX_DATE FROM GLXT_BB_SHXT_DJXX S WHERE S.DJXH_JS=T.DJXH)
     WHERE EXISTS (SELECT 1 FROM GLXT_BB_SHXT_DJXX S WHERE S.DJXH_JS=T.DJXH AND S.ZX_DATE>=LD_DEALDATA);
    COMMIT;
  END;
  
  RETURN;
END;
