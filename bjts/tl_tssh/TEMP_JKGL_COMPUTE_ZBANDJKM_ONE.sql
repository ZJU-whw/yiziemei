CREATE OR REPLACE PROCEDURE TEMP_JKGL_COMPUTE_ZBANDJKM_ONE
AS
BEGIN

  DELETE FROM TL_TSSH.JKGL_DATA_ZB_JGB T WHERE T.DJXH=10113307000050307619;
  COMMIT;
  INSERT INTO TL_TSSH.JKGL_DATA_ZB_JGB(DJXH,ZB_ID,ZB_VAL,BADPOINT,SCORE,JS_STATUS,FF_STATUS,UPTIME,PARAMS)
       SELECT T.DJXH,S.ZB_ID,S.ZB_VAL,S.BADPOINT, 0,'1','0',SYSDATE, S.PARAMS 
                FROM TL_TSSH.JKGL_DATA_BGQ T
               INNER JOIN TL_TSSH.JKGL_DATA_TJ_ZB S ON S.BGQID=T.BGQID
               WHERE T.DJXH=10113307000050307619
                 AND T.BGQ_Q=DATE'2021-01-01'
                 AND T.BGQ_Z=DATE'2021-12-31';
  COMMIT;

  DELETE FROM TL_TSSH.JKGL_DATA_QYJKM_JGB T WHERE T.DJXH=10113307000050307619;
  COMMIT;
  INSERT INTO JKGL_DATA_QYJKM_JGB(DJXH,TSJSFS_DM,CRTIME)
       SELECT T.CPCODE,T.JSMODE,SYSDATE 
         FROM GLXT_BB_SHXT_DJXX T 
        WHERE T.CPCODE='10113307000050307619';
  COMMIT;

  PRO_JKGL_JKM_MAIN(10113307000050307619,NULL);
  COMMIT;

  RETURN;
END;
