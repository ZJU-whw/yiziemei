CREATE OR REPLACE PROCEDURE PRO_JKGL_COMPUTE_S30401
/*
 * 出口目的国数量变动=报告期出口目的国数量-基期出口目的国数量（主要关注目的国增速过快，下降的不必关注。）
 * ZB_VAL：（出口_目的国数量-出口_目的国数量[基期]）/出口_目的国数量[基期]
 */
(
  P_BGQID   IN NUMBER,
  P_JQID    IN NUMBER
)
AS
  V_ZB_VAL     NUMBER(18,2);
  V_ROWS       NUMBER(10);
  V_BADPOINT   CHAR(1);
  V_THIS_DATA  NUMBER(18,2);
  V_LAST_DATA  NUMBER(18,2);
  V_PARAMS     VARCHAR(4000);
BEGIN
  BEGIN
    SELECT T.CK_GB_SL
      INTO V_THIS_DATA
      FROM TL_TSSH.JKGL_DATA_TJ_ZBU T
     WHERE T.BGQID=P_BGQID;

    SELECT T.CK_GB_SL
      INTO V_LAST_DATA
      FROM TL_TSSH.JKGL_DATA_TJ_ZBU T
     WHERE T.BGQID=P_JQID;

    V_PARAMS := '[d]报告期出口目的国数量=' || V_THIS_DATA || '|基期出口目的国数量=' || V_LAST_DATA;
    IF V_LAST_DATA<=1 OR V_THIS_DATA-V_LAST_DATA<0 THEN
      V_ZB_VAL:=0;
    ELSE
      V_ZB_VAL:=ROUND(100 * (V_THIS_DATA-V_LAST_DATA) / V_LAST_DATA,2);
    END IF;
  EXCEPTION
    WHEN OTHERS THEN
      V_ZB_VAL := NULL;
  END;

  IF V_ZB_VAL IS NULL THEN
    V_BADPOINT := 'Y';
  ELSE
    V_BADPOINT := 'N';
  END IF;

  SELECT COUNT(1)
    INTO V_ROWS
    FROM JKGL_DATA_TJ_ZB T
   WHERE T.BGQID=P_BGQID AND T.ZB_ID='S30401' AND ROWNUM=1;
  IF V_ROWS=0 THEN
    INSERT INTO JKGL_DATA_TJ_ZB(BGQID,ZB_ID,ZB_VAL,BADPOINT,PARAMS)
           VALUES(P_BGQID,'S30401',V_ZB_VAL,V_BADPOINT,V_PARAMS);
  ELSE
    UPDATE JKGL_DATA_TJ_ZB T
       SET T.ZB_VAL=V_ZB_VAL, T.BADPOINT=V_BADPOINT, T.PARAMS=V_PARAMS, T.UPTIME=SYSDATE
     WHERE T.BGQID=P_BGQID AND T.ZB_ID='S30401';
  END IF;
  COMMIT;

  RETURN;
END;
/
