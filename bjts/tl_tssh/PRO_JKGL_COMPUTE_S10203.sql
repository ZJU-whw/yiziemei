CREATE OR REPLACE PROCEDURE PRO_JKGL_COMPUTE_S10203
/*
 * 销售额与电费支出变动趋势，取统计期往前一年与前前一年的数据
 * ZB_VAL：销售额(扣除委托加工费)升降趋势与电费升降趋势不一致返回1，否则0
 */
(
  P_BGQID   IN NUMBER,
  P_JQID    IN NUMBER
)
AS
  V_ZB_VAL     NUMBER(18,2);
  V_ROWS       NUMBER(10);
  V_BADPOINT   CHAR(1);
  V_THIS_DATA  NUMBER(18,2);
  V_LAST_DATA  NUMBER(18,2);
  V_THIS_AMT   NUMBER(18,2);
  V_LAST_AMT   NUMBER(18,2);
  V_PARAMS     VARCHAR(1000);
BEGIN
  BEGIN
    SELECT S.ZZS_XSE_QB - S.DZ_WTJG, S.DZ_DFJE_ZC - S.DZ_DFJE_SR
      INTO V_THIS_DATA, V_THIS_AMT
      FROM JKGL_DATA_TJ_ZBU S
     WHERE S.BGQID=P_BGQID;

    SELECT S.ZZS_XSE_QB - S.DZ_WTJG, S.DZ_DFJE_ZC - S.DZ_DFJE_SR
      INTO V_LAST_DATA, V_LAST_AMT
      FROM JKGL_DATA_TJ_ZBU S
     WHERE S.BGQID=P_JQID;

    V_PARAMS := '[d]报告期销售额(扣除委托加工费)=' || V_THIS_DATA || '|报告期电费=' || V_THIS_AMT ||
                '|基期销售额(扣除委托加工费)=' || V_LAST_DATA || '|基期电费=' || V_LAST_AMT;
    IF V_THIS_DATA>0 AND V_THIS_AMT>=0 AND V_LAST_DATA>0 AND V_LAST_AMT>=0 THEN
      IF (V_THIS_DATA - V_LAST_DATA) * (V_THIS_AMT - V_LAST_AMT) < 0 THEN
        V_ZB_VAL := 1;
      ELSE
        V_ZB_VAL := 0;
      END IF;
    ELSE
      V_ZB_VAL := NULL;
    END IF;
  EXCEPTION
    WHEN OTHERS THEN
      V_ZB_VAL := NULL;
  END;

  IF V_ZB_VAL IS NULL THEN
    V_BADPOINT := 'Y';
  ELSE
    V_BADPOINT := 'N';
  END IF;

  SELECT COUNT(1)
    INTO V_ROWS
    FROM JKGL_DATA_TJ_ZB T
   WHERE T.BGQID=P_BGQID AND T.ZB_ID='S10203' AND ROWNUM=1;
  IF V_ROWS=0 THEN
    INSERT INTO JKGL_DATA_TJ_ZB(BGQID,ZB_ID,ZB_VAL,BADPOINT,PARAMS)
           VALUES(P_BGQID,'S10203',V_ZB_VAL,V_BADPOINT,V_PARAMS);
  ELSE
    UPDATE JKGL_DATA_TJ_ZB T
       SET T.ZB_VAL=V_ZB_VAL, T.BADPOINT=V_BADPOINT, T.PARAMS=V_PARAMS, T.UPTIME=SYSDATE
     WHERE T.BGQID=P_BGQID AND T.ZB_ID='S10203';
  END IF;
  COMMIT;

  RETURN;
END;
/
