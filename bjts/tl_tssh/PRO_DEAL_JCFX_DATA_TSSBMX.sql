CREATE OR REPLACE PROCEDURE PRO_DEAL_JCFX_DATA_TSSBMX
AS
  V_BEGINDATE      DATE;
  V_RMBLAJ         NUMBER(18,2);
  V_GHFNSRSBH      VARCHAR2(30);
  V_HYDXZQH_DM     VARCHAR2(10);
  LN_ROWS          NUMBER(10);
  LC_SBYY          VARCHAR2(2000);
BEGIN
  EXECUTE IMMEDIATE 'ALTER TABLE JCFX_DATA_TSSBMX ENABLE ROW MOVEMENT';
  
  SELECT TRUNC(MAX(T.SJGXSJ))-1
    INTO V_BEGINDATE
    FROM JCFX_DATA_TSSBMX T;

  SELECT COUNT(1)
    INTO LN_ROWS
    FROM CKTS_SB_MDT_CKMX S
   WHERE S.SJTB_SJ>=V_BEGINDATE
     AND NVL(S.BYBLBZ,'N')='N';

  INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('CKTS_SB_MDT_CKMX-->JCFX_DATA_TSSBMX开始运行，记录总数：' || LN_ROWS);
  COMMIT;
  
  --免抵退税
  BEGIN
    MERGE INTO JCFX_DATA_TSSBMX A
         USING (SELECT S.UUID,S.TSSWJG_DM,S.DJXH,NVL(TRIM(S.DLCKHWZMHM),S.CKBGDH) AS CKBGDH,TO_CHAR(S.SBRQ,'YYYYMM') AS NY,S.SBRQ,S.CKRQ_1,S.CKSP_DM,
                       S.HGCODE,S.GBCODE,S.TDCODE,S.HZDWDQDM,'1' AS SBYWLX,S.LCSLID_SB,
                       S.CKSL,S.MYLAJ,S.RMBLAJ,S.TSL,S.MDTSE
                  FROM CKTS_SB_MDT_CKMX S
                 WHERE S.SJTB_SJ>=V_BEGINDATE
                   AND NVL(S.BYBLBZ,'N')='N'
                   AND NVL(TRIM(S.DLCKHWZMHM),S.CKBGDH) IS NOT NULL) B
            ON (A.UUID=B.UUID)
          WHEN MATCHED THEN
            UPDATE SET A.TSSWJG_DM=B.TSSWJG_DM, A.DJXH=B.DJXH, A.CKBGDH=B.CKBGDH, A.NY=B.NY, A.SBRQ=B.SBRQ, A.CKRQ=B.CKRQ_1, A.CKSP_DM=B.CKSP_DM, 
                       A.HGGQKA_DM=B.HGCODE, A.MYGDQSZ_DM=B.GBCODE, A.JGFS_DM=B.TDCODE, A.HZDWDQ_DM=B.HZDWDQDM, A.SJGXSJ=SYSDATE, A.SBYWLX=B.SBYWLX, A.LCSLID=B.LCSLID_SB, 
                       A.MYLAJ=B.MYLAJ, A.RMBLAJ=B.RMBLAJ, A.JSJE=B.RMBLAJ, A.TSL=B.TSL, A.TMSE=B.MDTSE, A.CKSL=B.CKSL
          WHEN NOT MATCHED THEN
            INSERT (UUID,TSSWJG_DM,DJXH,CKBGDH,NY,SBRQ,CKRQ,CKSP_DM,HGGQKA_DM,MYGDQSZ_DM,JGFS_DM,HZDWDQ_DM,SJGXSJ,SBYWLX,LCSLID,MYLAJ,RMBLAJ,JSJE,TSL,TMSE,CKSL)
            VALUES (B.UUID,B.TSSWJG_DM,B.DJXH,B.CKBGDH,B.NY,B.SBRQ,B.CKRQ_1,B.CKSP_DM,B.HGCODE,B.GBCODE,B.TDCODE,B.HZDWDQDM,SYSDATE,B.SBYWLX,B.LCSLID_SB,B.MYLAJ,B.RMBLAJ,B.RMBLAJ,B.TSL,B.MDTSE,B.CKSL);
    COMMIT;
    --不需要补充GHFNSRSBH,HYDXZQH_DM 
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('CKTS_SB_MDT_CKMX-->JCFX_DATA_TSSBMX失败！', LC_SBYY);
      COMMIT;
  END;
  
  SELECT COUNT(1)
    INTO LN_ROWS
    FROM CKTS_SB_MTS_CKMX S
   WHERE S.SJTB_SJ>=V_BEGINDATE
     AND NVL(S.BYBLBZ,'N')='N';

  INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('CKTS_SB_MTS_CKMX-->JCFX_DATA_TSSBMX开始运行，记录总数：' || LN_ROWS);
  COMMIT;
  
  --免退税
  BEGIN
    MERGE INTO JCFX_DATA_TSSBMX A
         USING (SELECT S.UUID,S.TSSWJG_DM,S.DJXH,NVL(TRIM(S.DLCKHWZMHM),S.CKBGDH) AS CKBGDH,TO_CHAR(S.SBRQ,'YYYYMM') AS NY,S.SBRQ,S.CKRQ_1,S.CKSP_DM,
                       S.HGCODE,S.GBCODE,S.TDCODE,S.HZDWDQDM,'2' AS SBYWLX,S.LCSLID_SB,
                       S.CKSL,S.MYLAJ,S.GLH,S.JSJE,S.TSL,S.TSE
                  FROM CKTS_SB_MTS_CKMX S
                 WHERE S.SJTB_SJ>=V_BEGINDATE
                   AND NVL(S.BYBLBZ,'N')='N') B
            ON (A.UUID=B.UUID)
          WHEN MATCHED THEN
            UPDATE SET A.TSSWJG_DM=B.TSSWJG_DM, A.DJXH=B.DJXH, A.CKBGDH=B.CKBGDH, A.NY=B.NY, A.SBRQ=B.SBRQ, A.CKRQ=B.CKRQ_1, A.CKSP_DM=B.CKSP_DM, 
                       A.HGGQKA_DM=B.HGCODE, A.MYGDQSZ_DM=B.GBCODE, A.JGFS_DM=B.TDCODE, A.HZDWDQ_DM=B.HZDWDQDM, A.SJGXSJ=SYSDATE, A.SBYWLX=B.SBYWLX, A.LCSLID=B.LCSLID_SB, 
                       A.MYLAJ=B.MYLAJ, A.GLH=B.GLH, A.JSJE=B.JSJE, A.TSL=B.TSL, A.TMSE=B.TSE, A.CKSL=B.CKSL
          WHEN NOT MATCHED THEN
            INSERT (UUID,TSSWJG_DM,DJXH,CKBGDH,NY,SBRQ,CKRQ,CKSP_DM,HGGQKA_DM,MYGDQSZ_DM,JGFS_DM,HZDWDQ_DM,SJGXSJ,SBYWLX,LCSLID,MYLAJ,GLH,JSJE,TSL,TMSE,CKSL)
            VALUES (B.UUID,B.TSSWJG_DM,B.DJXH,B.CKBGDH,B.NY,B.SBRQ,B.CKRQ_1,B.CKSP_DM,B.HGCODE,B.GBCODE,B.TDCODE,B.HZDWDQDM,SYSDATE,B.SBYWLX,B.LCSLID_SB,B.MYLAJ,B.GLH,B.JSJE,B.TSL,B.TSE,B.CKSL);
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('CKTS_SB_MTS_CKMX-->JCFX_DATA_TSSBMX失败！', LC_SBYY);
      COMMIT;
  END;
    
  BEGIN
    --补充RMBLAJ,GHFNSRSBH,HYDXZQH_DM
    FOR CUR_TSSB IN (SELECT T.UUID,T.DJXH,T.CKBGDH,T.CKSP_DM,GLH,MYLAJ,TO_CHAR(T.CKRQ,'YYYYMM') AS CKNY FROM JCFX_DATA_TSSBMX T WHERE T.SJGXSJ>=TRUNC(SYSDATE,'DD') AND T.SBYWLX='2')
    LOOP
      BEGIN
        --防止部分申报
        SELECT CUR_TSSB.MYLAJ * S.RMBLAJ / S.MYLAJ 
          INTO V_RMBLAJ
          FROM CKTS_WBSJ_HG_BGD S
         WHERE S.DJXH=CUR_TSSB.DJXH AND S.CKBGDH=CUR_TSSB.CKBGDH;
      EXCEPTION
        WHEN OTHERS THEN
          V_RMBLAJ := NULL;
      END;
      
      IF V_RMBLAJ IS NULL THEN
        SELECT CUR_TSSB.MYLAJ * S.HL_RMB / 100
          INTO V_RMBLAJ
          FROM TL_BJTS.GS_HBZL_HLV S 
         WHERE S.CODE='USD' AND S.HL_YM=CUR_TSSB.CKNY AND ROWNUM=1;
      END IF;
      
      BEGIN
        --主要供货商
        SELECT GHFNSRSBH_1, CASE WHEN SUBSTR(GHFNSRSBH_1,1,2)='91' THEN SUBSTR(GHFNSRSBH_1,3,4) ELSE SUBSTR(GHFNSRSBH_1,1,4) END
          INTO V_GHFNSRSBH, V_HYDXZQH_DM
          FROM (SELECT S.GHFNSRSBH_1, SUM(S.TSE) AS TSE
                  FROM CKTS_SB_MTS_JHMX S
                 WHERE S.DJXH=CUR_TSSB.DJXH AND S.GLH=CUR_TSSB.GLH AND S.CKSP_DM=CUR_TSSB.CKSP_DM
                 GROUP BY S.GHFNSRSBH_1
                 ORDER BY SUM(S.TSE) DESC) TT
         WHERE ROWNUM=1;
      EXCEPTION
        WHEN OTHERS THEN
          V_GHFNSRSBH :=NULL;
          V_HYDXZQH_DM :=NULL;
      END;
      
      UPDATE JCFX_DATA_TSSBMX S
         SET S.RMBLAJ = V_RMBLAJ, GHFNSRSBH = V_GHFNSRSBH, HYDXZQH_DM = V_HYDXZQH_DM
       WHERE S.UUID=CUR_TSSB.UUID;
      COMMIT;
    END LOOP;
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('JCFX_DATA_TSSBMX补充RMBLAJ,GHFNSRSBH,HYDXZQH_DM失败！', LC_SBYY);
      COMMIT;
  END;
  
  SELECT COUNT(1)
    INTO LN_ROWS
    FROM CKTS_SB_WZF_CKMX S
   WHERE S.SJTB_SJ>=V_BEGINDATE
     AND NVL(S.BYBLBZ,'N')='N';

  INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('CKTS_SB_WZF_CKMX-->JCFX_DATA_TSSBMX开始运行，记录总数：' || LN_ROWS);
  COMMIT;
  
  --代办退税
  BEGIN
    MERGE INTO JCFX_DATA_TSSBMX A
         USING (SELECT S.UUID,S.TSSWJG_DM,S.DJXH,S.CKBGDH,TO_CHAR(S.SBRQ,'YYYYMM') AS NY,S.SBRQ,S.CKRQ_1,S.CKSP_DM,
                       S.HGCODE,S.GBCODE,S.TDCODE,S.HZDWDQDM,'3' AS SBYWLX,S.LCSLID_SB,
                       S.CKSL,S.MYLAJ,S.JSJE,S.TSL,S.TSE,S.WTDBTSSCQYNSRSBH,
                       CASE WHEN SUBSTR(S.WTDBTSSCQYNSRSBH,1,2)='91' THEN SUBSTR(S.WTDBTSSCQYNSRSBH,3,4) ELSE SUBSTR(S.WTDBTSSCQYNSRSBH,1,4) END AS HYDXZQH_DM
                  FROM CKTS_SB_WZF_CKMX S
                 WHERE S.SJTB_SJ>=V_BEGINDATE
                   AND NVL(S.BYBLBZ,'N')='N') B
            ON (A.UUID=B.UUID)
          WHEN MATCHED THEN
            UPDATE SET A.TSSWJG_DM=B.TSSWJG_DM, A.DJXH=B.DJXH, A.CKBGDH=B.CKBGDH, A.NY=B.NY, A.SBRQ=B.SBRQ, A.CKRQ=B.CKRQ_1, A.CKSP_DM=B.CKSP_DM, 
                       A.HGGQKA_DM=B.HGCODE, A.MYGDQSZ_DM=B.GBCODE, A.JGFS_DM=B.TDCODE, A.HZDWDQ_DM=B.HZDWDQDM, A.SJGXSJ=SYSDATE, A.SBYWLX=B.SBYWLX, A.LCSLID=B.LCSLID_SB, 
                       A.MYLAJ=B.MYLAJ,A.JSJE=B.JSJE,A.TSL=B.TSL,A.TMSE=B.TSE,A.CKSL=B.CKSL,A.GHFNSRSBH=B.WTDBTSSCQYNSRSBH,A.HYDXZQH_DM=B.HYDXZQH_DM
          WHEN NOT MATCHED THEN
            INSERT (UUID,TSSWJG_DM,DJXH,CKBGDH,NY,SBRQ,CKRQ,CKSP_DM,HGGQKA_DM,MYGDQSZ_DM,JGFS_DM,HZDWDQ_DM,SJGXSJ,SBYWLX,LCSLID,MYLAJ,JSJE,TSL,TMSE,CKSL,GHFNSRSBH,HYDXZQH_DM)
            VALUES (B.UUID,B.TSSWJG_DM,B.DJXH,B.CKBGDH,B.NY,B.SBRQ,B.CKRQ_1,B.CKSP_DM,B.HGCODE,B.GBCODE,B.TDCODE,B.HZDWDQDM,SYSDATE,B.SBYWLX,B.LCSLID_SB,B.MYLAJ,B.JSJE,B.TSL,B.TSE,B.CKSL,B.WTDBTSSCQYNSRSBH,B.HYDXZQH_DM);
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('CKTS_SB_WZF_CKMX-->JCFX_DATA_TSSBMX失败！', LC_SBYY);
      COMMIT;
  END;
    
  BEGIN
    --补充RMBLAJ
    FOR CUR_TSSB IN (SELECT T.UUID,T.DJXH,T.CKBGDH,MYLAJ,T.NY FROM JCFX_DATA_TSSBMX T WHERE T.SJGXSJ>=TRUNC(SYSDATE,'DD') AND T.SBYWLX='3')
    LOOP
      BEGIN
        SELECT S.RMBLAJ * CUR_TSSB.MYLAJ / S.MYLAJ  --防止部分申报
          INTO V_RMBLAJ
          FROM CKTS_WBSJ_HG_BGD S
         WHERE S.DJXH=CUR_TSSB.DJXH AND S.CKBGDH=CUR_TSSB.CKBGDH;
      EXCEPTION
        WHEN OTHERS THEN
          V_RMBLAJ := NULL;
      END;
      
      IF V_RMBLAJ IS NULL THEN
        SELECT CUR_TSSB.MYLAJ * S.HL_RMB / 100
          INTO V_RMBLAJ
          FROM TL_BJTS.GS_HBZL_HLV S 
         WHERE S.CODE='USD' AND S.HL_YM=CUR_TSSB.NY AND ROWNUM=1;
      END IF;
      
      UPDATE JCFX_DATA_TSSBMX S
         SET S.RMBLAJ = V_RMBLAJ
       WHERE S.UUID=CUR_TSSB.UUID;
      COMMIT;
    END LOOP;
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('JCFX_DATA_TSSBMX补充RMBLAJ失败！', LC_SBYY);
      COMMIT;
  END;

  EXECUTE IMMEDIATE 'ALTER TABLE JCFX_DATA_TSSBMX DISABLE ROW MOVEMENT';
  
  INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('JCFX_DATA_TSSBMX 开始运行，清除作废流程和不予办理数据...');
  COMMIT;
  
  BEGIN
    --根据明细变更情况，删除不予办理数据
    FOR CUR_BYBL IN (SELECT T.UUID FROM CKTS_SB_MDT_CKMX T WHERE T.XGRQ>=V_BEGINDATE AND T.BYBLBZ='Y')
    LOOP
      DELETE FROM JCFX_DATA_TSSBMX S WHERE S.UUID=CUR_BYBL.UUID;
    END LOOP;
    COMMIT;
    
    FOR CUR_BYBL IN (SELECT T.UUID FROM CKTS_SB_MTS_CKMX T WHERE T.XGRQ>=V_BEGINDATE AND T.BYBLBZ='Y')
    LOOP
      DELETE FROM JCFX_DATA_TSSBMX S WHERE S.UUID=CUR_BYBL.UUID;
    END LOOP;
    COMMIT;
    
    FOR CUR_BYBL IN (SELECT T.UUID FROM CKTS_SB_WZF_CKMX T WHERE T.XGRQ>=V_BEGINDATE AND T.BYBLBZ='Y')
    LOOP
      DELETE FROM JCFX_DATA_TSSBMX S WHERE S.UUID=CUR_BYBL.UUID;
    END LOOP;
    COMMIT;
    
    --根据流程信息作废情况，删除作废数据
    FOR CUR_ZFLC IN (SELECT T.LCSLID_SB FROM CKTS_LC_SBXX T WHERE T.ZFRQ>=V_BEGINDATE)
    LOOP
      DELETE FROM JCFX_DATA_TSSBMX S WHERE S.LCSLID=CUR_ZFLC.LCSLID_SB;
    END LOOP;
    COMMIT;

    DELETE FROM JCFX_DATA_TSSBMX T
     WHERE T.SJGXSJ>=ADD_MONTHS(TRUNC(SYSDATE),-1) AND T.SBYWLX='1'
       AND NOT EXISTS (SELECT 1 FROM TL_TSSH.CKTS_SB_MDT_CKMX S WHERE S.UUID=T.UUID);
    COMMIT;

    DELETE FROM JCFX_DATA_TSSBMX T
     WHERE T.SJGXSJ>=ADD_MONTHS(TRUNC(SYSDATE),-1) AND T.SBYWLX='2'
       AND NOT EXISTS (SELECT 1 FROM TL_TSSH.CKTS_SB_MTS_CKMX S WHERE S.UUID=T.UUID);
    COMMIT;

    DELETE FROM JCFX_DATA_TSSBMX T
     WHERE T.SJGXSJ>=ADD_MONTHS(TRUNC(SYSDATE),-1) AND T.SBYWLX='3'
       AND NOT EXISTS (SELECT 1 FROM TL_TSSH.CKTS_SB_WZF_CKMX S WHERE S.UUID=T.UUID);
    COMMIT;

  END;

  INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('JCFX_DATA_TSSBMX 处理结束！');
  COMMIT;
  
  RETURN;
END;
