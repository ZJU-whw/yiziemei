CREATE OR REPLACE PROCEDURE PRO_JKGL_COMPUTE_ZBU_QSPJ
/*
 * 全省平均数据刷新口径
 */
(
  P_ZBYEAR  IN VARCHAR2
)
AS
  V_SQL_SELECT      VARCHAR(1000);
  V_QSPJZ           NUMBER(18,2); --  全省平均值
  V_ROWS            NUMBER(10);  -- 待更新表中是否存在目标记录
BEGIN
  FOR CUR_BGQ IN (SELECT T.BGQID, T.QYLX, T.BGQ_Q, T.BGQ_Z 
                    FROM TL_TSSH.JKGL_DATA_BGQ_QSPJ T
                   WHERE P_ZBYEAR IS NULL 
                      OR TO_CHAR(T.BGQ_Q,'YYYY')=P_ZBYEAR)
  LOOP
    --锁定正在处理的报告期
    UPDATE TL_TSSH.JKGL_DATA_BGQ_QSPJ T
       SET T.TQBZ=SYS_GUID(), T.TQSJ=SYSDATE, T.SXZT='1'
     WHERE T.BGQID=CUR_BGQ.BGQID;
    COMMIT;

    --确定 JKGL_QSPJ_JGB.BGQID 存在
    SELECT COUNT(1)
      INTO V_ROWS
      FROM TL_TSSH.JKGL_QSPJ_JGB T
     WHERE T.BGQID=CUR_BGQ.BGQID AND ROWNUM=1;
    IF V_ROWS=0 THEN
      BEGIN
        INSERT INTO TL_TSSH.JKGL_QSPJ_JGB(ID,BGQID) VALUES (CUR_BGQ.BGQID,CUR_BGQ.BGQID);
        COMMIT;
      END;
    END IF;
    
    --更新全省平均数
    --毛利润
    SELECT 'SELECT C.CW_MLL AS OBJ FROM TL_TSSH.GLXT_BB_SHXT_DJXX A' ||
           ' INNER JOIN TL_TSSH.JKGL_DATA_BGQ B ON B.DJXH=A.DJXH_JS' ||
           ' INNER JOIN TL_TSSH.JKGL_DATA_TJ_ZBU_KZ C ON C.BGQID=B.BGQID' ||
           DECODE(CUR_BGQ.QYLX,'1', ' WHERE A.JSMODE=''1''', ' WHERE A.JSMODE=''2''') ||
           ' AND B.BGQ_Q=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Q,'YYYY-MM-DD')||'''' ||
           ' AND B.BGQ_Z=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Z,'YYYY-MM-DD')||'''' ||
           ' AND C.CW_MLL IS NOT NULL'
      INTO V_SQL_SELECT
      FROM DUAL;
    
    V_QSPJZ := TL_TSSH.F_MY_STDAVG_TMPTB(V_SQL_SELECT);
    
    UPDATE TL_TSSH.JKGL_QSPJ_JGB
       SET MLL = V_QSPJZ
     WHERE BGQID=CUR_BGQ.BGQID;
    COMMIT;
    
    --还原税负率
    SELECT 'SELECT C.CW_HYSFL AS OBJ FROM TL_TSSH.GLXT_BB_SHXT_DJXX A' ||
           ' INNER JOIN TL_TSSH.JKGL_DATA_BGQ B ON B.DJXH=A.DJXH_JS' ||
           ' INNER JOIN TL_TSSH.JKGL_DATA_TJ_ZBU_KZ C ON C.BGQID=B.BGQID' ||
           DECODE(CUR_BGQ.QYLX,'1', ' WHERE A.JSMODE=''1''', ' WHERE A.JSMODE=''2''') ||
           ' AND B.BGQ_Q=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Q,'YYYY-MM-DD')||'''' ||
           ' AND B.BGQ_Z=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Z,'YYYY-MM-DD')||'''' ||
           ' AND C.CW_HYSFL IS NOT NULL'
      INTO V_SQL_SELECT
      FROM DUAL;
    
    V_QSPJZ := TL_TSSH.F_MY_STDAVG_TMPTB(V_SQL_SELECT);
    
    UPDATE TL_TSSH.JKGL_QSPJ_JGB
       SET HYSFL = V_QSPJZ
     WHERE BGQID=CUR_BGQ.BGQID;
    COMMIT;
    
    --费用收入比
    SELECT 'SELECT ROUND(100 * C.LR_XSFY / C.LR_YYSR, 2) AS OBJ FROM TL_TSSH.GLXT_BB_SHXT_DJXX A' ||
           ' INNER JOIN TL_TSSH.JKGL_DATA_BGQ B ON B.DJXH=A.DJXH_JS' ||
           ' INNER JOIN TL_TSSH.JKGL_DATA_TJ_ZBU C ON C.BGQID=B.BGQID' ||
           DECODE(CUR_BGQ.QYLX,'1', ' WHERE A.JSMODE=''1''', ' WHERE A.JSMODE=''2''') ||
           ' AND B.BGQ_Q=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Q,'YYYY-MM-DD')||'''' ||
           ' AND B.BGQ_Z=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Z,'YYYY-MM-DD')||'''' ||
           ' AND C.LR_YYSR>1'
      INTO V_SQL_SELECT
      FROM DUAL;
    
    V_QSPJZ := TL_TSSH.F_MY_STDAVG_TMPTB(V_SQL_SELECT);
    
    UPDATE TL_TSSH.JKGL_QSPJ_JGB
       SET FYSRB = V_QSPJZ
     WHERE BGQID=CUR_BGQ.BGQID;
    COMMIT;
    
    --单位固定资产销售额
    SELECT 'SELECT ROUND(2*C.ZZS_XSE_QB/(C.ZC_GDZC_QC+C.ZC_GDZC_QM),2) AS OBJ' ||
           '  FROM TL_TSSH.GLXT_BB_SHXT_DJXX A' ||
           ' INNER JOIN TL_TSSH.JKGL_DATA_BGQ B ON B.DJXH=A.DJXH_JS' ||
           ' INNER JOIN TL_TSSH.JKGL_DATA_TJ_ZBU C ON C.BGQID=B.BGQID' ||
           DECODE(CUR_BGQ.QYLX,'1', ' WHERE A.JSMODE=''1''', ' WHERE A.JSMODE=''2''') ||
           ' AND B.BGQ_Q=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Q,'YYYY-MM-DD')||'''' ||
           ' AND B.BGQ_Z=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Z,'YYYY-MM-DD')||'''' ||
           ' AND C.ZC_GDZC_QC + C.ZC_GDZC_QM<>0'
      INTO V_SQL_SELECT
      FROM DUAL;
    
    V_QSPJZ := TL_TSSH.F_MY_STDAVG_TMPTB(V_SQL_SELECT);
    
    UPDATE TL_TSSH.JKGL_QSPJ_JGB
       SET DWGDZCXSE = V_QSPJZ
     WHERE BGQID=CUR_BGQ.BGQID;
    COMMIT;
    
    --单位经营面积销售额
    SELECT 'SELECT ROUND(C.ZZS_XSE_QB / D.YJBGCS_MJ, 2) AS OBJ' ||
           '  FROM TL_TSSH.GLXT_BB_SHXT_DJXX A' ||
           ' INNER JOIN TL_TSSH.JKGL_DATA_BGQ B ON B.DJXH=A.DJXH_JS' ||
           ' INNER JOIN TL_TSSH.JKGL_DATA_TJ_ZBU C ON C.BGQID=B.BGQID' ||
           ' INNER JOIN TL_TSSH.JKGL_ZLCJ_JGB D ON D.DJXH=A.DJXH_JS' ||
           DECODE(CUR_BGQ.QYLX,'1', ' WHERE A.JSMODE=''1''', ' WHERE A.JSMODE=''2''') ||
           ' AND B.BGQ_Q=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Q,'YYYY-MM-DD')||'''' ||
           ' AND B.BGQ_Z=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Z,'YYYY-MM-DD')||'''' ||
           ' AND D.YJBGCS_MJ<>0'
      INTO V_SQL_SELECT
      FROM DUAL;
    
    V_QSPJZ := TL_TSSH.F_MY_STDAVG_TMPTB(V_SQL_SELECT);
    
    UPDATE TL_TSSH.JKGL_QSPJ_JGB
       SET DWJYMJXSE = V_QSPJZ
     WHERE BGQID=CUR_BGQ.BGQID;
    COMMIT;

    --确定 JKGL_QSPJ_CKSP.BGQID 不存在
    DELETE FROM TL_TSSH.JKGL_QSPJ_CKSP T WHERE T.BGQID=CUR_BGQ.BGQID;
    COMMIT;
    
    --ID  N NUMBER(20)  N     序号
    --BGQID N NUMBER(20)  Y     报告期ID 关联主表PK_JKGL_DATA_BGQ
    --SP8_DM N VARCHAR2(8) Y     商品代码（8）
    --CKEUSD  N NUMBER(18,2)  Y     出口额USD
    --CKERMB N NUMBER(18,2)  Y     出口额
    --CKSL  N NUMBER(18,2)  Y     出口数量
    --QYHS  N INTEGER Y     企业户数
    INSERT INTO JKGL_QSPJ_CKSP (ID,BGQID,SP8_DM,CKEUSD,CKERMB,CKSL,QYHS)
         SELECT SEQ_JKGL_QSPJ_CKSP.NEXTVAL,CUR_BGQ.BGQID,SP8_DM,CKEUSD,CKERMB,CKSL,QYHS
           FROM (SELECT C.SP8_DM,SUM(C.CKSL) AS CKSL,SUM(C.CKEUSD) AS CKEUSD,SUM(C.CKERMB) AS CKERMB,
                        COUNT(DISTINCT A.DJXH_JS) AS QYHS
                   FROM TL_TSSH.GLXT_BB_SHXT_DJXX A
                  INNER JOIN TL_TSSH.JKGL_DATA_BGQ B ON B.DJXH=A.DJXH_JS
                  INNER JOIN TL_TSSH.JKGL_DATA_TJ_ZBU_CKSP C ON C.BGQID=B.BGQID
                  WHERE DECODE(A.JSMODE,'1','1','2')=CUR_BGQ.QYLX
                    AND B.BGQ_Q=CUR_BGQ.BGQ_Q 
                    AND B.BGQ_Z=CUR_BGQ.BGQ_Z
                  GROUP BY C.SP8_DM) TT;
    COMMIT;
    
    --CKDJ  N NUMBER(18,2)  Y     出口单价
    --MMYLR N NUMBER(18,2)  Y     每美元利润
    FOR CUR_CKSP IN (SELECT ID,SP8_DM FROM TL_TSSH.JKGL_QSPJ_CKSP WHERE BGQID=CUR_BGQ.BGQID ORDER BY ID)
    LOOP
      SELECT 'SELECT C.CKDJ AS OBJ FROM TL_TSSH.GLXT_BB_SHXT_DJXX A' ||
             ' INNER JOIN TL_TSSH.JKGL_DATA_BGQ B ON B.DJXH=A.DJXH_JS' ||
             ' INNER JOIN TL_TSSH.JKGL_DATA_TJ_ZBU_CKSP C ON C.BGQID=B.BGQID' ||
             DECODE(CUR_BGQ.QYLX,'1', ' WHERE A.JSMODE=''1''', ' WHERE A.JSMODE=''2''') ||
             ' AND B.BGQ_Q=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Q,'YYYY-MM-DD')||'''' ||
             ' AND B.BGQ_Z=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Z,'YYYY-MM-DD')||'''' ||
             ' AND C.SP8_DM='''|| CUR_CKSP.SP8_DM || '''' ||
             ' AND C.CKDJ IS NOT NULL'
        INTO V_SQL_SELECT
        FROM DUAL;
      
      V_QSPJZ := TL_TSSH.F_MY_STDAVG_TMPTB(V_SQL_SELECT);
      
      UPDATE TL_TSSH.JKGL_QSPJ_CKSP
         SET CKDJ = V_QSPJZ
       WHERE ID=CUR_CKSP.ID;
      COMMIT;
      
      IF CUR_BGQ.QYLX = '2' THEN
        SELECT 'SELECT C.MMYLR AS OBJ FROM TL_TSSH.GLXT_BB_SHXT_DJXX A' ||
               ' INNER JOIN TL_TSSH.JKGL_DATA_BGQ B ON B.DJXH=A.DJXH_JS' ||
               ' INNER JOIN TL_TSSH.JKGL_DATA_TJ_ZBU_TSSP C ON C.BGQID=B.BGQID' ||
               ' WHERE A.JSMODE=''2''' ||
               ' AND B.BGQ_Q=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Q,'YYYY-MM-DD')||'''' ||
               ' AND B.BGQ_Z=DATE'''||TO_CHAR(CUR_BGQ.BGQ_Z,'YYYY-MM-DD')||'''' ||
               ' AND C.SP8_DM='''|| CUR_CKSP.SP8_DM || '''' ||
               ' AND C.MMYLR IS NOT NULL'
          INTO V_SQL_SELECT
          FROM DUAL;
        
        V_QSPJZ := TL_TSSH.F_MY_STDAVG_TMPTB(V_SQL_SELECT);
        
        UPDATE TL_TSSH.JKGL_QSPJ_CKSP
           SET MMYLR = V_QSPJZ
         WHERE ID=CUR_CKSP.ID;
        COMMIT;
      END IF;
    END LOOP;

    --解锁处理完成的报告期
    UPDATE TL_TSSH.JKGL_DATA_BGQ_QSPJ T
       SET T.TQBZ=NULL, T.WCSJ=SYSDATE, T.SXZT='2'
     WHERE T.BGQID=CUR_BGQ.BGQID;
    COMMIT;
  END LOOP;

  RETURN;
END;
