CREATE OR REPLACE PROCEDURE PRO_JKGL_COMPUTE_W30401
/*
 * 根据报告期和基期分商品（8位HS编码）出口汇总指标元，
 * 商品出口额阈值>（参数1：阈值） 且 出口销售额同比>（参数2：150%）的敏感商品数量。
 * 报告期新增敏感出口商品只要出口额>（参数1阈值）即计入。
 * ZB_VAL：敏感商品出口数量
 */
(
  P_BGQID   IN NUMBER,
  P_JQID    IN NUMBER,
  P_SWJGDM  IN VARCHAR
)
AS
  V_ZB_VAL     NUMBER(18,2);
  V_ROWS       NUMBER(10);
  V_BADPOINT   CHAR(1);
  VAL1         NUMBER(18,2);    --参数1
  VAL2         NUMBER(18,2);    --参数1
  V_PARAMS     VARCHAR(4000);
BEGIN
  BEGIN
    SELECT NVL(S.VAL_DEF,T.VAL_DEF) / DECODE(T.CSTYPE,'百分比',100, 1)
      INTO VAL1
      FROM JKGL_PZ_ZB_CS T
      LEFT JOIN JKGL_PZ_ZB_CS_SWJG S ON S.CSBM=T.CSBM AND S.SWJG_DM=P_SWJGDM AND S.YXBZ='Y'
     WHERE T.CSBM='ZC_W30401_MGSP_CKE_HB';
    SELECT NVL(S.VAL_DEF,T.VAL_DEF) / DECODE(T.CSTYPE,'百分比',100, 1)
      INTO VAL2
      FROM JKGL_PZ_ZB_CS T
      LEFT JOIN JKGL_PZ_ZB_CS_SWJG S ON S.CSBM=T.CSBM AND S.SWJG_DM=P_SWJGDM AND S.YXBZ='Y'
     WHERE T.CSBM='ZC_W30401_MGSP_CKE_JE';
    
    V_ZB_VAL := 0;
    FOR CUR_SPDM IN (SELECT T.SP8_DM,DM.CKSP_MC,T.CKEUSD,NVL(JQ.CKEUSD,0) AS JQCKE
                       FROM TL_TSSH.JKGL_DATA_TJ_ZBU_CKSP T
                      INNER JOIN TL_TSSH.JKGL_GY_MGSP_SWJG MG ON MG.MGSP_DM=T.SP8_DM AND MG.QYBZ='Y'
                       LEFT JOIN TL_TSSH.JKGL_DATA_TJ_ZBU_CKSP JQ ON JQ.BGQID=P_JQID AND JQ.SP8_DM=T.SP8_DM
                       LEFT JOIN TL_TSSH.JCFX_DM_CKSPTREE DM ON DM.CKSP_DM=T.SP8_DM AND DM.CKSP_JC='4'
                      WHERE T.BGQID=P_BGQID
                        AND T.CKEUSD>=VAL2
                        AND T.CKEUSD>=VAL1 * NVL(JQ.CKEUSD,0))
    LOOP
      V_ZB_VAL := V_ZB_VAL +1;
      IF V_ZB_VAL=1 THEN
        V_PARAMS := '[d]敏感商品代码=' || CUR_SPDM.SP8_DM || '（' || CUR_SPDM.CKSP_MC ||'），报告期出口额=' || CUR_SPDM.CKEUSD || '，基期出口额=' || CUR_SPDM.JQCKE;
      ELSIF V_ZB_VAL<=20 THEN
        V_PARAMS := V_PARAMS || '|敏感商品代码=' || CUR_SPDM.SP8_DM || '（' || CUR_SPDM.CKSP_MC ||'），报告期出口额=' || CUR_SPDM.CKEUSD || '，基期出口额=' || CUR_SPDM.JQCKE;
      END IF;
    END LOOP;
    IF V_ZB_VAL>20 THEN
      V_PARAMS := V_PARAMS || '|...';
    END IF;
  EXCEPTION
    WHEN OTHERS THEN
      V_ZB_VAL := NULL;
  END;

  IF V_ZB_VAL IS NULL THEN
    V_BADPOINT := 'Y';
  ELSE
    V_BADPOINT := 'N';
  END IF;

  SELECT COUNT(1)
    INTO V_ROWS
    FROM JKGL_DATA_TJ_ZB T
   WHERE T.BGQID=P_BGQID AND T.ZB_ID='W30401' AND ROWNUM=1;
  IF V_ROWS=0 THEN
    INSERT INTO JKGL_DATA_TJ_ZB(BGQID,ZB_ID,ZB_VAL,BADPOINT,PARAMS)
           VALUES(P_BGQID,'W30401',V_ZB_VAL,V_BADPOINT,V_PARAMS);
  ELSE
    UPDATE JKGL_DATA_TJ_ZB T
       SET T.ZB_VAL=V_ZB_VAL, T.BADPOINT=V_BADPOINT, T.PARAMS=V_PARAMS, T.UPTIME=SYSDATE
     WHERE T.BGQID=P_BGQID AND T.ZB_ID='W30401';
  END IF;
  COMMIT;

  RETURN;
END;
/
