  --CKTS_LC_SEHZXX数据处理（GKBL_、XHRQ_、SNCKZB）
  BEGIN
    --CKTMSJHSSSWJGDM、MDTKSSSWJGDM补充
    UPDATE CKTS_LC_SEHZXX T
       SET T.CKTMSJHSSSWJGDM=T.TSSWJG_DM
     WHERE T.CKTMSJHSSSWJGDM IS NULL;
    COMMIT;
    UPDATE CKTS_LC_SEHZXX T
       SET T.MDTKSSSWJGDM=T.TSSWJG_DM
     WHERE T.MDTKSSSWJGDM IS NULL;
    COMMIT;
    --税额核准数为0的情况更新
    UPDATE CKTS_LC_SEHZXX T
       SET T.GKBL_ZZSTSE=0, T.XHRQ_TK =T.SEHZRQ, T.KPRQ=T.SEHZRQ
     WHERE T.GKBL_ZZSTSE IS NULL AND T.SEHZ_ZZSTSE=0;
    COMMIT;
    UPDATE CKTS_LC_SEHZXX T
       SET T.GKBL_XFSTSE=0, T.XHRQ_XFS =T.SEHZRQ
     WHERE T.GKBL_XFSTSE IS NULL AND T.SEHZ_XFSTSE=0;
    COMMIT;
    UPDATE CKTS_LC_SEHZXX T
       SET T.GKBL_MDSE=0, T.XHRQ_MD =T.SEHZRQ
     WHERE T.GKBL_MDSE IS NULL AND T.SEHZ_MDSE=0;
    COMMIT;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_LC_SEHZXX.GKBL_(SEHZ_=0)！');
      COMMIT;
    END IF;

    --根据收核回推至LD_DEALDATA免抵调数据，更新税额核准表办理数
    FOR CUR_TKXX IN (SELECT R.UUID,R.SEHZ_MDSE,LEAST(R.SEHZ_MDSE,S.MD_AMT,T.JE) AS GKBL_MDSE, T.XHRQ_1, NVL(T.HSSWJG_DM,R.CKTMSJHSSSWJGDM) AS MDTKSSSWJGDM
                       FROM CKTS_ZS_TKGZ T
                      INNER JOIN CKTS_ZS_MDTKB S ON S.DJXH=T.DJXH AND S.CKTS_NO=T.BTKGZUUID AND S.KJTKBJ='Y'
                      INNER JOIN CKTS_LC_SEHZXX R ON R.DJXH=T.DJXH AND NVL(R.GZTKTZSBH,R.YWHZBID||R.XH)=S.CKTS_NO AND R.XHRQ_MD>SYSDATE
                      WHERE T.XHRQ_1>=LD_DEALDATA AND T.TZSLY='3' AND T.TZLX_DM='1' AND T.GZBZ='Y' AND T.ZFRQ_1 IS NULL
                        AND T.JE>0
                        AND NOT EXISTS (SELECT 1
                                          FROM CKTS_LC_SEHZXX Q
                                         WHERE Q.DJXH=T.DJXH
                                           AND NVL(Q.GZTKTZSBH,Q.YWHZBID||Q.XH)=S.CKTS_NO
                                           AND Q.XHRQ_MD=T.XHRQ_1))
    LOOP
      BEGIN
        IF CUR_TKXX.SEHZ_MDSE<=CUR_TKXX.GKBL_MDSE THEN
          UPDATE CKTS_LC_SEHZXX T
             SET T.GKBL_MDSE = CUR_TKXX.GKBL_MDSE,
                 T.XHRQ_MD = CUR_TKXX.XHRQ_1,
                 T.MDTKSSSWJGDM = CUR_TKXX.MDTKSSSWJGDM
           WHERE T.UUID=CUR_TKXX.UUID;
          COMMIT;
        ELSE
          INSERT INTO CKTS_LC_SEHZXX(UUID,LCSLID_FS,TSSWJG_DM,DJXH,YWHZBUUID,YWHZBID,XH,SEHZR_DM,SEHZRQ,LRR_DM,
                      SJTB_SJ,XGRQ,SJTB_BZ,SBYWB_DM,SSQ,SBPC,CKQYGLLB_DM,WZHBZ,LCTJJC,CKTMSHWYSFWLX_DM,SNCKZB,
                      GZTKTZSBH,CKTMSJHSSSWJGDM,MDTKSSSWJGDM,KPRQ,XHRQ_TK,XHRQ_MD,XHRQ_XFS,
                      SEHZ_MDTSE,SEHZ_ZZSTSE,SEHZ_XFSTSE,SEHZ_MDSE,
                      GKBL_MDTSE,GKBL_ZZSTSE,GKBL_XFSTSE,GKBL_MDSE)
               SELECT 'YANGUOPINGXTYW'||TO_CHAR(SYSDATE,'YYYYMMDD')||TO_CHAR(SEQ_DEAL_TKGZ.NEXTVAL),
                      LCSLID_FS,TSSWJG_DM,DJXH,YWHZBUUID,YWHZBID,XH,SEHZR_DM,SEHZRQ,LRR_DM,
                      SJTB_SJ,XGRQ,SJTB_BZ,SBYWB_DM,SSQ,SBPC,CKQYGLLB_DM,WZHBZ,LCTJJC,CKTMSHWYSFWLX_DM,SNCKZB,
                      GZTKTZSBH,CKTMSJHSSSWJGDM,MDTKSSSWJGDM,KPRQ,XHRQ_TK,XHRQ_MD,XHRQ_XFS,
                      CUR_TKXX.SEHZ_MDSE-CUR_TKXX.GKBL_MDSE,0,0,CUR_TKXX.SEHZ_MDSE-CUR_TKXX.GKBL_MDSE,
                      0,0,0,0
                 FROM CKTS_LC_SEHZXX
                WHERE UUID=CUR_TKXX.UUID;
          UPDATE CKTS_LC_SEHZXX T
             SET T.SEHZ_MDTSE = T.SEHZ_ZZSTSE + T.SEHZ_XFSTSE + CUR_TKXX.GKBL_MDSE,
                 T.SEHZ_MDSE = CUR_TKXX.GKBL_MDSE,
                 T.GKBL_MDSE = CUR_TKXX.GKBL_MDSE,
                 T.XHRQ_MD = CUR_TKXX.XHRQ_1,
                 T.MDTKSSSWJGDM = CUR_TKXX.MDTKSSSWJGDM
           WHERE T.UUID=CUR_TKXX.UUID;
          COMMIT;
        END IF;
      END;
    END LOOP;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_LC_SEHZXX.GKBL_MDSE(SEHZ_<>0)！');
      COMMIT;
    END IF;

    --根据收核回推至LD_DEALDATA增值税退库数据，更新税额核准表办理数
    --KPRQ
    FOR CUR_TKXX IN (SELECT T.UUID,S.KPRQ,S.THRQ_1 FROM CKTS_ZS_SRTHS S, CKTS_LC_SEHZXX T
                      WHERE UPPER(TRIM(T.LRR_DM))='SJQY' AND S.KPRQ>=LD_DEALDATA AND S.TZLX_DM IN ('1','4') AND T.DJXH=S.DJXH AND T.ZZSSSSRTHSBH=S.YDTUUID AND T.XHRQ_TK>SYSDATE)
    LOOP
      BEGIN
        IF CUR_TKXX.THRQ_1 IS NOT NULL THEN
          UPDATE CKTS_LC_SEHZXX T
             SET T.GKBL_ZZSTSE=T.SEHZ_ZZSTSE,
                 T.XHRQ_TK = CUR_TKXX.THRQ_1,
                 T.KPRQ = GREATEST(CUR_TKXX.KPRQ,T.SEHZRQ)
           WHERE T.UUID=CUR_TKXX.UUID;
        ELSE
          UPDATE CKTS_LC_SEHZXX T
             SET T.KPRQ = GREATEST(CUR_TKXX.KPRQ,T.SEHZRQ)
           WHERE T.UUID=CUR_TKXX.UUID;
        END IF;
        COMMIT;
      END;
    END LOOP;
    --THRQ_1
    FOR CUR_TKXX IN (SELECT T.UUID,S.KPRQ,S.THRQ_1 FROM CKTS_ZS_SRTHS S, CKTS_LC_SEHZXX T
                      WHERE UPPER(TRIM(T.LRR_DM))='SJQY' AND GREATEST(S.THRQ_1,S.XHRQ_1)>=LD_DEALDATA AND S.TZLX_DM IN ('1','4') AND T.DJXH=S.DJXH AND T.ZZSSSSRTHSBH=S.YDTUUID AND T.XHRQ_TK>SYSDATE)
    LOOP
      BEGIN
        UPDATE CKTS_LC_SEHZXX T
           SET T.GKBL_ZZSTSE=T.SEHZ_ZZSTSE,
               T.XHRQ_TK = CUR_TKXX.THRQ_1,
               T.KPRQ = GREATEST(CUR_TKXX.KPRQ,T.SEHZRQ)
         WHERE T.UUID=CUR_TKXX.UUID;
        COMMIT;
      END;
    END LOOP;
    --KPRQ
    FOR CUR_TKXX IN (SELECT T.UUID,S.KPRQ,S.THRQ_1 FROM CKTS_ZS_SRTHS S, CKTS_LC_SEHZXX T
                      WHERE UPPER(TRIM(T.LRR_DM))<>'SJQY' AND S.KPRQ>=LD_DEALDATA AND S.TZLX_DM IN ('1','4') AND T.DJXH=S.DJXH AND T.ZZSSSSRTHSBH=S.YDTLYUUID AND T.XHRQ_TK>SYSDATE)
    LOOP
      BEGIN
        IF CUR_TKXX.THRQ_1 IS NOT NULL THEN
          UPDATE CKTS_LC_SEHZXX T
             SET T.GKBL_ZZSTSE=T.SEHZ_ZZSTSE,
                 T.XHRQ_TK = CUR_TKXX.THRQ_1,
                 T.KPRQ = GREATEST(CUR_TKXX.KPRQ,T.SEHZRQ)
           WHERE T.UUID=CUR_TKXX.UUID;
        ELSE
          UPDATE CKTS_LC_SEHZXX T
             SET T.KPRQ = GREATEST(CUR_TKXX.KPRQ,T.SEHZRQ)
           WHERE T.UUID=CUR_TKXX.UUID;
        END IF;
        COMMIT;
      END;
    END LOOP;
    --THRQ_1
    FOR CUR_TKXX IN (SELECT T.UUID,S.KPRQ,S.THRQ_1 FROM CKTS_ZS_SRTHS S, CKTS_LC_SEHZXX T
                      WHERE UPPER(TRIM(T.LRR_DM))<>'SJQY' AND GREATEST(S.THRQ_1,S.XHRQ_1)>=LD_DEALDATA AND S.TZLX_DM IN ('1','4') AND T.DJXH=S.DJXH AND T.ZZSSSSRTHSBH=S.YDTLYUUID AND T.XHRQ_TK>SYSDATE)
    LOOP
      BEGIN
        UPDATE CKTS_LC_SEHZXX T
           SET T.GKBL_ZZSTSE=T.SEHZ_ZZSTSE,
               T.XHRQ_TK = CUR_TKXX.THRQ_1,
               T.KPRQ = GREATEST(CUR_TKXX.KPRQ,T.SEHZRQ)
         WHERE T.UUID=CUR_TKXX.UUID;
        COMMIT;
      END;
    END LOOP;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_LC_SEHZXX.GKBL_ZZSTSE(SEHZ_>0)！');
      COMMIT;
    END IF;
    --增值税审核数为负处理
    FOR CUR_TKXX IN (SELECT T.UUID,T.DJXH,T.ZZSSSSRTHSBH,T.SEHZ_ZZSTSE FROM CKTS_LC_SEHZXX T
                      WHERE T.SEHZ_ZZSTSE<0 AND T.XHRQ_TK>SYSDATE AND T.ZZSSSSRTHSBH IS NOT NULL)
    LOOP
      BEGIN
        -- 检查是否正负对冲及对冲后剩余税额
        SELECT SUM(T.SEHZ_ZZSTSE),SUM(NVL(T.GKBL_ZZSTSE,0))
          INTO LN_ZZS,SN_ZZS
          FROM CKTS_LC_SEHZXX T
         WHERE T.DJXH=CUR_TKXX.DJXH AND T.ZZSSSSRTHSBH=CUR_TKXX.ZZSSSSRTHSBH;
        IF LN_ZZS=0 THEN
          --对冲后为0
          UPDATE CKTS_LC_SEHZXX T
             SET T.GKBL_ZZSTSE=T.SEHZ_ZZSTSE,
                 T.KPRQ = T.SEHZRQ,
                 T.XHRQ_TK = T.SEHZRQ
           WHERE T.DJXH=CUR_TKXX.DJXH AND T.ZZSSSSRTHSBH=CUR_TKXX.ZZSSSSRTHSBH;
          COMMIT;
        ELSIF LN_ZZS<0 THEN
          --对冲后为负数，需要返纳，考虑用户分次返纳的情况
          BEGIN
            SELECT COUNT(1),SUM(S.SJJE),MAX(S.KJRQ),MAX(S.RKRQ)
              INTO LN_I, SY_ZZS, V_TSKP_DATE,V_TSTK_DATE
              FROM TL_ADMIN.FG_CKTSFN_HXZG S
             WHERE S.DJXH=CUR_TKXX.DJXH AND S.YZPZXH_CKTS=CUR_TKXX.ZZSSSSRTHSBH AND S.RKRQ IS NOT NULL;
            IF LN_I>0 THEN
              --存在返纳入库记录的时候判断
              IF SY_ZZS+LN_ZZS=0 THEN
                --返纳数+税额核准数=0，表示对应退还书已全部返纳
                UPDATE CKTS_LC_SEHZXX T
                   SET T.GKBL_ZZSTSE=T.SEHZ_ZZSTSE,
                       T.KPRQ = V_TSKP_DATE,
                       T.XHRQ_TK = V_TSTK_DATE
                 WHERE T.DJXH=CUR_TKXX.DJXH AND T.ZZSSSSRTHSBH=CUR_TKXX.ZZSSSSRTHSBH
                   AND T.XHRQ_TK>SYSDATE;
                COMMIT;
              ELSIF SY_ZZS+SN_ZZS+CUR_TKXX.SEHZ_ZZSTSE>=0 THEN
                --返纳数+已办理数+当前未销号记录核准数>=0，表示对应未销号记录已全部返纳
                UPDATE CKTS_LC_SEHZXX T
                   SET T.GKBL_ZZSTSE=T.SEHZ_ZZSTSE,
                       T.KPRQ = V_TSKP_DATE,
                       T.XHRQ_TK = V_TSTK_DATE
                 WHERE T.UUID=CUR_TKXX.UUID;
                COMMIT;
              ELSIF SY_ZZS+SN_ZZS>0 THEN
                --返纳数+已办理数>0，表示对应未销号记录可部分返纳，按（SY_ZZS+SN_ZZS）拆分已返纳部分
                INSERT INTO CKTS_LC_SEHZXX(UUID,LCSLID_FS,TSSWJG_DM,DJXH,YWHZBUUID,YWHZBID,XH,SEHZR_DM,SEHZRQ,LRR_DM,
                            SJTB_SJ,XGRQ,SJTB_BZ,SBYWB_DM,SSQ,SBPC,CKQYGLLB_DM,WZHBZ,LCTJJC,CKTMSHWYSFWLX_DM,SNCKZB,
                            ZZSSSSRTHSBH,CKTMSJHSSSWJGDM,MDTKSSSWJGDM,KPRQ,XHRQ_TK,XHRQ_MD,XHRQ_XFS,
                            SEHZ_MDTSE,SEHZ_ZZSTSE,SEHZ_XFSTSE,SEHZ_MDSE,
                            GKBL_MDTSE,GKBL_ZZSTSE,GKBL_XFSTSE,GKBL_MDSE)
                     SELECT 'YANGUOPINGXTYW'||TO_CHAR(SYSDATE,'YYYYMMDD')||TO_CHAR(SEQ_DEAL_TKGZ.NEXTVAL),
                            LCSLID_FS,TSSWJG_DM,DJXH,YWHZBUUID,YWHZBID,XH,SEHZR_DM,SEHZRQ,LRR_DM,
                            SJTB_SJ,XGRQ,SJTB_BZ,SBYWB_DM,SSQ,SBPC,CKQYGLLB_DM,WZHBZ,LCTJJC,CKTMSHWYSFWLX_DM,SNCKZB,
                            ZZSSSSRTHSBH,CKTMSJHSSSWJGDM,MDTKSSSWJGDM,KPRQ,XHRQ_TK,XHRQ_MD,XHRQ_XFS,
                            (SY_ZZS+SN_ZZS)+CUR_TKXX.SEHZ_ZZSTSE,(SY_ZZS+SN_ZZS)+CUR_TKXX.SEHZ_ZZSTSE,0,0,
                            0,0,0,0
                       FROM CKTS_LC_SEHZXX
                      WHERE UUID=CUR_TKXX.UUID;
                UPDATE CKTS_LC_SEHZXX T
                   SET T.SEHZ_MDTSE = 0 - (SY_ZZS+SN_ZZS) + T.SEHZ_XFSTSE + T.SEHZ_MDSE,
                       T.SEHZ_ZZSTSE = 0 - (SY_ZZS+SN_ZZS),
                       T.GKBL_ZZSTSE = 0 - (SY_ZZS+SN_ZZS),
                       T.KPRQ = V_TSKP_DATE,
                       T.XHRQ_TK = V_TSTK_DATE
                 WHERE T.UUID=CUR_TKXX.UUID;
                COMMIT;
              END IF;
            END IF;
          EXCEPTION
            WHEN OTHERS THEN
              CONTINUE;
          END;
        END IF;
      END;
    END LOOP;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_LC_SEHZXX.GKBL_ZZSTSE(SEHZ_<0)(对冲/返纳)！');
      COMMIT;
    END IF;

    --根据收核回推两天消费税退库数据，更新税额核准表办理数
    FOR CUR_TKXX IN (SELECT T.UUID,S.KPRQ,S.THRQ_1 FROM CKTS_ZS_SRTHS S, CKTS_LC_SEHZXX T
                      WHERE UPPER(TRIM(T.LRR_DM))='SJQY' AND GREATEST(S.THRQ_1,S.XHRQ_1)>=LD_DEALDATA AND S.TZLX_DM IN ('1','4') AND T.DJXH=S.DJXH AND T.XFSSSSRTHSBH=S.YDTUUID AND T.XHRQ_XFS>SYSDATE)
    LOOP
      BEGIN
        UPDATE TL_TSSH.CKTS_LC_SEHZXX T
           SET T.GKBL_XFSTSE=T.SEHZ_XFSTSE,
               T.XHRQ_XFS = CUR_TKXX.THRQ_1,
               T.KPRQ = GREATEST(CUR_TKXX.KPRQ,T.SEHZRQ)
         WHERE T.UUID=CUR_TKXX.UUID;
        COMMIT;
      END;
    END LOOP;
    FOR CUR_TKXX IN (SELECT T.UUID,S.KPRQ,S.THRQ_1 FROM CKTS_ZS_SRTHS S, CKTS_LC_SEHZXX T
                      WHERE UPPER(TRIM(T.LRR_DM))<>'SJQY' AND GREATEST(S.THRQ_1,S.XHRQ_1)>=LD_DEALDATA AND S.TZLX_DM IN ('1','4') AND T.DJXH=S.DJXH AND T.XFSSSSRTHSBH=S.YDTLYUUID AND T.XHRQ_XFS>SYSDATE)
    LOOP
      BEGIN
        UPDATE CKTS_LC_SEHZXX T
           SET T.GKBL_XFSTSE=T.SEHZ_XFSTSE,
               T.XHRQ_XFS = CUR_TKXX.THRQ_1,
               T.KPRQ = GREATEST(CUR_TKXX.KPRQ,T.SEHZRQ)
         WHERE T.UUID=CUR_TKXX.UUID;
        COMMIT;
      END;
    END LOOP;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_LC_SEHZXX.GKBL_XFSTSE(SEHZ_<>0)！');
      COMMIT;
    END IF;
    --消费税审核数为负处理
    FOR CUR_TKXX IN (SELECT T.UUID,T.DJXH,T.XFSSSSRTHSBH,T.SEHZ_XFSTSE FROM CKTS_LC_SEHZXX T
                     WHERE T.SEHZ_XFSTSE<0 AND T.XHRQ_XFS>SYSDATE AND T.XFSSSSRTHSBH IS NOT NULL)
    LOOP
      BEGIN
        -- 检查是否正负对冲及对冲后剩余税额
        SELECT SUM(T.SEHZ_XFSTSE),SUM(NVL(T.GKBL_XFSTSE,0))
          INTO LN_XFS,SN_XFS
          FROM CKTS_LC_SEHZXX T
         WHERE T.DJXH=CUR_TKXX.DJXH AND T.XFSSSSRTHSBH=CUR_TKXX.XFSSSSRTHSBH;
        IF LN_XFS=0 THEN
          --对冲后为0
          UPDATE CKTS_LC_SEHZXX T
             SET T.GKBL_XFSTSE=T.SEHZ_XFSTSE,
                 T.KPRQ = T.SEHZRQ,
                 T.XHRQ_XFS = T.SEHZRQ
           WHERE T.DJXH=CUR_TKXX.DJXH AND T.XFSSSSRTHSBH=CUR_TKXX.XFSSSSRTHSBH;
          COMMIT;
        ELSIF LN_XFS<0 THEN
          --对冲后为负数，需要返纳，考虑用户分次返纳的情况
          BEGIN
            SELECT COUNT(1),SUM(S.SJJE),MAX(S.KJRQ),MAX(S.RKRQ)
              INTO LN_I, SY_XFS, V_TSKP_DATE,V_TSTK_DATE
              FROM TL_ADMIN.FG_CKTSFN_HXZG S
             WHERE S.DJXH=CUR_TKXX.DJXH AND S.YZPZXH_CKTS=CUR_TKXX.XFSSSSRTHSBH AND S.RKRQ IS NOT NULL;
            IF LN_I>0 THEN
              --存在返纳入库记录的时候判断
              IF SY_XFS+LN_XFS=0 THEN
                --返纳数+税额核准数=0，表示对应退还书已全部返纳
                UPDATE CKTS_LC_SEHZXX T
                   SET T.GKBL_XFSTSE=T.SEHZ_XFSTSE,
