CREATE OR REPLACE PROCEDURE PRO_DEAL_AFTER_ETL
(
  V_ERROR   OUT NUMBER,
  V_MSG     OUT VARCHAR2
)
AS
  LC_SBYY          VARCHAR2(2000);
  LD_DEALDATA      DATE;          --用于基础数据处理的提前量
  LN_LOG           NUMBER(2);
  LC_BBNY          VARCHAR2(6);   --本期制表年月
  LD_BBNY_KSNF     DATE;          --本期制表年月年初
  LD_BBNY_KSRQ     DATE;          --本期制表年月开始日期，一般为制表年月的月初
  LD_BBNY_JZRQ     DATE;          --本期制表年月结束日期，一般为制表年月的下一个月初
  LC_DJZCLX        VARCHAR2(6);   --本期制表年月
  GLH_JSJE         NUMBER(18,2);
  GLH_TSL          NUMBER(18,2);
  GLH_TMSE         NUMBER(18,2);
  LN_ALLCK         NUMBER(18,2);
  LN_SNCK          NUMBER(18,2);
  LN_MYLAJ         NUMBER(18,2);
  LN_RMBLAJ        NUMBER(18,2);
  LN_MDTSE         NUMBER(18,2);
  LN_ZH_MDTSE      NUMBER(18,2);
  LN_BYTS_MDTSE    NUMBER(18,2);
  LN_BYBL_MDTSE    NUMBER(18,2);
  LN_ZZS           NUMBER(18,2);
  LN_XFS           NUMBER(18,2);
  LN_MDSE          NUMBER(18,2);
  SN_ZZS           NUMBER(18,2);
  SN_XFS           NUMBER(18,2);
  SN_MDSE          NUMBER(18,2);
  SY_ZZS           NUMBER(18,2);
  SY_XFS           NUMBER(18,2);
  SY_MDSE          NUMBER(18,2);
  LD_LASTRQ        DATE;
  V_ZLC_FS         NUMBER(18,2);
  V_ZLC_TS_AMT     NUMBER(18,2);
  V_ZLC_MD_AMT     NUMBER(18,2);
  V_ZLC_ZK_AMT     NUMBER(18,2);
  V_FF_DATE        DATE;
  V_SL_DATE        DATE;
  V_FH_DATE        DATE;
  V_FH_USER        VARCHAR2(20);
  V_YWHZ_DATE      DATE;
  V_YWHZ_USER      VARCHAR2(20);
  V_SEHZ_DATE      DATE;
  V_SEHZ_USER      VARCHAR2(20);
  V_TSKP_DATE      DATE;
  V_TSTK_DATE      DATE;
  LN_I             NUMBER(10);
  V_ZFBZ           CHAR(1);
  V_ZFR_DM         VARCHAR2(100);
  V_ZFRQ           DATE;
  V_CKSPTSSPLX_DM  CHAR(1);
  V_TSL            NUMBER(18,2);
  V_JGFSTSLX_DM    CHAR(1);
  V_HYDXZQH_DM     CHAR(4);
BEGIN
  V_ERROR :=0;
  V_MSG   := ' ';

  LD_DEALDATA:=TRUNC(SYSDATE) - 3;
  LN_LOG  :=2;

  INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('PRO_DEAL_AFTER_ETL开始处理！');
  COMMIT;

  --获取当前制表区间
  BEGIN
    SELECT T.BBNY, T.BBNY_KSRQ, T.BBNY_JZRQ, T.BBNY_KSNF
      INTO LC_BBNY, LD_BBNY_KSRQ, LD_BBNY_JZRQ, LD_BBNY_KSNF
      FROM (SELECT *
              FROM TL_ADMIN.TJBB_CS_ZBRQ
             WHERE SYSDATE>=BBNY_JZRQ
             ORDER BY BBNY_JZRQ DESC) T
     WHERE ROWNUM=1;

    INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('获取当前制表区间成功！');
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('获取当前制表区间失败！', LC_SBYY);
      COMMIT;

      LC_BBNY := TO_CHAR(ADD_MONTHS(SYSDATE,-1),'YYYYMM');
      LD_BBNY_KSRQ := TRUNC(ADD_MONTHS(SYSDATE,-1),'MM');
      LD_BBNY_JZRQ := TRUNC(SYSDATE,'MM');
      LD_BBNY_KSNF := TRUNC(ADD_MONTHS(SYSDATE,-1),'YY');
  END;

  --对部分外贸企业免退税申报，前一次全部分流以后又作废重新申报导致CKTS_LC_SBXX数据重复，LCSLID_SB设置错误进行纠正
  BEGIN
    LN_I:=0;
    FOR CUR_DUP IN (SELECT T.DJXH,T.SSQ,T.SBPC
                      FROM CKTS_LC_SBXX T
                     WHERE T.SBYWB_DM='A0301001' AND T.ZFBZ IS NULL
                     GROUP BY T.DJXH,T.SSQ,T.SBPC
                    HAVING COUNT(1)>1)
    LOOP
      FOR CUR_ZFLC IN (SELECT S.UUID,S.LCSLID_SB
                         FROM CKTS_LC_SBXX S
                        WHERE S.DJXH=CUR_DUP.DJXH AND S.SSQ=CUR_DUP.SSQ AND S.SBPC=CUR_DUP.SBPC AND S.ZFBZ IS NULL
                          AND S.QDSJ<>(SELECT MAX(R.QDSJ)
                                         FROM CKTS_LC_SBXX R
                                        WHERE R.DJXH=CUR_DUP.DJXH AND R.SSQ=CUR_DUP.SSQ AND R.SBPC=CUR_DUP.SBPC))
      LOOP
        BEGIN
          SELECT A.ZFBZ,A.ZFR_DM,A.ZFRQ
            INTO V_ZFBZ,V_ZFR_DM,V_ZFRQ
            FROM CKTS_LC_SHXX_ZF A
           WHERE A.DJXH=CUR_DUP.DJXH AND A.SSQ=CUR_DUP.SSQ AND A.SBPC=CUR_DUP.SBPC AND A.ZLCLCSLID=CUR_ZFLC.LCSLID_SB
             AND A.ZFRQ=(SELECT MAX(B.ZFRQ)
                           FROM CKTS_LC_SHXX_ZF B
                          WHERE B.DJXH=CUR_DUP.DJXH AND B.SSQ=CUR_DUP.SSQ AND B.SBPC=CUR_DUP.SBPC AND B.ZLCLCSLID=CUR_ZFLC.LCSLID_SB)
             AND ROWNUM=1;
        EXCEPTION
          WHEN OTHERS THEN
            CONTINUE;
        END;

        UPDATE CKTS_LC_SBXX A
           SET A.ZFBZ=V_ZFBZ,A.ZFR_DM=V_ZFR_DM,A.ZFRQ=V_ZFRQ
         WHERE A.UUID=CUR_ZFLC.UUID;
        UPDATE CKTS_LC_SHXX A
           SET A.ZFBZ=V_ZFBZ,A.ZFR_DM=V_ZFR_DM,A.ZFRQ=V_ZFRQ
         WHERE A.UUID=CUR_ZFLC.UUID;
        UPDATE CKTS_LC_SHXX A
           SET A.LCSLID_SB=' '
         WHERE A.DJXH=CUR_DUP.DJXH AND A.SSQ=CUR_DUP.SSQ AND A.SBPC=CUR_DUP.SBPC AND A.LCSLID<>CUR_ZFLC.LCSLID_SB;
        UPDATE CKTS_SB_MTS_CKMX A
           SET A.LCSLID_SB=' '
         WHERE A.LCSLID_SB=CUR_ZFLC.LCSLID_SB;
        UPDATE CKTS_SB_MTS_JHMX A
           SET A.LCSLID_SB=' '
         WHERE A.LCSLID_SB=CUR_ZFLC.LCSLID_SB;
        DELETE FROM GLXT_BB_SHXT_LCXX A
         WHERE A.UUID=CUR_ZFLC.UUID;
        COMMIT;
        LN_I:=LN_I +1;
      END LOOP;
    END LOOP;

    INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('对部分外贸企业免退税申报重复数据处理成功！' || LN_I);
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('对部分外贸企业免退税申报重复数据处理失败！', LC_SBYY);
      COMMIT;
  END;

  --GLXT_BB_SHXT_DJXX数据处理
  --设置备案信息的级次
  BEGIN
    UPDATE GLXT_BB_SHXT_DJXX T
       SET T.SQ_DATE=DATE'2009-11-19'
     WHERE T.CPCODE='10113305000049913646';
    COMMIT;

    --外贸综合服务企业
    --35号公告+17号公告
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '71'
     WHERE BAJC_YEAR='00' AND WZFQY='Y' AND WZFQY13='Y' AND JSMODE='2';
    COMMIT;
    --35号公告
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '72'
     WHERE BAJC_YEAR='00' AND WZFQY='Y' AND JSMODE='2';
    COMMIT;
    --17号公告
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '70'
     WHERE BAJC_YEAR='00' AND WZFQY13='Y' AND JSMODE='2';
    COMMIT;
    --服务贸易
    --国际运输业务
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '60'
     WHERE BAJC_YEAR='00' AND YSFW='Y' AND YSFWCODE LIKE '%01%' AND YSFS IS NOT NULL;
    COMMIT;
    --研发设计业务
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '50'
     WHERE BAJC_YEAR='00' AND YSFW='Y' AND YSFWCODE LIKE '%03%' AND (YFSJFW LIKE '%01%' OR YFSJFW LIKE '%03%');
    COMMIT;
    --其他服务贸易
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '40'
     WHERE BAJC_YEAR='00' AND YSFW='Y' AND YSFWCODE IS NOT NULL;
    COMMIT;
    --其他企业
    --周边业务
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '30'
     WHERE BAJC_YEAR='00'
       AND EXISTS (SELECT 1 FROM CKTS_LC_SBXX A WHERE A.TSSWJG_DM=T.SWJGDM AND A.DJXH=T.DJXH_JS AND A.SBYWB_DM IN ('A0302001','A0303001','A0304001') AND A.ZFBZ IS NULL);
    COMMIT;
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '30'
     WHERE BAJC_YEAR='00'
       AND EXISTS (SELECT 1 FROM CKTS_LC_YWHZXX A WHERE A.TSSWJG_DM=T.SWJGDM AND A.DJXH=T.DJXH_JS AND A.TBYY_DM IN ('470','480'));
    COMMIT;
    --生产企业
    --外商投资企业
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '23'
     WHERE BAJC_YEAR='00' AND JSMODE='1' AND SUBSTR(DJZCLX_JS,0,1) IN ('2','3');
    COMMIT;
    --委托出口企业
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '22'
     WHERE BAJC_YEAR='00' AND JSMODE='1' AND LENGTH(QYHGDM)=10 AND QYHGDM LIKE '9%';
    COMMIT;
    --内资生产企业
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '21'
     WHERE BAJC_YEAR='00' AND JSMODE='1';
    COMMIT;
    --外贸企业
    UPDATE GLXT_BB_SHXT_DJXX T
       SET BAJC_YEAR = '10'
     WHERE BAJC_YEAR='00' AND JSMODE='2';
    COMMIT;

    INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('GLXT_BB_SHXT_DJXX数据,处理成功！');
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('GLXT_BB_SHXT_DJXX数据,处理失败！', LC_SBYY);
      COMMIT;
  END;

  --部分生产企业登记注册类型调整过，导致既有内资又有外资，统计级次按最新调整
  BEGIN
    FOR CUR_DJXH IN (SELECT DJXH FROM TL_TSSH.CKTS_LC_SHXX
                      WHERE LCJSRQ>=DATE'2024-01-01' AND SBYWB_DM='A0305001' AND LCTJJC IN ('21','23')
                      GROUP BY DJXH HAVING COUNT(DISTINCT LCTJJC)>1)
    LOOP
      BEGIN
        SELECT T.DJZCLX_JS
          INTO LC_DJZCLX
          FROM TL_TSSH.GLXT_BB_SHXT_DJXX T
         WHERE T.DJXH_JS=CUR_DJXH.DJXH;
      EXCEPTION
        WHEN OTHERS THEN
          CONTINUE;
      END;
      IF SUBSTR(LC_DJZCLX,1,1)='1' THEN
        UPDATE TL_TSSH.CKTS_LC_SHXX t SET T.LCTJJC='21' WHERE T.DJXH=CUR_DJXH.DJXH AND T.LCTJJC='23';
        UPDATE TL_TSSH.CKTS_LC_YWHZXX t SET T.LCTJJC='21' WHERE T.DJXH=CUR_DJXH.DJXH AND T.LCTJJC='23';
        UPDATE TL_TSSH.CKTS_LC_SEHZXX t SET T.LCTJJC='21' WHERE T.DJXH=CUR_DJXH.DJXH AND T.LCTJJC='23';
        COMMIT;
      ELSIF SUBSTR(LC_DJZCLX,1,1) IN ('2','3') THEN
        UPDATE TL_TSSH.CKTS_LC_SHXX t SET T.LCTJJC='23' WHERE T.DJXH=CUR_DJXH.DJXH AND T.LCTJJC='21';
        UPDATE TL_TSSH.CKTS_LC_YWHZXX t SET T.LCTJJC='23' WHERE T.DJXH=CUR_DJXH.DJXH AND T.LCTJJC='21';
        UPDATE TL_TSSH.CKTS_LC_SEHZXX t SET T.LCTJJC='23' WHERE T.DJXH=CUR_DJXH.DJXH AND T.LCTJJC='21';
        COMMIT;
      END IF;
    END LOOP;

    INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('部分生产企业登记注册类型调整过，统计级次按最新调整成功！' || LN_I);
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('部分生产企业登记注册类型调整过，统计级次按最新调整失败！', LC_SBYY);
      COMMIT;
  END;

  --部分企业出口与收核登记序号不一致，需要通过CKTS_ZS_DJXHDZB转换
  BEGIN
    LN_I:=0;
    FOR CUR_DJXH IN (SELECT S.DJXH_CK,S.DJXH_ZS FROM CKTS_ZS_DJXHDZB S)
    LOOP
      UPDATE TL_ADMIN.FG_CKTSFN_HXZG T
         SET (T.SKSSSWJG_DM,T.CPCODE,T.QYHGDM,T.NSRSBH,T.NSRMC)=
             (SELECT R.SWJGDM,R.CPCODE,R.QYHGDM,NVL(R.SHXYNO,R.NSRDJNO),R.NSRMC FROM GLXT_BB_SHXT_DJXX R WHERE R.DJXH_JS=CUR_DJXH.DJXH_CK)
       WHERE T.DJXH=CUR_DJXH.DJXH_ZS;
      COMMIT;
      UPDATE CKTS_ZS_SRTHS T
         SET T.DJXH=CUR_DJXH.DJXH_CK
       WHERE T.DJXH=CUR_DJXH.DJXH_ZS;
      COMMIT;
      UPDATE CKTS_ZS_MDTKB T
         SET T.DJXH=CUR_DJXH.DJXH_CK
       WHERE T.DJXH=CUR_DJXH.DJXH_ZS;
      COMMIT;
      UPDATE CKTS_ZS_TKGZ T
         SET T.DJXH=CUR_DJXH.DJXH_CK
       WHERE T.DJXH=CUR_DJXH.DJXH_ZS;
      COMMIT;
      LN_I:=LN_I +1;
    END LOOP;

    INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('出口与收核登记序号不一致，通过CKTS_ZS_DJXHDZB转换成功！' || LN_I);
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('出口与收核登记序号不一致，通过CKTS_ZS_DJXHDZB转换失败！', LC_SBYY);
      COMMIT;
  END;

  --针对部分税局返纳不符合返纳数据etl条件，设置临时表保存转换
  BEGIN
    INSERT INTO TL_ADMIN.FG_CKTSFN_HXZG
           (SPUUID,SKSSSWJG_DM,DJXH,CPCODE,QYHGDM,NSRSBH,NSRMC,ZSUUID,DZSPHM,DZSPMXXH,ZSXM_DM,SKSX_DM,YSKM_DM,
           SKSSQQ,SKSSQZ,KJRQ,JSYJ,JKQX,RKRQ,SJJE,YZPZXH_CKTS,XGRQ,SJTB_DATE,DZJG,SKSSSWJG_JS,YZHYTMSKYY_DM,YWHZBUUID,BZ)
    SELECT SPUUID,SKSSSWJG_DM,DJXH,CPCODE,QYHGDM,NSRSBH,NSRMC,ZSUUID,DZSPHM,DZSPMXXH,ZSXM_DM,SKSX_DM,YSKM_DM,
           SKSSQQ,SKSSQZ,KJRQ,JSYJ,JKQX,RKRQ,SJJE,YZPZXH_CKTS,XGRQ,SJTB_DATE,DZJG,SKSSSWJG_JS,YZHYTMSKYY_DM,YWHZBUUID,BZ
      FROM TL_ADMIN.FG_CKTSFN_HXZG_YGP T
     WHERE NOT EXISTS (SELECT 1 FROM TL_ADMIN.FG_CKTSFN_HXZG S WHERE S.SPUUID=T.SPUUID);

    INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('青田有企业返纳不符合返纳数据etl条件，设置临时表保存转换成功！');
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      LC_SBYY:=SQLERRM;
      INSERT INTO CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('青田有企业返纳不符合返纳数据etl条件，设置临时表保存转换失败！', LC_SBYY);
      COMMIT;
  END;

  --CKTS_SB_MDT_CKMX
  BEGIN
    --删除作废流程信息
    LN_I:=0;
    FOR CUR_MDT IN (SELECT LCSLID_SB FROM CKTS_LC_SBXX WHERE ZFBZ='Y' AND SBYWB_DM='A0305001' AND NVL(ZFRQ,QDSJ)>=LD_DEALDATA)
    LOOP
      BEGIN
        DELETE FROM CKTS_SB_MDT_CKMX T WHERE T.LCSLID=CUR_MDT.LCSLID_SB;
        DELETE FROM CKTS_SB_MDT_GJYS T WHERE T.LCSLID=CUR_MDT.LCSLID_SB;
        DELETE FROM CKTS_SB_MDT_YFSJ T WHERE T.LCSLID=CUR_MDT.LCSLID_SB;
        COMMIT;
        LN_I:=LN_I +1;
      END;
    END LOOP;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_SB_MDT_CKMX删除作废流程信息！' || LN_I);
      COMMIT;
    END IF;
    --设置LCSLID_SB
    --按税局、企业、业务、所属期、批次查找申报流程
    UPDATE CKTS_SB_MDT_CKMX T
       SET T.LCSLID_SB=NVL((SELECT A.LCSLID_SB
                              FROM CKTS_LC_SBXX A
                             WHERE A.DJXH=T.DJXH AND A.SBYWB_DM='A0305001' AND A.SSQ=T.SSQ AND A.ZFBZ IS NULL
                               AND A.SJTB_BZ='2'
                               AND ROWNUM=1),' ')
     WHERE T.LCSLID_SB=' ' AND T.SSQ>='201901';
    COMMIT;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_SB_MDT_CKMX分流数据设置LCSLID_SB！');
      COMMIT;
    END IF;
    --设置LCSLID_FS
    --按税局、企业、业务、准予退税所属期、批次查找申报流程
    UPDATE CKTS_SB_MDT_CKMX T
       SET T.LCSLID_FS=NVL((SELECT A.LCSLID_SB
                              FROM CKTS_LC_SBXX A
                             WHERE A.DJXH=T.DJXH AND A.SBYWB_DM='A0305001' AND T.MDTSNY=A.SSQ AND A.ZFBZ IS NULL
                               AND A.SJTB_BZ='2'
                               AND ROWNUM=1),' ')
     WHERE T.LCSLID_FS=' ' AND T.SSQ>='201901' AND T.SJLY='2' AND T.MDTSNY IS NOT NULL;
    COMMIT;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_SB_MDT_CKMX后期准予退税设置LCSLID_FS！');
      COMMIT;
    END IF;
    --按税局、企业、业务、不予退税所属期、批次查找申报流程
    UPDATE CKTS_SB_MDT_CKMX T
       SET T.LCSLID_FS=NVL((SELECT A.LCSLID_SB
                              FROM CKTS_LC_SBXX A
                             WHERE A.DJXH=T.DJXH AND A.SBYWB_DM='A0305001' AND T.BYTSNY=A.SSQ AND A.ZFBZ IS NULL
                               AND A.SJTB_BZ='2'
                               AND ROWNUM=1),' ')
     WHERE T.LCSLID_FS=' ' AND T.SSQ>='201901' AND T.SJLY='2' AND T.BYTSNY IS NOT NULL;
    COMMIT;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_SB_MDT_CKMX后期不予退税设置LCSLID_FS！');
      COMMIT;
    END IF;
    --按税局、企业、业务、不予办理所属期、批次查找申报流程
    UPDATE CKTS_SB_MDT_CKMX T
       SET T.LCSLID_FS=NVL((SELECT A.LCSLID_SB
                              FROM CKTS_LC_SBXX A
                             WHERE A.DJXH=T.DJXH AND A.SBYWB_DM='A0305001' AND T.BYBLNY=A.SSQ AND A.ZFBZ IS NULL
                               AND A.SJTB_BZ='2'
                               AND ROWNUM=1),' ')
     WHERE T.LCSLID_FS=' ' AND T.SSQ>='201901' AND T.SJLY='2' AND T.BYBLNY IS NOT NULL;
    COMMIT;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_SB_MDT_CKMX后期不予办理设置LCSLID_FS！');
      COMMIT;
    END IF;
    --企业撤回申报数据
    UPDATE CKTS_SB_MDT_CKMX T
       SET T.LCSLID_FS=T.LCSLID
     WHERE T.LCSLID_FS=' ' AND T.SSQ>='201901' AND T.SJLY='2' AND T.CHBZ='Y';
    COMMIT;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_SB_MDT_CKMX撤回申报数据设置LCSLID_FS！');
      COMMIT;
    END IF;
/*
    UPDATE CKTS_SB_MDT_CKMX T
       SET T.ZHBZ_1='N'
     WHERE T.ZHBZ_1='Y' AND (T.MDTSNY IS NOT NULL OR T.BYTSNY IS NOT NULL);
    COMMIT;
    IF LN_LOG>1 THEN
      INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('             CKTS_SB_MDT_CKMX后期取消暂缓！');
      COMMIT;
    END IF;
*/
    --BYTSBZ：明确
    --ZBBLBZ：待定
    --ZYTSBZ：CASE WHEN TRIM(B.MDTSNY) IS NOT NULL THEN 'Y' ELSE 'N' END

    --免抵退FSRQ处理
    FOR LCXX_FH IN (SELECT T.LCSLID, MIN(S.FSRQ) AS FSRQ
                      FROM CKTS_SB_MDT_CKMX T
                     INNER JOIN CKTS_LC_SHXX R ON R.LCSLID=T.LCSLID
                     INNER JOIN CKTS_LC_YWHZXX S ON S.LCSLID_FS=R.LCSLID_FS
                     WHERE T.FSRQ IS NULL
                     GROUP BY T.LCSLID)
    LOOP
      BEGIN
        UPDATE CKTS_SB_MDT_CKMX T
           SET T.FSRQ=LCXX_FH.FSRQ
         WHERE LCSLID=LCXX_FH.LCSLID;
        COMMIT;
      END;
    END LOOP;
    IF LN_LOG>1 THEN
