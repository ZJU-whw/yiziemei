  FOR CUR_CQWSB IN (SELECT S.DJXH,S.CKBGDH,S.CYTSSBJL
                      FROM RCGL_CQWSB_DATA S
                     WHERE S.QYQR_ZT='3' AND S.JS_ZT='1' AND S.SWSH_ZT='1' AND S.YSB_TSE IS NULL)
  LOOP
    IF SUBSTR(CUR_CQWSB.CYTSSBJL,5,3)='133' THEN
      -- 代理证明，退运证明
      LN_ZZS:=0;
      LN_MDSE:=0;
    ELSE
      --退税申报
      BEGIN
        SELECT SUM(TSE), SUM(MDE)
          INTO LN_ZZS, LN_MDSE
          FROM (SELECT SUM(A.TMSE) AS TSE, 0 AS MDE
                  FROM JCFX_DATA_TSSBMX A
                 WHERE A.DJXH=CUR_CQWSB.DJXH
                   AND A.CKBGDH=CUR_CQWSB.CKBGDH
                   AND A.SBYWLX<>'1'
                 UNION ALL
                SELECT SUM(ROUND(A.TMSE * CASE WHEN B.MDTSEHJ<=0 THEN 0 ELSE B.YTSE_1/B.MDTSEHJ END, 2)) AS TSE,
                       SUM(A.TMSE) - SUM(ROUND(A.TMSE * CASE WHEN B.MDTSEHJ<=0 THEN 0 ELSE B.YTSE_1/B.MDTSEHJ END, 2)) AS MDE
                  FROM JCFX_DATA_TSSBMX A
                 INNER JOIN CKTS_SB_MDT_SBDSHZ B ON B.LCSLID=A.LCSLID
                 WHERE A.DJXH=CUR_CQWSB.DJXH
                   AND A.CKBGDH=CUR_CQWSB.CKBGDH
                   AND A.SBYWLX='1');
      EXCEPTION
        WHEN OTHERS THEN
          --找不到对应的记录，可能未复审、不予办理
          LN_ZZS:=NULL;
          LN_MDSE:=NULL;
      END;
    END IF;
    IF LN_ZZS IS NOT NULL THEN
      UPDATE RCGL_CQWSB_DATA T
         SET T.YSB_TSE=LN_ZZS,
             T.YSB_MDE=LN_MDSE
       WHERE T.DJXH=CUR_CQWSB.DJXH
         AND T.CKBGDH=CUR_CQWSB.CKBGDH;
      COMMIT;
    END IF;
  END LOOP;
  INSERT INTO CKTS_LOG_DEALDATA(CZJL) VALUES ('长期未申报出口业务退税清理成功！');
