CREATE OR REPLACE PROCEDURE PRO_TJBB_DT_B03104_HZ_NEW
/*************************************************
 * 浙江省主要出口商品统计表（省、市局汇总）
 * 20210205，金额栏保留整数，比率保留小数点后1位
 ************************************************/
(
  V_SWCODE  IN  VARCHAR2,
  V_SSNY IN VARCHAR2,
  V_ERROR   OUT NUMBER,
  V_MSG     OUT VARCHAR2
)
AS
  LC_THISMONTH     VARCHAR2(6);--当月
  LC_THISYEAR      VARCHAR2(6);--当年1月
  LC_LASTMONTH     VARCHAR2(6);--上年同期
  LC_LASTYEAR      VARCHAR2(6);--上年1月
  
  LN_CKE_THIS      NUMBER(16,4);--本年出口额合计
  LN_TSE_THIS      NUMBER(16,4);--本年退税额合计
  LN_CKE_LAST      NUMBER(16,4);--上年出口额合计
  LN_TSE_LAST      NUMBER(16,4);--上年退税额合计
  LC_SQL_UPDATEHZ  VARCHAR2(4000);
  LD_SYSDATE       DATE;
BEGIN
  V_ERROR :=0;
  V_MSG   := ' ';

  IF V_SSNY IS NOT NULL THEN
    LD_SYSDATE:=TO_DATE(V_SSNY||'01','YYYYMMDD');
  ELSE
    LD_SYSDATE:=SYSDATE;
  END IF;
  
  LC_THISMONTH   :=TO_CHAR(LD_SYSDATE,'YYYYMM');
  LC_THISYEAR    :=TO_CHAR(LD_SYSDATE,'YYYY')||'01';
  LC_LASTMONTH   :=TO_CHAR(ADD_MONTHS(LD_SYSDATE,-12),'YYYYMM');
  LC_LASTYEAR    :=TO_CHAR(ADD_MONTHS(LD_SYSDATE,-12),'YYYY')||'01';
  
  --0、清除原有制表数据，准备重新制表
  BEGIN
    DELETE FROM TJBB_DT_B03104 WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  --1、计算并插入本年明细
  BEGIN
    INSERT INTO TJBB_DT_B03104 (SSNY,BBLC,SWJGDM,SPDLDM,SPDL,SPMC,CKE_YEAR,TSE_YEAR,CKE_YEAR_LAST,TSE_YEAR_LAST)
      WITH FL_CMCODE AS (SELECT XMFL, 
                                SUM(CASE WHEN SSNY BETWEEN LC_THISYEAR AND LC_THISMONTH THEN USD_AMT_ALL ELSE 0 END)/10000 AS USD_AMT, 
                                SUM(CASE WHEN SSNY BETWEEN LC_THISYEAR AND LC_THISMONTH THEN TS_AMT_ALL  ELSE 0 END)/10000 AS TS_AMT, 
                                SUM(CASE WHEN SSNY BETWEEN LC_LASTYEAR AND LC_LASTMONTH THEN USD_AMT_ALL ELSE 0 END)/10000 AS USD_AMT_LAST, 
                                SUM(CASE WHEN SSNY BETWEEN LC_LASTYEAR AND LC_LASTMONTH THEN TS_AMT_ALL  ELSE 0 END)/10000 AS TS_AMT_LAST
                           FROM TL_TSSH.TJBB_FHXX_CMCODE
                          WHERE ((V_SWCODE='13300000000'  AND (SWCODE IN (SELECT SWJG_DM FROM TL_ADMIN.DM_SWJG WHERE TSJG_BZ='1'))) OR 
                                 (V_SWCODE<>'13300000000' AND (SWCODE IN (SELECT SWJG_DM FROM TABLE(TL_ADMIN.FUNC_GET_XJ_SWJG(V_SWCODE))))))
                            AND ((SSNY BETWEEN LC_THISYEAR AND LC_THISMONTH) OR (SSNY BETWEEN LC_LASTYEAR AND LC_LASTMONTH))
                          GROUP BY XMFL)
    SELECT LC_THISMONTH, 1 + ROW_NUMBER() OVER (ORDER BY NVL(SUM(C.USD_AMT),0) DESC,NVL(SUM(C.USD_AMT_LAST),0) DESC) AS BBLC, V_SWCODE, 
           A.SPML, A.MLDM, A.MLMC, 
           ROUND(SUM(C.USD_AMT),0), ROUND(SUM(C.TS_AMT),0), ROUND(SUM(C.USD_AMT_LAST),0), ROUND(SUM(C.TS_AMT_LAST),0)
      FROM DM_SPML A
     INNER JOIN DM_SPFL B ON A.SPML=B.SPML
      LEFT JOIN FL_CMCODE C ON C.XMFL = B.SPDL
      GROUP BY A.SPML, A.MLDM, A.MLMC;
    COMMIT;

    UPDATE TJBB_DT_B03104
       SET BBLC = '0'||BBLC
     WHERE LENGTH(BBLC)<2;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
  END;
  IF V_ERROR <> 0 THEN
    RETURN;
  END IF;

  --2、计算并插入合计数
  BEGIN
    SELECT SUM(CASE WHEN SSNY BETWEEN LC_THISYEAR AND LC_THISMONTH THEN USD_AMT_ALL ELSE 0 END)/10000 AS USD_AMT, 
           SUM(CASE WHEN SSNY BETWEEN LC_THISYEAR AND LC_THISMONTH THEN TS_AMT_ALL  ELSE 0 END)/10000 AS TS_AMT, 
           SUM(CASE WHEN SSNY BETWEEN LC_LASTYEAR AND LC_LASTMONTH THEN USD_AMT_ALL ELSE 0 END)/10000 AS USD_AMT_LAST, 
           SUM(CASE WHEN SSNY BETWEEN LC_LASTYEAR AND LC_LASTMONTH THEN TS_AMT_ALL  ELSE 0 END)/10000 AS TS_AMT_LAST
      INTO LN_CKE_THIS, LN_TSE_THIS, LN_CKE_LAST, LN_TSE_LAST
      FROM TL_TSSH.TJBB_FHXX_CMCODE
     WHERE ((V_SWCODE='13300000000'  AND (SWCODE IN (SELECT SWJG_DM FROM TL_ADMIN.DM_SWJG WHERE TSJG_BZ='1'))) OR 
            (V_SWCODE<>'13300000000' AND (SWCODE IN (SELECT SWJG_DM FROM TABLE(TL_ADMIN.FUNC_GET_XJ_SWJG(V_SWCODE))))));

    INSERT INTO TJBB_DT_B03104 (SSNY,BBLC,SWJGDM,SPDLDM,SPDL,SPMC,CKE_YEAR,TSE_YEAR, CKE_YEAR_LAST, TSE_YEAR_LAST)
    SELECT LC_THISMONTH, '01', V_SWCODE,
           'HJ', '', '合计',
           ROUND(LN_CKE_THIS,0), ROUND(LN_TSE_THIS,0), ROUND(LN_CKE_LAST,0), ROUND(LN_TSE_LAST,0)
      FROM DUAL;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      NULL;
  END;

  --3、同比计算
  BEGIN
    UPDATE TJBB_DT_B03104
       SET CKE_TB = CASE WHEN NVL(CKE_YEAR_LAST,0)=0 THEN NULL ELSE ROUND(100 * CKE_YEAR / CKE_YEAR_LAST -100,1) END,
           TSE_TB = CASE WHEN NVL(TSE_YEAR_LAST,0)=0 THEN NULL ELSE ROUND(100 * TSE_YEAR / TSE_YEAR_LAST -100,1) END
     WHERE SWJGDM=V_SWCODE
       AND SSNY=LC_THISMONTH;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  --4、占比计算
  BEGIN
    UPDATE TJBB_DT_B03104 T
       SET CKE_ZB = CASE WHEN NVL(LN_CKE_THIS,0)=0 THEN NULL ELSE ROUND(100 * CKE_YEAR / LN_CKE_THIS,1) END,
           TSE_ZB = CASE WHEN NVL(LN_TSE_THIS,0)=0 THEN NULL ELSE ROUND(100 * TSE_YEAR / LN_TSE_THIS,1) END
     WHERE SWJGDM=V_SWCODE
       AND SSNY=LC_THISMONTH;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  --6、汇总栏初始化
  BEGIN
    LC_SQL_UPDATEHZ := 'UPDATE TJBB_DT_B03104 SET ';

    FOR LSF_XX IN (SELECT FNAME FROM TJBB_HEADER_COLS WHERE BBDM='B03104' AND FTYPE='NUMBER' ORDER BY SHOWORDER)
    LOOP
      LC_SQL_UPDATEHZ := LC_SQL_UPDATEHZ || LSF_XX.FNAME || '_HZ=' || LSF_XX.FNAME || ', ';
    END LOOP;

    LC_SQL_UPDATEHZ := SUBSTR(LC_SQL_UPDATEHZ, 1, LENGTH(LC_SQL_UPDATEHZ)-2) ||
                       ' WHERE SWJGDM=''' || V_SWCODE || ''' AND SSNY=''' || LC_THISMONTH || '''';

    EXECUTE IMMEDIATE LC_SQL_UPDATEHZ;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
  END;

  RETURN;
END;
/
