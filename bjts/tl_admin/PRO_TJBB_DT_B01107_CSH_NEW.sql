CREATE OR REPLACE PROCEDURE PRO_TJBB_DT_B01107_CSH_NEW
/****************************************************
 * 全国出口退税专设机构设置及专职人员配备年度统计表
 * 202202，调整口径，按用户表中金三国地税用户筛选，原审核系统或其他用户不统计，其中原国税以133开始，原地税以233开始
 ***************************************************/
(
  V_SWCODE  IN  VARCHAR2,
  V_SSNY IN VARCHAR2,
  V_ERROR   OUT NUMBER,
  V_MSG     OUT VARCHAR2
)
AS
  LD_SYSDATE       DATE;
  LC_THISMONTH     VARCHAR2(6);
  LD_THISYEAR      DATE;
  LD_NEXTMONTH     DATE;

  TOTAL_TS_AMT     NUMBER(18,6);
  LC_SWJGMC        VARCHAR2(100);
  LN_USERS         NUMBER(10);
  LN_TSE_PER_USER  NUMBER(18,6);
  LC_SQL_UPDATEHZ  VARCHAR2(4000);
BEGIN
  V_ERROR :=0;
  V_MSG   := ' ';

  IF V_SSNY IS NOT NULL THEN
    LD_SYSDATE:=TO_DATE(V_SSNY||'01','YYYYMMDD');
  ELSE
    LD_SYSDATE:=TRUNC(SYSDATE,'MM');
  END IF;
  LC_THISMONTH :=TO_CHAR(LD_SYSDATE,'YYYYMM');
  LD_THISYEAR  :=TRUNC(LD_SYSDATE,'YY');
  LD_NEXTMONTH :=TRUNC(ADD_MONTHS(LD_SYSDATE,1),'MM');

  --0、清除原有制表数据，准备重新制表
  BEGIN
    DELETE FROM TJBB_DT_B01107 WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  --1、计算列
  BEGIN
    --税务机关名称
    SELECT SWJG_JC
      INTO LC_SWJGMC
      FROM DM_SWJG
     WHERE SWJG_DM=V_SWCODE;
    --本税务机关人数
    SELECT COUNT(1)
      INTO LN_USERS
      FROM SYS_USER T
     WHERE T.SWJG_DM=V_SWCODE
       AND T.USRSTATE='3' AND (T.CZRY_DM LIKE '133%' OR T.CZRY_DM LIKE '233%');
    --本税务机关办理退税额
    SELECT SUM(NVL(T.SEHZ_MDTSE,0))/10000
      INTO TOTAL_TS_AMT
      FROM TL_TSSH.CKTS_LC_SEHZXX T
     WHERE T.TSSWJG_DM=V_SWCODE
       AND T.SEHZRQ>LD_THISYEAR AND T.SEHZRQ<LD_NEXTMONTH;
    LN_TSE_PER_USER := CASE WHEN LN_USERS=0 THEN ROUND(TOTAL_TS_AMT,6) ELSE ROUND(TOTAL_TS_AMT/LN_USERS,6) END;

    INSERT INTO TJBB_DT_B01107(SSNY,BBLC,SWJGDM,SWJGMC,
                JG_HJ,JG_XJ_CITY,JG_XJ_JG,JG_XJ_LV,
                RY_HJ,RY_XJ,RY_XJ_LV,
                PER_SE)
         SELECT LC_THISMONTH, '01', V_SWCODE, LC_SWJGMC,
                1, 1, 1, 100,
                LN_USERS, LN_USERS, 100,
                LN_TSE_PER_USER
           FROM DUAL;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
  END;

  --2、更新汇总列
  BEGIN
    LC_SQL_UPDATEHZ := 'UPDATE TJBB_DT_B01107 SET ';

    FOR LSF_XX IN (SELECT FNAME FROM TJBB_HEADER_COLS WHERE BBDM='B01107' AND FTYPE='NUMBER' ORDER BY SHOWORDER)
    LOOP
      LC_SQL_UPDATEHZ := LC_SQL_UPDATEHZ || LSF_XX.FNAME || '_HZ=' || LSF_XX.FNAME || ', ';
    END LOOP;

    LC_SQL_UPDATEHZ := SUBSTR(LC_SQL_UPDATEHZ, 1, LENGTH(LC_SQL_UPDATEHZ)-2) ||
                       ' WHERE SWJGDM=''' || V_SWCODE || ''' AND SSNY=''' || LC_THISMONTH || '''';

    EXECUTE IMMEDIATE LC_SQL_UPDATEHZ;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
  END;

  RETURN;
END;
/
