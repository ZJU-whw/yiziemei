CREATE OR REPLACE PROCEDURE PRO_TJBB_DT_B02106_CSH_NEW
/*************************************************
 * 综服企业代办退税情况统计表
 * 202202，针对同时申报出口货物劳务以及服务贸易的企业，调整lctjjc
 ************************************************/
(
  V_SWCODE  IN  VARCHAR2,
  V_SSNY    IN  VARCHAR2,
  V_ERROR   OUT NUMBER,
  V_MSG     OUT VARCHAR2
)
AS
  LD_SYSDATE       DATE;
  LC_THISMONTH     VARCHAR2(6);
  LD_NEXTMONTH     DATE;
  LD_STARTMONTH    DATE;

  LN_WMBAHS        NUMBER(10);
  LN_WMBAHS13      NUMBER(10);
  LN_WMBAHS35      NUMBER(10);
  LN_SCBAHS        NUMBER(10);
  LN_WMSBHS        NUMBER(10);
  LN_SCSBHS        NUMBER(10);

  LN_SB_CKE    NUMBER(18,6);

  LN_SB_ZZS    NUMBER(18,6);
  LN_SH_ZZS    NUMBER(18,6);
  LN_ZH_ZZS    NUMBER(18,6);
  LN_BY_ZZS    NUMBER(18,6);
  LN_ZT_ZZS    NUMBER(18,6);
  LN_SP_ZZS    NUMBER(18,6);
  LN_YS_ZZS    NUMBER(18,6);

  LN_SB_XFS    NUMBER(18,6);
  LN_SH_XFS    NUMBER(18,6);
  LN_ZH_XFS    NUMBER(18,6);
  LN_BY_XFS    NUMBER(18,6);
  LN_ZT_XFS    NUMBER(18,6);
  LN_SP_XFS    NUMBER(18,6);
  LN_YS_XFS    NUMBER(18,6);

  LC_SQL_UPDATEHZ  VARCHAR2(4000);
BEGIN
  V_ERROR :=0;
  V_MSG   := ' ';
  
  IF V_SSNY IS NOT NULL THEN
    LD_SYSDATE:=TO_DATE(V_SSNY||'01','YYYYMMDD');
  ELSE
    LD_SYSDATE:=TRUNC(SYSDATE,'MM');
  END IF;
  LC_THISMONTH :=TO_CHAR(LD_SYSDATE,'YYYYMM');
  LD_NEXTMONTH :=TRUNC(ADD_MONTHS(LD_SYSDATE,1),'MM');
  LD_STARTMONTH:=DATE'2017-11-01';
  
  --0、清除原有制表数据，准备重新制表
  BEGIN
    DELETE FROM TJBB_DT_B02106 WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  --1、统计
  BEGIN
    --备案代办退税生产企业户数
    SELECT COUNT(DISTINCT A.CPCODE)
      INTO LN_SCBAHS
      FROM TL_TSSH.GLXT_BB_SHXT_DJXX A
     WHERE A.SWJGDM=V_SWCODE
       --AND A.ZX_FLAG <>'R'
       AND A.DBTSBA_FLAG='1';
    --申报代办退税生产企业户数
    SELECT COUNT(DISTINCT A.CPCODE)
      INTO LN_SCSBHS
      FROM TL_TSSH.GLXT_BB_SHXT_DJXX A
     INNER JOIN TL_TSSH.CKTS_SB_WZF_CKMX B ON B.WTDBTSSCQYNSRSBH=A.NSRDJNO OR B.WTDBTSSCQYNSRSBH=A.SHXYNO
     INNER JOIN TL_TSSH.CKTS_LC_SHXX C ON C.LCSLID=B.LCSLID AND C.QDSJ<LD_NEXTMONTH
     WHERE A.SWJGDM=V_SWCODE
       --AND A.ZX_FLAG <>'R'
       AND A.DBTSBA_FLAG='1';

    --外综服企业备案户数
    SELECT COUNT(1)
      INTO LN_WMBAHS
      FROM TL_TSSH.GLXT_BB_SHXT_DJXX A
     WHERE A.SWJGDM=V_SWCODE
       --AND A.ZX_FLAG <>'R'
       AND A.BAJC_YEAR IN ('71','72');

    --申报户数、申报出口额
    SELECT COUNT(DISTINCT T.DJXH), ROUND(NVL(SUM(T.MYLAJ),0)/10000,6)
      INTO LN_WMSBHS, LN_SB_CKE
      FROM (SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,B.MYLAJ
              FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
             INNER JOIN TL_TSSH.CKTS_LC_SHXX A ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
              LEFT JOIN TL_TSSH.CKTS_SB_MTS_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N'
             WHERE S.SWJGDM=V_SWCODE
               AND S.BAJC_YEAR IN ('71','72')
               AND A.LCTJJC IN ('71','72')
             UNION ALL
            SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,B.MYLAJ
              FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
             INNER JOIN TL_TSSH.CKTS_LC_SHXX A  ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
              LEFT JOIN TL_TSSH.CKTS_SB_WZF_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N'
             WHERE S.SWJGDM=V_SWCODE
               AND S.BAJC_YEAR  IN ('71','72')
               AND A.LCTJJC IN ('71','72')) T;

    --申报退税额、审核通过退税额、暂缓退税额、不予退税额、在途退税额
    SELECT ROUND(NVL(SUM(CASE WHEN T.SZ='V' THEN T.TSE ELSE 0 END),0)/10000,6), --增值税申报
           ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND TRIM(T.LCSLID_FS) IS NULL THEN T.TSE ELSE 0 END),0)/10000,6), --在途
           ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.MTSBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6), --准予
           ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6), --不予
           ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.ZBBLBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6), --暂缓
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' THEN T.TSE ELSE 0 END),0)/10000,6), --消费税申报
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND TRIM(T.LCSLID_FS) IS NULL THEN T.TSE ELSE 0 END),0)/10000,6), --在途
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.MTSBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6), --准予
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6), --不予
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.ZBBLBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6) --暂缓
      INTO LN_SB_ZZS, LN_ZT_ZZS, LN_SH_ZZS, LN_BY_ZZS, LN_ZH_ZZS, LN_SB_XFS, LN_ZT_XFS, LN_SH_XFS, LN_BY_XFS, LN_ZH_XFS
      FROM (SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,B.MTSBZ,B.BYTSBZ,B.ZBBLBZ,A.LCSLID_FS,B.SZ,B.TSE
              FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
             INNER JOIN TL_TSSH.CKTS_LC_SHXX A  ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
             INNER JOIN TL_TSSH.CKTS_SB_MTS_JHMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N' 
             WHERE S.SWJGDM=V_SWCODE
               AND S.BAJC_YEAR  IN ('71','72')
               AND A.LCTJJC IN ('71','72')
             UNION ALL
            SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,B.MTSBZ,B.BYTSBZ,B.ZBBLBZ,A.LCSLID_FS,'V' AS SZ,B.TSE
              FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
             INNER JOIN TL_TSSH.CKTS_LC_SHXX A  ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
             INNER JOIN TL_TSSH.CKTS_SB_WZF_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N' 
             WHERE S.SWJGDM=V_SWCODE
               AND S.BAJC_YEAR  IN ('71','72')
               AND A.LCTJJC IN ('71','72')) T;

    --审批退税额、移送国库退税额、国库办理退税额
    SELECT ROUND(NVL(SUM(T.SEHZ_ZZSTSE),0)/10000,6), --增值税审批
           ROUND(NVL(SUM(T.GKBL_ZZSTSE),0)/10000,6), --移送国库
           ROUND(NVL(SUM(T.SEHZ_XFSTSE),0)/10000,6), --消费税审批
           ROUND(NVL(SUM(T.GKBL_XFSTSE),0)/10000,6) --移送国库
      INTO LN_SP_ZZS, LN_YS_ZZS, LN_SP_XFS, LN_YS_XFS
      FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
     INNER JOIN TL_TSSH.CKTS_LC_SHXX A  ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
     INNER JOIN TL_TSSH.CKTS_LC_SEHZXX T ON TRIM(T.LCSLID_FS)=A.LCSLID_FS AND T.SEHZRQ<LD_NEXTMONTH
     WHERE S.SWJGDM=V_SWCODE
       AND S.BAJC_YEAR IN ('71','72')
       AND A.LCTJJC IN ('71','72');

    INSERT INTO TJBB_DT_B02106 (SSNY, BBLC, SWJGDM,
           BAHS_ZFQY, BAHS_DBTS,
           SBHS_ZFQY, SBHS_DBTS, TSCKE, TSE,
           SHTG_TSE, ZHBL_TSE, BYBL_TSE, SHZT_TSE,
           SPYT_TKE, YSGK_TKE, WSGK_TKE, GKBL_TKE, ZT_TKE)
    SELECT LC_THISMONTH, '01', V_SWCODE,
           LN_WMBAHS, LN_SCBAHS, LN_WMSBHS, LN_SCSBHS, LN_SB_CKE, LN_SB_ZZS + LN_SB_XFS, 
           LN_SH_ZZS + LN_SH_XFS, LN_ZH_ZZS + LN_ZH_XFS, LN_BY_ZZS + LN_BY_XFS, LN_ZT_ZZS + LN_ZT_XFS,
           LN_SP_ZZS + LN_SP_XFS, LN_YS_ZZS + LN_YS_XFS, 0, LN_YS_ZZS + LN_YS_XFS, 0
      FROM DUAL
     UNION ALL
    SELECT LC_THISMONTH, '02', V_SWCODE,
           LN_WMBAHS, LN_SCBAHS, 0, 0, LN_SB_CKE, LN_SB_ZZS,
           LN_SH_ZZS, LN_ZH_ZZS, LN_BY_ZZS, LN_ZT_ZZS,
           LN_SP_ZZS, LN_YS_ZZS, 0, LN_YS_ZZS, 0
      FROM DUAL
     UNION ALL
    SELECT LC_THISMONTH, '03', V_SWCODE,
           LN_WMBAHS, LN_SCBAHS, 0, 0, 0, LN_SB_XFS, 
           LN_SH_XFS, LN_ZH_XFS, LN_BY_XFS, LN_ZT_XFS,
           LN_SP_XFS, LN_YS_XFS, 0, LN_YS_XFS, 0
      FROM DUAL;

    --符合13号公告规定业务备案户数
    SELECT COUNT(1)
      INTO LN_WMBAHS13
      FROM TL_TSSH.GLXT_BB_SHXT_DJXX A
     WHERE A.SWJGDM=V_SWCODE
       --AND A.ZX_FLAG <>'R'
       AND A.BAJC_YEAR = 71;

    --申报户数、申报出口额
    SELECT COUNT(DISTINCT T.DJXH), ROUND(NVL(SUM(T.MYLAJ),0)/10000,6)
      INTO LN_WMSBHS, LN_SB_CKE
      FROM (SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,B.MYLAJ
              FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
             INNER JOIN TL_TSSH.CKTS_LC_SHXX A ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
              LEFT JOIN TL_TSSH.CKTS_SB_MTS_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N' 
             WHERE S.SWJGDM=V_SWCODE
               AND S.BAJC_YEAR IN ('71','72')
               AND A.LCTJJC='71') T;

    --申报退税额、审核通过退税额、暂缓退税额、不予退税额、在途退税额
    SELECT ROUND(NVL(SUM(T.TSE),0)/10000,6), --申报
           ROUND(NVL(SUM(CASE WHEN TRIM(T.LCSLID_FS) IS NULL THEN T.TSE ELSE 0 END),0)/10000,6), --在途
           ROUND(NVL(SUM(CASE WHEN TRIM(T.LCSLID_FS) IS NOT NULL AND T.MTSBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6), --准予
           ROUND(NVL(SUM(CASE WHEN TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6), --不予
           ROUND(NVL(SUM(CASE WHEN TRIM(T.LCSLID_FS) IS NOT NULL AND T.ZBBLBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6) --暂缓
      INTO LN_SB_ZZS, LN_ZT_ZZS, LN_SH_ZZS, LN_BY_ZZS, LN_ZH_ZZS
      FROM (SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,B.MTSBZ,B.BYTSBZ,B.ZBBLBZ,A.LCSLID_FS,B.TSE
              FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
             INNER JOIN TL_TSSH.CKTS_LC_SHXX A  ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
             INNER JOIN TL_TSSH.CKTS_SB_MTS_JHMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N' 
             WHERE S.SWJGDM=V_SWCODE
               AND S.BAJC_YEAR IN ('71','72')
               AND A.LCTJJC='71') T;

    --审批退税额、移送国库退税额、国库办理退税额
    SELECT ROUND(NVL(SUM(T.SEHZ_ZZSTSE + T.SEHZ_XFSTSE),0)/10000,6), --审批
           ROUND(NVL(SUM(T.GKBL_ZZSTSE + T.GKBL_XFSTSE),0)/10000,6) --移送国库
      INTO LN_SP_ZZS, LN_YS_ZZS
      FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
     INNER JOIN TL_TSSH.CKTS_LC_SHXX A  ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
     INNER JOIN TL_TSSH.CKTS_LC_SEHZXX T ON TRIM(T.LCSLID_FS)=A.LCSLID_FS AND T.SEHZRQ<LD_NEXTMONTH
     WHERE S.SWJGDM=V_SWCODE
       AND S.BAJC_YEAR IN ('71','72')
       AND A.LCTJJC='71';

    INSERT INTO TJBB_DT_B02106 (SSNY, BBLC, SWJGDM,
           BAHS_ZFQY, BAHS_DBTS,
           SBHS_ZFQY, SBHS_DBTS, TSCKE, TSE,
           SHTG_TSE, ZHBL_TSE, BYBL_TSE, SHZT_TSE,
           SPYT_TKE, YSGK_TKE, WSGK_TKE, GKBL_TKE, ZT_TKE)
    SELECT LC_THISMONTH, '04', V_SWCODE,
           LN_WMBAHS13, LN_SCBAHS, 0, 0, LN_SB_CKE, LN_SB_ZZS, 
           LN_SH_ZZS, LN_ZH_ZZS, LN_BY_ZZS, LN_ZT_ZZS,
           LN_SP_ZZS, LN_YS_ZZS, 0, LN_YS_ZZS, 0
      FROM DUAL;

    --符合35号公告规定业务备案户数
    SELECT COUNT(1)
      INTO LN_WMBAHS35
      FROM TL_TSSH.GLXT_BB_SHXT_DJXX A
     WHERE A.SWJGDM=V_SWCODE
       --AND A.ZX_FLAG <>'R'
       AND A.BAJC_YEAR IN ('71','72');

    --申报户数、申报出口额
    SELECT COUNT(DISTINCT T.DJXH), ROUND(NVL(SUM(T.MYLAJ),0)/10000,6)
      INTO LN_WMSBHS, LN_SB_CKE
      FROM (SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,B.MYLAJ
              FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
             INNER JOIN TL_TSSH.CKTS_LC_SHXX A  ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
              LEFT JOIN TL_TSSH.CKTS_SB_WZF_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N' 
             WHERE S.SWJGDM=V_SWCODE
               AND S.BAJC_YEAR IN ('71','72')
               AND A.LCTJJC='72') T;

    --申报退税额、审核通过退税额、暂缓退税额、不予退税额、在途退税额
    SELECT ROUND(NVL(SUM(T.TSE),0)/10000,6), --申报
           ROUND(NVL(SUM(CASE WHEN TRIM(T.LCSLID_FS) IS NULL THEN T.TSE ELSE 0 END),0)/10000,6), --在途
           ROUND(NVL(SUM(CASE WHEN TRIM(T.LCSLID_FS) IS NOT NULL AND T.MTSBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6), --准予
           ROUND(NVL(SUM(CASE WHEN TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6), --不予
           ROUND(NVL(SUM(CASE WHEN TRIM(T.LCSLID_FS) IS NOT NULL AND T.ZBBLBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6) --暂缓
      INTO LN_SB_ZZS, LN_ZT_ZZS, LN_SH_ZZS, LN_BY_ZZS, LN_ZH_ZZS
      FROM (SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,B.MTSBZ,B.BYTSBZ,B.ZBBLBZ,A.LCSLID_FS,B.TSE
              FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
             INNER JOIN TL_TSSH.CKTS_LC_SHXX A  ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
             INNER JOIN TL_TSSH.CKTS_SB_WZF_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N' 
             WHERE S.SWJGDM=V_SWCODE
               AND S.BAJC_YEAR  IN ('71','72')
               AND A.LCTJJC='72') T;

    --审批退税额、移送国库退税额、国库办理退税额
    SELECT ROUND(NVL(SUM(T.SEHZ_ZZSTSE + T.SEHZ_XFSTSE),0)/10000,6), --审批
           ROUND(NVL(SUM(T.GKBL_ZZSTSE + T.GKBL_XFSTSE),0)/10000,6) --移送国库
      INTO LN_SP_ZZS, LN_YS_ZZS
      FROM TL_TSSH.GLXT_BB_SHXT_DJXX S
     INNER JOIN TL_TSSH.CKTS_LC_SHXX A  ON A.DJXH=S.DJXH_JS AND A.QDSJ>=LD_STARTMONTH AND A.QDSJ<LD_NEXTMONTH
     INNER JOIN TL_TSSH.CKTS_LC_SEHZXX T ON TRIM(T.LCSLID_FS)=A.LCSLID_FS AND T.SEHZRQ<LD_NEXTMONTH
     WHERE S.SWJGDM=V_SWCODE
       AND S.BAJC_YEAR IN ('71','72')
       AND A.LCTJJC='72';

    INSERT INTO TJBB_DT_B02106 (SSNY, BBLC, SWJGDM,
           BAHS_ZFQY, BAHS_DBTS,
           SBHS_ZFQY, SBHS_DBTS, TSCKE, TSE,
           SHTG_TSE, ZHBL_TSE, BYBL_TSE, SHZT_TSE,
           SPYT_TKE, YSGK_TKE, WSGK_TKE, GKBL_TKE, ZT_TKE)
    SELECT LC_THISMONTH, '05', V_SWCODE,
           LN_WMBAHS35, LN_SCBAHS, LN_WMSBHS, LN_SCSBHS, LN_SB_CKE, LN_SB_ZZS, 
           LN_SH_ZZS, LN_ZH_ZZS, LN_BY_ZZS, LN_ZT_ZZS,
           LN_SP_ZZS, LN_YS_ZZS, 0, LN_YS_ZZS, 0
      FROM DUAL;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  --2、行内计算
  --3、汇总栏初始化
  BEGIN
    LC_SQL_UPDATEHZ := 'UPDATE TJBB_DT_B02106 SET ';

    FOR LSF_XX IN (SELECT FNAME FROM TJBB_HEADER_COLS WHERE BBDM='B02106' AND FTYPE='NUMBER' ORDER BY SHOWORDER)
    LOOP
      LC_SQL_UPDATEHZ := LC_SQL_UPDATEHZ || LSF_XX.FNAME || '_HZ=' || LSF_XX.FNAME || ', ';
    END LOOP;

    LC_SQL_UPDATEHZ := SUBSTR(LC_SQL_UPDATEHZ, 1, LENGTH(LC_SQL_UPDATEHZ)-2) ||
                       ' WHERE SWJGDM=''' || V_SWCODE || ''' AND SSNY=''' || LC_THISMONTH || '''';

    EXECUTE IMMEDIATE LC_SQL_UPDATEHZ;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  RETURN;
END;
