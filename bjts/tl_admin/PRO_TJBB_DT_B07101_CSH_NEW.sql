                   C.JLJGHXYTZMDTSE * (CASE WHEN A.SB_MDTSE=0 THEN 1 ELSE A.SB_MDSE  /A.SB_MDTSE END) AS MDE
              FROM TL_TSSH.CKTS_LC_SBXX A
