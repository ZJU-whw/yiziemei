             INNER JOIN TL_TSSH.CKTS_SB_MDT_SBDSHZ C ON C.LCSLID=B.LCSLID AND C.JLJGHXYTZMDTSE<>0
             WHERE A.TSSWJG_DM=V_SWCODE
