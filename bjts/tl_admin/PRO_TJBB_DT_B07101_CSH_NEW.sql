           ROUND(NVL(SUM(MDE),0)/10000,6)
      INTO LN_SBHS, LN_SB_CKE, LN_SB_ZZS, LN_SB_XFS
      FROM (SELECT A.DJXH,C.LCSLID,C.SBXH,C.MYLAJ,
                   C.MDTSE * (CASE WHEN A.SB_MDTSE=0 THEN 1 ELSE A.SB_ZZSTSE/A.SB_MDTSE END) AS TSE,
                   C.MDTSE * (CASE WHEN A.SB_MDTSE=0 THEN 1 ELSE A.SB_MDSE  /A.SB_MDTSE END) AS MDE
              FROM TL_TSSH.CKTS_LC_SBXX A
             INNER JOIN TL_TSSH.CKTS_LC_SHXX B ON B.LCSLID_SB=A.LCSLID_SB
             INNER JOIN TL_TSSH.CKTS_SB_MDT_CKMX C ON C.LCSLID=B.LCSLID AND C.BYBLBZ='N'
