CREATE OR REPLACE PROCEDURE PRO_TJBB_B07_HZ
/*
 * 	出口退税月报表（不计结转），地市局、省局初始化
 * 需要指定区县级税务机关和报表所属期
 */
(
  LC_SWJGDM  IN  VARCHAR2,
  LC_MONTH    IN  VARCHAR2
)
AS
  LN_ERROR         NUMBER;
  LC_MSG           VARCHAR2(2000);
BEGIN
  --按报表顺序依次制表
  BEGIN
    PRO_TJBB_DT_B07101_HZ_NEW(LC_SWJGDM,LC_MONTH,LN_ERROR,LC_MSG);
    INSERT INTO TL_TSSH.CKTS_LOG_DEALDATA(CZJL) VALUES ('PRO_TJBB_DT_B07101_HZ_NEW！'||LC_SWJGDM);
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      INSERT INTO TL_TSSH.CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('执行PRO_TJBB_DT_B07101_HZ_NEW失败，税务机关：'||LC_SWJGDM, LC_MSG);
      COMMIT;
  END;

END;
/
