CREATE OR REPLACE PROCEDURE PRO_TJBB_CSH_ALL
/***********************************************
 * 每月报表截止期次日凌晨执行(目前暂时为每月初)
 * 202504，调整9810报表，增加QYGTS报表，耗时较长，调整顺序为总局月报表、总局专项报表先做
 * 注：温州二分局撤并以后，2025年报表未重置，因此需要2026年保留一年以获取省局报表的上年数据
 ***********************************************/
(
	V_SSNY    IN  VARCHAR2
)
AS
  LC_MONTH         VARCHAR2(6);
  LC_MSG           VARCHAR2(2000);
  LC_SWJGDM        VARCHAR2(11);
  LN_I             NUMBER;
BEGIN
  
  IF V_SSNY IS NOT NULL THEN
    LC_MONTH :=V_SSNY;
  ELSE
    LC_MONTH:= TO_CHAR(ADD_MONTHS(SYSDATE,-1),'YYYYMM');
  END IF;

  BEGIN
    --刷新TJBB_TASK任务
    SELECT COUNT(1)
      INTO LN_I
      FROM TJBB_TASK
     WHERE NY=LC_MONTH;
    IF LN_I>0 THEN
      BEGIN
        DELETE FROM TJBB_TASK WHERE NY=LC_MONTH;
        COMMIT;
      EXCEPTION
        WHEN OTHERS THEN
          LC_MSG   := SQLERRM;
          INSERT INTO TL_TSSH.CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('清除TJBB_TASK原有任务失败！', LC_MSG);
          COMMIT;
      END;
    END IF;

    BEGIN
      INSERT INTO TJBB_TASK (BBDLDM, SWJGDM, NY, STATUS, SJSWJG, CJTIME, CJR, ZBTIME, ZBR, TYPE, SWJGMC, SWJGJC)
           SELECT S.BBDLDM, T.SWJG_DM, LC_MONTH, 
                  CASE WHEN SUBSTR(T.SWJG_DM,6,6)='000000' THEN '00' ELSE '10' END, 
                  T.SWJG_DM_SJ, SYSDATE, 'system', SYSDATE, 'system', '1', T.SWJG_MC, T.SWJG_JC
             FROM DM_SWJG T, TJBB_REPORT_ITEM S
            WHERE T.TSJG_BZ='1'
              AND S.TYPE='1'
            ORDER BY T.SWJG_DM, S.BBDLDM;
      COMMIT;
    EXCEPTION
      WHEN OTHERS THEN
        LC_MSG   := SQLERRM;
        INSERT INTO TL_TSSH.CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('新增TJBB_TASK任务失败！', LC_MSG);
        COMMIT;
    END;

    --刷新TJBB_TASK_SUB任务
    SELECT COUNT(1)
      INTO LN_I
      FROM TJBB_TASK_SUB
     WHERE NY=LC_MONTH;
    IF LN_I>0 THEN
      BEGIN
        DELETE FROM TJBB_TASK_SUB WHERE NY=LC_MONTH;
        COMMIT;
      EXCEPTION
        WHEN OTHERS THEN
          LC_MSG   := SQLERRM;
          INSERT INTO TL_TSSH.CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('清除TJBB_TASK_SUB原有任务失败！', LC_MSG);
          COMMIT;
      END;
    END IF;

    BEGIN
      INSERT INTO TJBB_TASK_SUB (BBID, BBDM, SWJGDM, NY, HZTIME, HZR, BBDLDM)
           SELECT SYS_GUID(), S.BBDM, T.SWJG_DM, LC_MONTH, SYSDATE, 'system', S.BBDLDM
             FROM DM_SWJG T, TJBB_REPORT_ITEM R, TJBB_REPORT_LIST S
            WHERE T.TSJG_BZ='1'
              AND R.BBDLDM=S.BBDLDM AND R.TYPE='1'
              AND S.QYBJ='Y'
            ORDER BY T.SWJG_DM, S.BBDM;
      COMMIT;
    EXCEPTION
      WHEN OTHERS THEN
        LC_MSG   := SQLERRM;
        INSERT INTO TL_TSSH.CKTS_LOG_DEALDATA(CZJL,SBYY) VALUES ('新增TJBB_TASK_SUB任务失败！', LC_MSG);
        COMMIT;
    END;
  END;

  --初始化
  INSERT INTO TL_TSSH.CKTS_LOG_DEALDATA(CZJL) VALUES ('初始化开始！'||LC_MONTH);
  COMMIT;

  --区县局
  FOR LSF_SWJG IN (SELECT SWJG_DM FROM DM_SWJG WHERE TSJG_BZ='1' AND YXWS=7 ORDER BY SWJG_DM) LOOP
    LC_SWJGDM := LSF_SWJG.SWJG_DM;

    -- 总局月报表
    PRO_TJBB_B01_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='10'
     WHERE T.BBDLDM='B01' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS='00';
    COMMIT;

    -- 总局专项报表
    PRO_TJBB_B02_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='10'
     WHERE T.BBDLDM='B02' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS='00';
    COMMIT;

    -- 总局专项报表（二）
    PRO_TJBB_B04_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='10'
     WHERE T.BBDLDM='B04' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS='00';
    COMMIT;

    -- 跨境电商统计表
    PRO_TJBB_B05_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='10'
     WHERE T.BBDLDM='B05' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS='00';
    COMMIT;

    -- 市场采购情况统计表
    PRO_TJBB_B06_CSH(LC_SWJGDM,LC_MONTH);
    UPDATE TJBB_TASK T
       SET T.STATUS='10'
     WHERE T.BBDLDM='B06' AND T.SWJGDM=LC_SWJGDM AND NY=LC_MONTH AND T.STATUS='00';
    COMMIT;
  END LOOP;

  INSERT INTO TL_TSSH.CKTS_LOG_DEALDATA(CZJL) VALUES ('初始化结束！'||LC_MONTH);
  COMMIT;
END;
/
