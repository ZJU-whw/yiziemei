CREATE OR REPLACE PROCEDURE PRO_TJBB_DT_B05101_HZ_NEW
/**************************************************************
 * 跨境电商统计表——跨境电商出口情况统计表（省、市局汇总）
 **************************************************************/
(
  V_SWCODE  IN  VARCHAR2,
  V_SSNY IN VARCHAR2,
  V_ERROR   OUT NUMBER,
  V_MSG     OUT VARCHAR2
)
AS
  LD_SYSDATE       DATE;
  LC_THISMONTH     VARCHAR2(6);
BEGIN
  V_ERROR :=0;
  V_MSG   := ' ';

  IF V_SSNY IS NOT NULL THEN
    LD_SYSDATE:=TO_DATE(V_SSNY||'01','YYYYMMDD');
  ELSE
    LD_SYSDATE:=SYSDATE;
  END IF;

  LC_THISMONTH :=TO_CHAR(LD_SYSDATE,'YYYYMM');
  
  --0、清除原有制表数据，准备重新制表
  BEGIN
    DELETE FROM TJBB_DT_B05101 WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  --1、统计
  BEGIN
    INSERT INTO TJBB_DT_B05101 (
           SSNY,BBLC,SWJGDM,QJNY,
           CKE_9610_HS, CKE_9610_HS_HZ, CKE_9610_JE, CKE_9610_JE_HZ, TMS_9610_HS, TMS_9610_HS_HZ, TMS_9610_JE, TMS_9610_JE_HZ,
           CKE_9710_HS, CKE_9710_HS_HZ, CKE_9710_JE, CKE_9710_JE_HZ, TMS_9710_HS, TMS_9710_HS_HZ, TMS_9710_JE, TMS_9710_JE_HZ,
           CKE_9810_HS, CKE_9810_HS_HZ, CKE_9810_JE, CKE_9810_JE_HZ, TMS_9810_HS, TMS_9810_HS_HZ, TMS_9810_JE, TMS_9810_JE_HZ)
    SELECT LC_THISMONTH,BBLC,V_SWCODE,QJNY,
           SUM(CKE_9610_HS), SUM(CKE_9610_HS_HZ), SUM(CKE_9610_JE), SUM(CKE_9610_JE_HZ), SUM(TMS_9610_HS), SUM(TMS_9610_HS_HZ), SUM(TMS_9610_JE), SUM(TMS_9610_JE_HZ),
           SUM(CKE_9710_HS), SUM(CKE_9710_HS_HZ), SUM(CKE_9710_JE), SUM(CKE_9710_JE_HZ), SUM(TMS_9710_HS), SUM(TMS_9710_HS_HZ), SUM(TMS_9710_JE), SUM(TMS_9710_JE_HZ),
           SUM(CKE_9810_HS), SUM(CKE_9810_HS_HZ), SUM(CKE_9810_JE), SUM(CKE_9810_JE_HZ), SUM(TMS_9810_HS), SUM(TMS_9810_HS_HZ), SUM(TMS_9810_JE), SUM(TMS_9810_JE_HZ)
      FROM TJBB_DT_B05101
     WHERE SWJGDM IN (SELECT SWJG_DM FROM TABLE(TL_ADMIN.FUNC_GET_XJ_SWJG(V_SWCODE))) 
       AND SSNY=LC_THISMONTH
     GROUP BY BBLC,QJNY;

    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  RETURN;
END;
/
