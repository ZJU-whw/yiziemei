           SUM(CASE WHEN TSTK.TKMONTH=LC_LASTYEAR||'12' THEN NVL(TSTK.TKSE,0) - NVL(TSFN.FNSE,0) ELSE 0 END),
           SUM(CASE WHEN TSTK.TKMONTH=LC_LASTYEAR||'01' THEN NVL(TSTK.TKSE,0) - NVL(TSFN.FNSE,0) ELSE 0 END),
           SUM(CASE WHEN TSTK.TKMONTH=LC_LASTYEAR||'02' THEN NVL(TSTK.TKSE,0) - NVL(TSFN.FNSE,0) ELSE 0 END),
           SUM(CASE WHEN TSTK.TKMONTH=LC_LASTYEAR||'03' THEN NVL(TSTK.TKSE,0) - NVL(TSFN.FNSE,0) ELSE 0 END),
