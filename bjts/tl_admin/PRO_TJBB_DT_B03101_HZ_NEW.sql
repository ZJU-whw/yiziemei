           SUM(CASE WHEN TSTK.TKMONTH=LC_THISYEAR||'08' THEN NVL(TSTK.TKSE,0) - NVL(TSFN.FNSE,0) ELSE 0 END),
           SUM(CASE WHEN TSTK.TKMONTH=LC_THISYEAR||'09' THEN NVL(TSTK.TKSE,0) - NVL(TSFN.FNSE,0) ELSE 0 END),
