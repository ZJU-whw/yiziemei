CREATE OR REPLACE PROCEDURE PRO_RECORD_TASK_DELE
/* 删除企业端作废单证备案 */
(
  V_NSRSBH  IN  VARCHAR2,
	V_SSNYPC  IN  VARCHAR2
)
AS
BEGIN
  DELETE FROM EDOC_FILE_INFO WHERE EDOC_ID IN
    (SELECT EDOC_ID FROM EDOC_CATALOG_SECOND WHERE ENTRY_ID IN
    (SELECT ENTRY_ID FROM EDOC_CATALOG_FIRST WHERE nsrsbh = V_NSRSBH AND SBNYPC = V_SSNYPC AND ENTRY_ID NOT IN
    (SELECT ENTRY_ID FROM EDOC_CATALOG_FIRST WHERE nsrsbh = V_NSRSBH AND SBNYPC <> V_SSNYPC)));

  DELETE FROM EDOC_CATALOG_SECOND WHERE ENTRY_ID IN
    (SELECT ENTRY_ID FROM EDOC_CATALOG_FIRST WHERE nsrsbh = V_NSRSBH AND SBNYPC = V_SSNYPC AND ENTRY_ID NOT IN
    (SELECT ENTRY_ID FROM EDOC_CATALOG_FIRST WHERE nsrsbh = V_NSRSBH AND SBNYPC <> V_SSNYPC));

  DELETE FROM EDOC_CATALOG_FIRST WHERE nsrsbh = V_NSRSBH AND SBNYPC = V_SSNYPC;
  DELETE FROM EDOC_RECORD_TASK WHERE nsrsbh = V_NSRSBH AND SBNYPC = V_SSNYPC;
  COMMIT;

  RETURN;
END;
