      SELECT COUNT(DISTINCT T.DJXH), 0, 0,
             ROUND(NVL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR THEN T.TSE ELSE 0 END),0)/10000,6), 
             ROUND(NVL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR THEN T.TSE ELSE 0 END),0)/10000,6),
             ROUND(NVL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NULL THEN T.TSE ELSE 0 END),0)/10000,6), --在途
             ROUND(NVL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NULL THEN T.TSE ELSE 0 END),0)/10000,6), --在途
             ROUND(NVL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='N' THEN T.TSE ELSE 0 END),0)/10000,6), --准予
             ROUND(NVL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='N' THEN T.TSE ELSE 0 END),0)/10000,6), --准予
             ROUND(NVL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6), --不予
             ROUND(NVL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR AND TRIM(T.LCSLID_FS) IS NOT NULL AND T.BYTSBZ='Y' THEN T.TSE ELSE 0 END),0)/10000,6) --不予
        INTO LN_SBHS, LN_SB_CKE_HIS, LN_SB_CKE_CUR, 
             LN_SB_ZZS_HIS, LN_SB_ZZS_CUR, LN_ZT_ZZS_HIS, LN_ZT_ZZS_CUR, LN_SH_ZZS_HIS, LN_SH_ZZS_CUR, LN_BY_ZZS_HIS, LN_BY_ZZS_CUR
        FROM (SELECT B.DJXH,B.LCSLID,B.SBXH,B.KPRQ AS CKRQ_1,B.BYTSBZ,C.LCSLID_FS,
                     B.TSE   * CASE WHEN TRIM(C.LCSLID_FS) IS NULL THEN 1  
                                    WHEN A.SNBL_MDTSE=0 THEN 1
                                    WHEN A.SNBL_MDTSE>0 AND B.BYTSBZ='Y' THEN 0
                                    ELSE 1 - A.SNBL_MDTSE / A.ZY_MDTSE 
                               END AS TSE
                FROM TL_TSSH.CKTS_LC_SHXX A
               INNER JOIN TL_TSSH.CKTS_SB_GJ_SBMX B ON B.LCSLID=A.LCSLID AND B.CHBZ='N'
                LEFT JOIN (SELECT DISTINCT LCSLID_FS FROM TL_TSSH.CKTS_LC_YWHZXX S) C ON C.LCSLID_FS=A.LCSLID_FS
               INNER JOIN TL_TSSH.GLXT_BB_SHXT_DJXX D ON D.DJXH_JS=A.DJXH
               WHERE A.TSSWJG_DM=V_SWCODE
                 AND A.QDSJ<LD_NEXTMONTH
                 AND A.LCJSRQ>=LD_THISYEAR
                 AND ((B.CKTMSYWLXDMJH IN ('SDQ',' NZYFJG')) OR (B.CKTMSYWLXDMJH='GCSB' AND D.QYLX<>'2'))
               UNION ALL
              SELECT B.DJXH,B.LCSLID,B.SBXH,B.KPRQ AS CKRQ_1,B.BYTSBZ,C.LCSLID_FS,
                     B.XFSTSE * CASE WHEN TRIM(C.LCSLID_FS) IS NULL THEN 1  
                                    WHEN A.SNBL_MDTSE=0 THEN 1
                                     WHEN A.SNBL_MDTSE>0 AND B.BYTSBZ='Y' THEN 0
                                     ELSE 1 - A.SNBL_MDTSE / A.ZY_MDTSE 
                                END AS TSE
                FROM TL_TSSH.CKTS_LC_SHXX A
               INNER JOIN TL_TSSH.CKTS_SB_FZC_SBMX B ON B.LCSLID=A.LCSLID AND B.CHBZ='N'
                LEFT JOIN (SELECT DISTINCT LCSLID_FS FROM TL_TSSH.CKTS_LC_YWHZXX S) C ON C.LCSLID_FS=A.LCSLID_FS
               INNER JOIN TL_TSSH.GLXT_BB_SHXT_DJXX D ON D.DJXH_JS=A.DJXH
               WHERE A.TSSWJG_DM=V_SWCODE
                 AND A.QDSJ<LD_NEXTMONTH
                 AND A.LCJSRQ>=LD_THISYEAR
               UNION ALL
              SELECT B.DJXH,B.LCSLID,B.SBXH,B.KPRQ AS CKRQ_1,B.BYTSBZ,C.LCSLID_FS,
                     B.TSE * CASE WHEN TRIM(C.LCSLID_FS) IS NULL THEN 1  
                                    WHEN A.SNBL_MDTSE=0 THEN 1
                                     WHEN A.SNBL_MDTSE>0 AND B.BYTSBZ='Y' THEN 0
                                     ELSE 1 - A.SNBL_MDTSE / A.ZY_MDTSE 
                                END AS TSE
                FROM TL_TSSH.CKTS_LC_SHXX A
               INNER JOIN TL_TSSH.CKTS_SB_YS_SBMX B ON B.LCSLID=A.LCSLID AND B.CHBZ='N'
                LEFT JOIN (SELECT DISTINCT LCSLID_FS FROM TL_TSSH.CKTS_LC_YWHZXX S) C ON C.LCSLID_FS=A.LCSLID_FS
               INNER JOIN TL_TSSH.GLXT_BB_SHXT_DJXX D ON D.DJXH_JS=A.DJXH
               WHERE A.TSSWJG_DM=V_SWCODE
                 AND A.QDSJ<LD_NEXTMONTH
                 AND A.LCJSRQ>=LD_THISYEAR
                 ) T;

      INSERT INTO TJBB_DT_B02105 (SSNY, BBLC, SWJGDM, SBHS, 
                SBLJ_TSCKE_HIS, SBLJ_TSCKE_YEAR, SBLJ_TMSE_HIS,  SBLJ_TMSE_YEAR, 
                SHLJ_TMSE_HIS,  SHLJ_TMSE_YEAR, SHBY_TMSE_HIS,  SHBY_TMSE_YEAR, SHZT_TMSE_HIS,  SHZT_TMSE_YEAR, 
                SPTK_TKE_HIS,   SPTK_TKE_YEAR, YSGK_TKE, GKBL_TKE_HIS,   GKBL_TKE_YEAR)
         SELECT LC_THISMONTH, '18', V_SWCODE, LN_SBHS, 
                LN_SB_CKE_HIS, LN_SB_CKE_CUR, LN_SB_ZZS_HIS, LN_SB_ZZS_CUR, 
                LN_SH_ZZS_HIS, LN_SH_ZZS_CUR, LN_BY_ZZS_HIS, LN_BY_ZZS_CUR, LN_ZT_ZZS_HIS, LN_ZT_ZZS_CUR, 
