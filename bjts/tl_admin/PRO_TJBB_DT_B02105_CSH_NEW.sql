                FROM TL_TSSH.CKTS_LC_SHXX A
               INNER JOIN TL_TSSH.CKTS_SB_MTS_CKMX B ON B.LCSLID=A.LCSLID AND B.CHBZ='N' AND B.CKTMSYWLXDMJH LIKE '%MSD%'
