CREATE OR REPLACE PROCEDURE PRO_TJBB_DT_B03113_CSH_NEW
/*************************************************
 * 浙江省对美主要出口企业情况表
 * 20210205，金额栏保留整数，比率保留小数点后1位
 ************************************************/
(
  V_SWCODE  IN  VARCHAR2,
  V_SSNY IN VARCHAR2,
  V_ERROR   OUT NUMBER,
  V_MSG     OUT VARCHAR2
)
AS
  LC_THISMONTH     VARCHAR2(6);--当月
  LC_THISYEAR      VARCHAR2(6);--当年首月
  LC_LASTMONTH     VARCHAR2(6);--上年同期
  LC_LASTYEAR      VARCHAR2(6);--上年首月
  LC_SQL_UPDATEHZ  VARCHAR2(4000);
  LD_SYSDATE       DATE;
BEGIN
  V_ERROR :=0;
  V_MSG   := ' ';

  IF V_SSNY IS NOT NULL THEN
    LD_SYSDATE:=TO_DATE(V_SSNY||'01','YYYYMMDD');
  ELSE
    LD_SYSDATE:=SYSDATE;
  END IF;

  LC_THISMONTH   :=TO_CHAR(LD_SYSDATE,'YYYYMM');
  LC_THISYEAR    :=TO_CHAR(LD_SYSDATE,'YYYY')||'01';
  LC_LASTMONTH   :=TO_CHAR(ADD_MONTHS(LD_SYSDATE,-12),'YYYYMM');
  LC_LASTYEAR    :=TO_CHAR(ADD_MONTHS(LD_SYSDATE,-12),'YYYY')||'01';

  --0、清除原有制表数据，准备重新制表
  BEGIN
    DELETE FROM TJBB_DT_B03113 WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  --1、本年前50名当年数据与上年同期数据
  BEGIN
    INSERT INTO TJBB_DT_B03113 (SSNY,BBLC,SWJGDM,CPCODE,QYHGDM,QYMC,JSMODE,JSMODEMC,
                                USA_CKE_YEAR,CKE_YEAR,USA_TMSE_YEAR,TMSE_YEAR,PM,
                                USA_CKE_YEAR_LAST,CKE_YEAR_LAST,USA_TMSE_YEAR_LAST,TMSE_YEAR_LAST)
      WITH THISYEAR AS (SELECT A.CPCODE, A.QYHGDM, A.NSRMC, A.JSMODE,
                               SUM(B.USD_AMT_USA)/10000 AS USD_AMT_USA, SUM(B.USD_AMT_ALL)/10000 AS USD_AMT_ALL,
                               SUM(B.TS_AMT_USA)/10000 AS TSE_AMT_USA, SUM(B.TS_AMT_ALL)/10000 AS TSE_AMT_ALL,
                               ROW_NUMBER() OVER (PARTITION BY A.JSMODE ORDER BY SUM(B.USD_AMT_USA) DESC) AS PM
                          FROM TL_TSSH.GLXT_BB_SHXT_DJXX A, TL_TSSH.TJBB_FHXX_CPCODE B
                         WHERE A.SWJGDM=V_SWCODE 
                           AND B.SWCODE=V_SWCODE 
                           AND SSNY BETWEEN LC_THISYEAR AND LC_THISMONTH
                           AND B.XMFL=A.CPCODE
                           AND A.JSMODE IN ('1','2')
                         GROUP BY A.CPCODE, A.QYHGDM, A.NSRMC, A.JSMODE),
           LASTYEAR AS (SELECT XMFL, SUM(USD_AMT_USA)/10000 AS USD_AMT_USA, SUM(USD_AMT_ALL)/10000 AS USD_AMT_ALL,
                               SUM(TS_AMT_USA)/10000 AS TSE_AMT_USA, SUM(TS_AMT_ALL)/10000 AS TSE_AMT_ALL
                          FROM TL_TSSH.TJBB_FHXX_CPCODE
                         WHERE SWCODE=V_SWCODE 
                           AND SSNY BETWEEN LC_LASTYEAR AND LC_LASTMONTH
                         GROUP BY XMFL)
    SELECT LC_THISMONTH, A.JSMODE||CASE WHEN A.PM<10 THEN '0' ELSE '' END||A.PM, V_SWCODE,
           A.CPCODE, A.QYHGDM, A.NSRMC, A.JSMODE, CASE WHEN A.JSMODE='1' THEN '生产' ELSE '外贸' END,
           ROUND(A.USD_AMT_USA,0), ROUND(A.USD_AMT_ALL,0), ROUND(A.TSE_AMT_USA,0), ROUND(A.TSE_AMT_ALL,0), A.PM,
           ROUND(B.USD_AMT_USA,0), ROUND(B.USD_AMT_ALL,0), ROUND(B.TSE_AMT_USA,0), ROUND(B.TSE_AMT_ALL,0)
      FROM THISYEAR A
      LEFT JOIN LASTYEAR B ON B.XMFL = A.CPCODE
     WHERE PM<=50
       AND A.USD_AMT_USA>0
    ;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  --2、同比计算
  BEGIN
    UPDATE TJBB_DT_B03113
       SET USA_CKE_TB  = CASE WHEN NVL(USA_CKE_YEAR_LAST,0)=0 THEN NULL ELSE ROUND(100 * USA_CKE_YEAR / USA_CKE_YEAR_LAST -100,1) END,
           CKE_TB  = CASE WHEN NVL(CKE_YEAR_LAST,0)=0 THEN NULL ELSE ROUND(100 * CKE_YEAR / CKE_YEAR_LAST -100,1) END,
           USA_TMSE_TB = CASE WHEN NVL(USA_TMSE_YEAR_LAST,0)=0 THEN NULL ELSE ROUND(100 * USA_TMSE_YEAR / USA_TMSE_YEAR_LAST -100,1) END,
           TMSE_TB = CASE WHEN NVL(TMSE_YEAR_LAST,0)=0 THEN NULL ELSE ROUND(100 * TMSE_YEAR / TMSE_YEAR_LAST -100,1) END
     WHERE SWJGDM=V_SWCODE
       AND SSNY=LC_THISMONTH;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
  END;
  IF V_ERROR <> 0 THEN
    RETURN;
  END IF;

  --3、占比计算
  BEGIN
    UPDATE TJBB_DT_B03113 T
       SET T.CKE_YEAR_ZB = CASE WHEN NVL(CKE_YEAR,0)=0 THEN NULL ELSE ROUND(100 * USA_CKE_YEAR / CKE_YEAR,1) END,
           T.CKE_YEAR_ZB_LAST = CASE WHEN NVL(CKE_YEAR_LAST,0)=0 THEN NULL ELSE ROUND(100 * USA_CKE_YEAR_LAST / CKE_YEAR_LAST,1) END,
           T.TMSE_YEAR_ZB = CASE WHEN NVL(TMSE_YEAR,0)=0 THEN NULL ELSE ROUND(100 * USA_TMSE_YEAR / TMSE_YEAR,1) END,
           T.TMSE_YEAR_ZB_LAST = CASE WHEN NVL(TMSE_YEAR_LAST,0)=0 THEN NULL ELSE ROUND(100 * USA_TMSE_YEAR_LAST / TMSE_YEAR_LAST,1) END
     WHERE SWJGDM=V_SWCODE
       AND SSNY=LC_THISMONTH;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
  END;
  IF V_ERROR <> 0 THEN
    RETURN;
  END IF;

  --4、汇总栏初始化
  BEGIN
    LC_SQL_UPDATEHZ := 'UPDATE TJBB_DT_B03113 SET ';

    FOR LSF_XX IN (SELECT FNAME FROM TJBB_HEADER_COLS WHERE BBDM='B03113' AND FTYPE='NUMBER' ORDER BY SHOWORDER)
    LOOP
      LC_SQL_UPDATEHZ := LC_SQL_UPDATEHZ || LSF_XX.FNAME || '_HZ=' || LSF_XX.FNAME || ', ';
    END LOOP;

    LC_SQL_UPDATEHZ := SUBSTR(LC_SQL_UPDATEHZ, 1, LENGTH(LC_SQL_UPDATEHZ)-2) ||
                       ' WHERE SWJGDM=''' || V_SWCODE || ''' AND SSNY=''' || LC_THISMONTH || '''';

    EXECUTE IMMEDIATE LC_SQL_UPDATEHZ;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
  END;

  RETURN;
END;
/
