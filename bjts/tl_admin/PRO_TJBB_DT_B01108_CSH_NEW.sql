CREATE OR REPLACE PROCEDURE PRO_TJBB_DT_B01108_CSH_NEW
/*
 * 202101，返纳数据从金三系统缴款书获取
 * 202102，外贸企业由申报到在途顺序计算改成由在途到申报反向计算，防止报表生成时在途数出负数
 * 202102，受理数统计时扣除返纳，防止报表生成时在途数虚增
 * 202102，符合13号公告规定业务的申报退税只取WMZHFW的数据
 * 202202，针对同时申报出口货物劳务以及服务贸易的企业，调整lctjjc
 * 20260116，根据舟山反馈问题分析，在统计生产企业申报户数、申报出口额、申报免抵退税额口径，提取进料加工数据时加调整数不为0的条件
 */
(
  V_SWCODE  IN  VARCHAR2,
	V_SSNY    IN  VARCHAR2,
  V_ERROR   OUT NUMBER,
  V_MSG     OUT VARCHAR2
)
AS
  LD_SYSDATE       DATE;
  LC_THISMONTH     VARCHAR2(6);
  LD_THISYEAR      DATE;
  LD_NEXTMONTH     DATE;
  LC_LASTMONTH     VARCHAR2(6);

  LN_BAHS          NUMBER(10);
  LN_SBHS          NUMBER(10);
  LN_SB_CKE_HIS    NUMBER(18,6);
  LN_SB_CKE_CUR    NUMBER(18,6);

  LN_SB_ZZS_HIS    NUMBER(18,6);
  LN_SB_ZZS_CUR    NUMBER(18,6);
  LN_SH_ZZS_HIS    NUMBER(18,6);
  LN_SH_ZZS_CUR    NUMBER(18,6);
  LN_SP_ZZS_XJ     NUMBER(18,6);
  LN_SP_ZZS_HIS    NUMBER(18,6);
  LN_SP_ZZS_CUR    NUMBER(18,6);
  LN_YS_ZZS        NUMBER(18,6);
  LN_BL_ZZS_HIS    NUMBER(18,6);
  LN_BL_ZZS_CUR    NUMBER(18,6);
  LN_BL_ZZS_HIS_JZ NUMBER(18,6);
  LN_BL_ZZS_HIS_SP NUMBER(18,6);
  TSFN_ZZS_HIS     NUMBER(18,6);
  TSFN_ZZS_CUR     NUMBER(18,6);

  LN_SB_XFS_HIS    NUMBER(18,6);
  LN_SB_XFS_CUR    NUMBER(18,6);
  LN_SH_XFS_HIS    NUMBER(18,6);
  LN_SH_XFS_CUR    NUMBER(18,6);
  LN_SP_XFS_XJ     NUMBER(18,6);
  LN_SP_XFS_HIS    NUMBER(18,6);
  LN_SP_XFS_CUR    NUMBER(18,6);
  LN_YS_XFS        NUMBER(18,6);
  LN_BL_XFS_HIS    NUMBER(18,6);
  LN_BL_XFS_CUR    NUMBER(18,6);
  LN_BL_XFS_HIS_JZ NUMBER(18,6);
  LN_BL_XFS_HIS_SP NUMBER(18,6);
  TSFN_XFS_HIS     NUMBER(18,6);
  TSFN_XFS_CUR     NUMBER(18,6);

  LC_SQL           VARCHAR2(4000);
  LC_SQL_UPDATEHZ  VARCHAR2(4000);
BEGIN
  V_ERROR :=0;
  V_MSG   := ' ';
  
  IF V_SSNY IS NOT NULL THEN
    LD_SYSDATE:=TO_DATE(V_SSNY||'01','YYYYMMDD');
  ELSE
    LD_SYSDATE:=TRUNC(SYSDATE,'MM');
  END IF;
  LC_THISMONTH :=TO_CHAR(LD_SYSDATE,'YYYYMM');
  LD_THISYEAR  :=TRUNC(LD_SYSDATE,'YY');
  LD_NEXTMONTH :=TRUNC(ADD_MONTHS(LD_SYSDATE,1),'MM');
  LC_LASTMONTH :=TO_CHAR(ADD_MONTHS(LD_SYSDATE,-12),'YYYYMM');
  
  --0、清除原有制表数据，准备重新制表
  BEGIN
    DELETE FROM TJBB_DT_B01108 WHERE SWJGDM=V_SWCODE AND SSNY=LC_THISMONTH;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
      RETURN;
  END;

  --1、外贸企业
  BEGIN
    --返纳
    SELECT NVL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10101' AND T.SKSSQZ< LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6),0),
           NVL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10101' AND T.SKSSQZ>=LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6),0),
           NVL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10102' AND T.SKSSQZ< LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6),0),
           NVL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10102' AND T.SKSSQZ>=LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6),0)
      INTO TSFN_ZZS_HIS, TSFN_ZZS_CUR, TSFN_XFS_HIS, TSFN_XFS_CUR
      FROM FG_CKTSFN_HXZG T, TL_TSSH.GLXT_BB_SHXT_DJXX S
     WHERE S.BAJC_YEAR IN ('00','10')
       AND T.CPCODE=S.CPCODE
       AND T.SKSSSWJG_DM=V_SWCODE
       AND T.RKRQ>=LD_SYSDATE AND T.RKRQ<LD_NEXTMONTH
       AND T.YWHZBUUID IS NULL;

    --备案户数
    SELECT COUNT(1)
      INTO LN_BAHS
      FROM TL_TSSH.GLXT_BB_SHXT_DJXX T
     WHERE T.SWJGDM=V_SWCODE
       AND T.ZX_FLAG='N'
       AND T.BAJC_YEAR='10';

    --申报户数、申报出口额
    SELECT COUNT(DISTINCT T.DJXH), 
           ROUND(NVL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR THEN T.MYLAJ ELSE 0 END),0)/10000,6), 
           ROUND(NVL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR THEN T.MYLAJ ELSE 0 END),0)/10000,6)
      INTO LN_SBHS, LN_SB_CKE_HIS, LN_SB_CKE_CUR
      FROM (SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,
                   B.MYLAJ * CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1 
                                  WHEN A.ZY_MDTSE=0 THEN 1
                                  WHEN A.SYBL_MDTSE=0 THEN 1
                                  WHEN A.SYBL_MDTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                  ELSE LEAST(GREATEST(1 - A.SYBL_MDTSE / A.ZY_MDTSE,0),1)
                             END AS MYLAJ
              FROM TL_TSSH.CKTS_LC_SHXX A
              LEFT JOIN TL_TSSH.CKTS_SB_MTS_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N'
             WHERE A.TSSWJG_DM=V_SWCODE
               AND A.LCTJJC IN ('10','40','50')
               AND A.QDSJ<LD_NEXTMONTH
               AND A.LCJSRQ>=LD_SYSDATE) T;

    --申报退税额、审核通过退税额
    SELECT ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1< LD_THISYEAR THEN T.TSE ELSE 0 END),0)/10000,6), --增值税申报
           ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1>=LD_THISYEAR THEN T.TSE ELSE 0 END),0)/10000,6), --申报
           ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END),0)/10000,6), --准予
           ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END),0)/10000,6), --准予
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1< LD_THISYEAR THEN T.TSE ELSE 0 END),0)/10000,6), --消费税申报
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1>=LD_THISYEAR THEN T.TSE ELSE 0 END),0)/10000,6), --申报
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END),0)/10000,6), --准予
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END),0)/10000,6) --准予
      INTO LN_SB_ZZS_HIS, LN_SB_ZZS_CUR, LN_SH_ZZS_HIS, LN_SH_ZZS_CUR, LN_SB_XFS_HIS, LN_SB_XFS_CUR, LN_SH_XFS_HIS, LN_SH_XFS_CUR
      FROM (SELECT A.DJXH,B.SBXH,B.CKRQ_1,B.SZ,
                   CASE WHEN TRIM(A.LCSLID_FS) IS NOT NULL AND B.ZBBLBZ='Y' THEN 10 
                        WHEN TRIM(A.LCSLID_FS) IS NOT NULL AND B.BYTSBZ='Y' THEN 20 
                        WHEN TRIM(A.LCSLID_FS) IS NOT NULL THEN 30 
                        WHEN TRIM(A.LCSLID_FS) IS NULL AND A.LCSLID_SB<>A.LCSLID THEN 10 
                        ELSE 40 END AS SHZT, 
                   B.TSE * CASE WHEN B.SZ='V' THEN (CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1 
                                                         WHEN A.ZY_ZZSTSE=0 THEN 1
                                                         WHEN A.SYBL_ZZSTSE=0 THEN 1
                                                         WHEN A.SYBL_ZZSTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                                         ELSE LEAST(GREATEST(1 - A.SYBL_ZZSTSE / A.ZY_ZZSTSE,0),1)
                                                    END)
                           ELSE (CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1 
                                      WHEN A.ZY_XFSTSE=0 THEN 1
                                      WHEN A.SYBL_XFSTSE=0 THEN 1
                                      WHEN A.SYBL_XFSTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                      ELSE LEAST(GREATEST(1 - A.SYBL_XFSTSE / A.ZY_XFSTSE,0),1)
                                 END)
                           END AS TSE
              FROM TL_TSSH.CKTS_LC_SHXX A
             INNER JOIN TL_TSSH.CKTS_SB_MTS_JHMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N'
             WHERE A.TSSWJG_DM=V_SWCODE
               AND A.LCTJJC IN ('10','40','50')
               AND A.QDSJ<LD_NEXTMONTH
               AND A.LCJSRQ>=LD_SYSDATE) T;

    --审批退税额、移送国库退税额、国库办理退税额
    SELECT ROUND(NVL(SUM(T.SEHZ_ZZSTSE),0)/10000,6), --增值税审批
           ROUND(NVL(SUM(T.SEHZ_ZZSTSE * T.SNCKZB),0)/10000,6), --审批上年出口
           ROUND(NVL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_ZZSTSE ELSE 0 END),0)/10000,6), --移送国库
           ROUND(NVL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_ZZSTSE ELSE 0 END * T.SNCKZB),0)/10000,6), --办理上年出口
           ROUND(NVL(SUM(CASE WHEN S.FSRQ<LD_THISYEAR AND T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_ZZSTSE ELSE 0 END * T.SNCKZB),0)/10000,6), --办理上年结转
           ROUND(NVL(SUM(CASE WHEN S.YWHZRQ<LD_THISYEAR AND T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_ZZSTSE ELSE 0 END * T.SNCKZB),0)/10000,6), --办理上年审批结转
           ROUND(NVL(SUM(T.SEHZ_XFSTSE),0)/10000,6), --消费税审批
           ROUND(NVL(SUM(T.SEHZ_XFSTSE * T.SNCKZB),0)/10000,6), --审批上年出口
           ROUND(NVL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_XFSTSE ELSE 0 END),0)/10000,6), --移送国库
           ROUND(NVL(SUM(CASE WHEN T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_XFSTSE ELSE 0 END * T.SNCKZB),0)/10000,6), --办理上年出口
           ROUND(NVL(SUM(CASE WHEN S.FSRQ<LD_THISYEAR AND T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_XFSTSE ELSE 0 END * T.SNCKZB),0)/10000,6), --办理上年结转
           ROUND(NVL(SUM(CASE WHEN S.YWHZRQ<LD_THISYEAR AND T.XHRQ_TK<LD_NEXTMONTH THEN T.GKBL_XFSTSE ELSE 0 END * T.SNCKZB),0)/10000,6) --办理上年审批结转
      INTO LN_SP_ZZS_XJ, LN_SP_ZZS_HIS, LN_YS_ZZS, LN_BL_ZZS_HIS, LN_BL_ZZS_HIS_JZ, LN_BL_ZZS_HIS_SP,
           LN_SP_XFS_XJ, LN_SP_XFS_HIS, LN_YS_XFS, LN_BL_XFS_HIS, LN_BL_XFS_HIS_JZ, LN_BL_XFS_HIS_SP
      FROM TL_TSSH.CKTS_LC_SEHZXX T
     INNER JOIN TL_TSSH.CKTS_LC_YWHZXX S ON S.YWHZBUUID=T.YWHZBUUID AND S.CKTMSHWYSFWLX_DM=T.CKTMSHWYSFWLX_DM
     WHERE T.CKTMSJHSSSWJGDM=V_SWCODE
       AND T.LCTJJC='10'
       AND T.XHRQ_TK>=LD_SYSDATE
       AND T.SEHZRQ<LD_NEXTMONTH;
    LN_SP_ZZS_CUR := LN_SP_ZZS_XJ - LN_SP_ZZS_HIS;
    LN_SP_XFS_CUR := LN_SP_XFS_XJ - LN_SP_XFS_HIS;
    LN_BL_ZZS_CUR := LN_YS_ZZS - LN_BL_ZZS_HIS;
    LN_BL_XFS_CUR := LN_YS_XFS - LN_BL_XFS_HIS;

    INSERT INTO TJBB_DT_B01108 (SSNY, BBLC, SWJGDM, RDHS, SBHS,
           SB_CKE_XJ,  SB_CKE_HIS,  SB_CKE_CUR,
           SB_TMSE_XJ, SB_TMSE_HIS, SB_TMSE_CUR,
           SH_TMSE_XJ, SH_TMSE_HIS, SH_TMSE_CUR,
           SP_TMSE_XJ, SP_TMSE_HIS, SP_TMSE_CUR,
           TK_XJ,      TK_SB_HIS,   TK_JZ_HIS,   TK_WBL_HIS,   TK_SB_CUR)
    SELECT LC_THISMONTH, '05', V_SWCODE, LN_BAHS, LN_SBHS, LN_SB_CKE_HIS + LN_SB_CKE_CUR, LN_SB_CKE_HIS, LN_SB_CKE_CUR,
           LN_SB_ZZS_HIS + LN_SB_ZZS_CUR, LN_SB_ZZS_HIS, LN_SB_ZZS_CUR,
           LN_SH_ZZS_HIS + LN_SH_ZZS_CUR, LN_SH_ZZS_HIS, LN_SH_ZZS_CUR,
           LN_SP_ZZS_XJ - TSFN_ZZS_HIS - TSFN_ZZS_CUR,   LN_SP_ZZS_HIS - TSFN_ZZS_HIS, LN_SP_ZZS_CUR - TSFN_ZZS_CUR,
           LN_YS_ZZS    - TSFN_ZZS_HIS - TSFN_ZZS_CUR,   LN_BL_ZZS_HIS - TSFN_ZZS_HIS, 
           GREATEST(LN_BL_ZZS_HIS_JZ - TSFN_ZZS_HIS, 0), GREATEST(LN_BL_ZZS_HIS_SP - TSFN_ZZS_HIS, 0),
           LN_BL_ZZS_CUR - TSFN_ZZS_CUR
      FROM DUAL;

    INSERT INTO TJBB_DT_B01108 (SSNY, BBLC, SWJGDM, RDHS, SBHS,
           SB_CKE_XJ,  SB_CKE_HIS,  SB_CKE_CUR,
           SB_TMSE_XJ, SB_TMSE_HIS, SB_TMSE_CUR,
           SH_TMSE_XJ, SH_TMSE_HIS, SH_TMSE_CUR,
           SP_TMSE_XJ, SP_TMSE_HIS, SP_TMSE_CUR,
           TK_XJ,      TK_SB_HIS,   TK_JZ_HIS,   TK_WBL_HIS,   TK_SB_CUR)
    SELECT LC_THISMONTH, '06', V_SWCODE, 0, 0, 0, 0, 0,
           LN_SB_XFS_HIS + LN_SB_XFS_CUR, LN_SB_XFS_HIS, LN_SB_XFS_CUR,
           LN_SH_XFS_HIS + LN_SH_XFS_CUR, LN_SH_XFS_HIS, LN_SH_XFS_CUR,
           LN_SP_XFS_XJ - TSFN_XFS_HIS - TSFN_XFS_CUR,   LN_SP_XFS_HIS - TSFN_XFS_HIS, LN_SP_XFS_CUR - TSFN_XFS_CUR,
           LN_YS_XFS    - TSFN_XFS_HIS - TSFN_XFS_CUR,   LN_BL_XFS_HIS - TSFN_XFS_HIS, 
           GREATEST(LN_BL_XFS_HIS_JZ - TSFN_XFS_HIS, 0), GREATEST(LN_BL_XFS_HIS_SP - TSFN_XFS_HIS, 0),
           LN_BL_XFS_CUR - TSFN_XFS_CUR
      FROM DUAL;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      V_ERROR := SQLCODE;
      V_MSG   := SQLERRM;
  END;

  --2、外综服企业
  BEGIN
    --返纳
    SELECT NVL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10101' AND T.SKSSQZ< LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6),0),
           NVL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10101' AND T.SKSSQZ>=LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6),0),
           NVL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10102' AND T.SKSSQZ< LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6),0),
           NVL(ROUND(SUM(CASE WHEN T.ZSXM_DM='10102' AND T.SKSSQZ>=LD_THISYEAR THEN T.SJJE ELSE 0 END)/10000,6),0)
      INTO TSFN_ZZS_HIS, TSFN_ZZS_CUR, TSFN_XFS_HIS, TSFN_XFS_CUR
      FROM FG_CKTSFN_HXZG T, TL_TSSH.GLXT_BB_SHXT_DJXX S
     WHERE S.BAJC_YEAR IN ('70','71','72')
       AND T.CPCODE=S.CPCODE
       AND T.SKSSSWJG_DM=V_SWCODE
       AND T.RKRQ>=LD_SYSDATE AND T.RKRQ<LD_NEXTMONTH
       AND T.YWHZBUUID IS NULL;

    --备案户数
    SELECT COUNT(1)
      INTO LN_BAHS
      FROM TL_TSSH.GLXT_BB_SHXT_DJXX T
     WHERE T.SWJGDM=V_SWCODE
       AND T.ZX_FLAG='N'
       AND T.BAJC_YEAR IN ('70','71','72');

    --申报户数、申报出口额
    SELECT COUNT(DISTINCT T.DJXH), 
           ROUND(NVL(SUM(CASE WHEN T.CKRQ_1< LD_THISYEAR THEN T.MYLAJ ELSE 0 END),0)/10000,6), 
           ROUND(NVL(SUM(CASE WHEN T.CKRQ_1>=LD_THISYEAR THEN T.MYLAJ ELSE 0 END),0)/10000,6)
      INTO LN_SBHS, LN_SB_CKE_HIS, LN_SB_CKE_CUR
      FROM (SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,
                   B.MYLAJ * CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1 
                                  WHEN A.ZY_MDTSE=0 THEN 1
                                  WHEN A.SYBL_MDTSE=0 THEN 1
                                  WHEN A.SYBL_MDTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                  ELSE LEAST(GREATEST(1 - A.SYBL_MDTSE / A.ZY_MDTSE,0),1)
                             END AS MYLAJ
              FROM TL_TSSH.CKTS_LC_SHXX A
              LEFT JOIN TL_TSSH.CKTS_SB_MTS_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N'
             WHERE A.TSSWJG_DM=V_SWCODE
               AND A.LCTJJC IN ('70','71')
               AND A.QDSJ<LD_NEXTMONTH
               AND A.LCJSRQ>=LD_SYSDATE
             UNION ALL
            SELECT A.DJXH,B.LCSLID,B.SBXH,B.CKRQ_1,
                   B.MYLAJ * CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1 
                                  WHEN A.ZY_MDTSE=0 THEN 1
                                  WHEN A.SYBL_MDTSE=0 THEN 1
                                  WHEN A.SYBL_MDTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                  ELSE LEAST(GREATEST(1 - A.SYBL_MDTSE / A.ZY_MDTSE,0),1)
                             END AS MYLAJ
              FROM TL_TSSH.CKTS_LC_SHXX A
              LEFT JOIN TL_TSSH.CKTS_SB_WZF_CKMX B ON B.LCSLID=A.LCSLID AND B.BYBLBZ='N'
             WHERE A.TSSWJG_DM=V_SWCODE
               AND A.LCTJJC = '72'
               AND A.QDSJ<LD_NEXTMONTH
               AND A.LCJSRQ>=LD_SYSDATE) T;

    --申报退税额、审核通过退税额
    SELECT ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1< LD_THISYEAR THEN T.TSE ELSE 0 END),0)/10000,6), --增值税申报
           ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1>=LD_THISYEAR THEN T.TSE ELSE 0 END),0)/10000,6), --申报
           ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END),0)/10000,6), --准予
           ROUND(NVL(SUM(CASE WHEN T.SZ='V' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END),0)/10000,6), --准予
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1< LD_THISYEAR THEN T.TSE ELSE 0 END),0)/10000,6), --消费税申报
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1>=LD_THISYEAR THEN T.TSE ELSE 0 END),0)/10000,6), --申报
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1< LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END),0)/10000,6), --准予
           ROUND(NVL(SUM(CASE WHEN T.SZ='C' AND T.CKRQ_1>=LD_THISYEAR AND T.SHZT=30 THEN T.TSE ELSE 0 END),0)/10000,6) --准予
      INTO LN_SB_ZZS_HIS, LN_SB_ZZS_CUR, LN_SH_ZZS_HIS, LN_SH_ZZS_CUR, LN_SB_XFS_HIS, LN_SB_XFS_CUR, LN_SH_XFS_HIS, LN_SH_XFS_CUR
      FROM (SELECT A.DJXH,B.SBXH,B.CKRQ_1,B.SZ,
                   CASE WHEN TRIM(A.LCSLID_FS) IS NOT NULL AND B.ZBBLBZ='Y' THEN 10 
                        WHEN TRIM(A.LCSLID_FS) IS NOT NULL AND B.BYTSBZ='Y' THEN 20 
                        WHEN TRIM(A.LCSLID_FS) IS NOT NULL THEN 30 
                        WHEN TRIM(A.LCSLID_FS) IS NULL AND A.LCSLID_SB<>A.LCSLID THEN 10 
                        ELSE 40 END AS SHZT, 
                   B.TSE * CASE WHEN B.SZ='V' THEN (CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1 
                                                         WHEN A.ZY_ZZSTSE=0 THEN 1
                                                         WHEN A.SYBL_ZZSTSE=0 THEN 1
                                                         WHEN A.SYBL_ZZSTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                                         ELSE LEAST(GREATEST(1 - A.SYBL_ZZSTSE / A.ZY_ZZSTSE,0),1)
                                                    END)
                           ELSE (CASE WHEN TRIM(A.LCSLID_FS) IS NULL THEN 1 
                                      WHEN A.ZY_XFSTSE=0 THEN 1
                                      WHEN A.SYBL_XFSTSE=0 THEN 1
                                      WHEN A.SYBL_XFSTSE>0 AND (B.ZBBLBZ='Y' OR B.BYTSBZ='Y') THEN 0
                                      ELSE LEAST(GREATEST(1 - A.SYBL_XFSTSE / A.ZY_XFSTSE,0),1)
                                 END)
                           END AS TSE
              FROM TL_TSSH.CKTS_LC_SHXX A
