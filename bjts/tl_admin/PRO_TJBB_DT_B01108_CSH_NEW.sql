                      AND T.TYPE=2
                      AND T.FORMULA<>'(14)=(12)*100/(13)'
                    ORDER BY T.YXJ)
    LOOP
      BEGIN
        LC_SQL := 'INSERT INTO TJBB_DT_B01108 (SSNY, BBLC, SWJGDM, RDHS, SBHS,
                          SB_CKE_XJ,  SB_CKE_HIS,  SB_CKE_CUR,
                          SB_TMSE_XJ, SB_TMSE_HIS, SB_TMSE_CUR,
